# 一键全验 - PowerShell 版本（17 项门禁）
# 决策锚：260826-2230 工程-DSH § 一键全验

$ErrorActionPreference = "Continue"
Set-Location (Split-Path -Parent $PSCommandPath)

$门禁目录 = "道果树/质量门禁 - 域/门禁 - 府"

Write-Host "╔══════════════════════════════════════════════╗"
Write-Host "║  洪荒 · 世界 v3 · 一键全验 17 项              ║"
Write-Host "╚══════════════════════════════════════════════╝"
Write-Host ""

$通过 = 0
$失败 = 0
$跳过 = 0

$门禁 = @(
    @{ 编号 = 1;  名称 = "格式";          脚本 = "验证-格式.ps1" },
    @{ 编号 = 2;  名称 = "静态分析";      脚本 = "验证-警告.ps1" },
    @{ 编号 = 3;  名称 = "单元测试";      脚本 = "验证-测试.ps1" },
    @{ 编号 = 4;  名称 = "编译";          脚本 = "验证-编译.ps1" },
    @{ 编号 = 5;  名称 = "文档";          脚本 = "验证-文档.ps1" },
    @{ 编号 = 6;  名称 = "安全审计";      脚本 = "验证-审计.ps1" },
    @{ 编号 = 7;  名称 = "依赖审查";      脚本 = "验证-依赖.ps1" },
    @{ 编号 = 8;  名称 = "无 src/ 平铺"; 脚本 = "验证-无src目录.ps1" },
    @{ 编号 = 9;  名称 = "无空目录";      脚本 = "验证-无空目录.ps1" },
    @{ 编号 = 10; 名称 = "无临时目录残留"; 脚本 = "验证-临时目录.ps1" },
    @{ 编号 = 11; 名称 = "决策契约";          脚本 = "验证-决策契约.ps1" },
    @{ 编号 = 12; 名称 = "命名唯一性";          脚本 = "验证-命名唯一性.ps1" },
    @{ 编号 = 13; 名称 = "防退化 ≥2 殿";        脚本 = "验证-防退化.ps1" },
    @{ 编号 = 14; 名称 = "格位稀缺 36 上限";       脚本 = "验证-格位稀缺.ps1" },
    @{ 编号 = 15; 名称 = "文档收割门防污染";       脚本 = "验证-文档收割门.ps1" },
    @{ 编号 = 16; 名称 = "治理审计";          脚本 = "验证-治理审计.ps1" },
    @{ 编号 = 17; 名称 = "标识符中文";          脚本 = "验证-标识符中文.ps1" }
)

foreach ($项 in $门禁) {
    Write-Host "─── [$($项.编号)] $($项.名称) ───"
    $脚本路径 = Join-Path $门禁目录 $项.脚本
    if (-not (Test-Path $脚本路径)) {
        Write-Host "  [SKIP] 脚本不存在：$脚本路径" -ForegroundColor Yellow
        $跳过++
        continue
    }
    & "C:\Windows\System32\WindowsPowerShell\v1.0\powershell.exe" -NoProfile -ExecutionPolicy Bypass -File $脚本路径
    $退出码 = $LASTEXITCODE
    if ($退出码 -eq 0) {
        $通过++
    } else {
        Write-Host "  [FAIL] $($项.名称) 未通过" -ForegroundColor Red
        $失败++
    }
    Write-Host ""
}
Write-Host "╔══════════════════════════════════════════════╗"
Write-Host "║  汇总：通过 $通过 / 失败 $失败 / 跳过 $跳过                ║"
Write-Host "╚══════════════════════════════════════════════╝"

if ($失败 -gt 0) { exit 1 }
exit 0
