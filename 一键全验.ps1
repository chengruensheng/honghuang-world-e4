$ErrorActionPreference = "Continue"
Set-Location (Split-Path -Parent $PSCommandPath)

$门禁目录 = "道果树/质量门禁-域/门禁-府"

Write-Host "╔══════════════════════════════════════════════╗"
Write-Host "║  洪荒 · 世界 v3 · 阶段 1 · 一键全验 10 项      ║"
Write-Host "╚══════════════════════════════════════════════╝"
Write-Host ""

$通过 = 0
$失败 = 0
$跳过 = 0

$门禁 = @(
    @{ 编号 = 1;  名称 = "格式";          脚本 = "验证-格式.ps1" },
    @{ 编号 = 2;  名称 = "静态分析";      脚本 = "验证-警告.ps1" },
    @{ 编号 = 3;  名称 = "单元测试";      脚本 = "验证-测试.ps1" },
    @{ 编号 = 4;  名称 = "编译";          脚本 = "验证-编译.ps1" },
    @{ 编号 = 5;  名称 = "文档";          脚本 = "验证-文档.ps1" },
    @{ 编号 = 6;  名称 = "安全审计";      脚本 = "验证-审计.ps1" },
    @{ 编号 = 7;  名称 = "依赖审查";      脚本 = "验证-依赖.ps1" },
    @{ 编号 = 8;  名称 = "无 src/ 平铺"; 脚本 = "验证-无src目录.ps1" },
    @{ 编号 = 9;  名称 = "无空目录";      脚本 = "验证-无空目录.ps1" },
    @{ 编号 = 10; 名称 = "无临时目录残留"; 脚本 = "验证-临时目录.ps1" }
)

foreach ($项 in $门禁) {
    Write-Host "─── [$($项.编号)] $($项.名称) ───"
    $脚本路径 = Join-Path $门禁目录 $项.脚本
    if (-not (Test-Path $脚本路径)) {
        Write-Host "  [SKIP] 脚本不存在：$脚本路径" -ForegroundColor Yellow
        $跳过++
        continue
    }
    & pwsh $脚本路径
    if ($LASTEXITCODE -eq 0) {
        $通过++
    } else {
        Write-Host "  [FAIL] $($项.名称) 未通过" -ForegroundColor Red
        $失败++
    }
    Write-Host ""
}

Write-Host "╔══════════════════════════════════════════════╗"
Write-Host "║  汇总：通过 $通过 / 失败 $失败 / 跳过 $跳过                ║"
Write-Host "╚══════════════════════════════════════════════╝"

if ($失败 -gt 0) { exit 1 }
exit 0
