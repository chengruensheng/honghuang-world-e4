// 就绪_核心.rs - 传承殿·就绪-检测-殿·就绪-方法-阁·就绪-园
// 职责：就绪态语义集（标签 / 判定 / 报告 三件套）
// 自举锚：常量即语义之源，函数即行为之流，报告即呈现之果
// 四要素：decided_by=大罗金仙级（执行）；falsifiable=cargo build 退出码 0 且
//        就绪状态描述=="工作空间就绪" 且 就绪报告() 包含"就绪=真"；
//        implements=传承殿自举哲学；复现=cargo build -p 就绪_核心 + cargo test -p 就绪_核心

/// 工作空间就绪态语义标签常量（自举新增）
pub const 就绪状态描述: &str = "工作空间就绪";

/// 判定工作空间是否就绪（既有函数，原样保留）
pub fn 就绪() -> bool {
    true
}

/// 生成就绪态可读报告（既有函数，原样保留——版本 + 就绪双字段）
pub fn 就绪报告() -> String {
    let 状态 = if 就绪() { "真" } else { "假" };
    format!("版本=v0.2.0\n就绪={}", 状态)
}

#[cfg(test)]
mod 测试 {
    use super::*;

    /// 新增测试：断言常量等于「工作空间就绪」（任务字面要求）
    #[test]
    fn 就绪状态描述常量等于工作空间就绪() {
        assert_eq!(就绪状态描述, "工作空间就绪");
    }

    /// 回归保护：就绪报告包含版本=v0.2.0（既有契约，严禁漂移）
    #[test]
    fn 就绪报告包含版本() {
        assert!(
            就绪报告().contains("版本=v0.2.0"),
            "就绪报告应含版本=v0.2.0：{}",
            就绪报告()
        );
    }

    /// 回归保护：就绪报告包含就绪=真旗
    #[test]
    fn 就绪报告包含就绪真旗() {
        let 报告 = 就绪报告();
        assert!(
            报告.contains("就绪=真"),
            "就绪报告未包含就绪=真，实际为：{}",
            报告
        );
    }

    /// 回归保护：就绪函数返回真
    #[test]
    fn 就绪函数返回真() {
        assert!(就绪());
    }
}
