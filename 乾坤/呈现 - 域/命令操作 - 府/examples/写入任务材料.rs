//! 写入任务材料 - 把「任务已完成」的产出/验证材料写入格位，供真实流水线准圣验收
//!
//! 决策锚：260829 真实通过端到端验证（Round 19，自举闭环：执行层产出材料 → 治理层验收通过）
//! 用法：cargo run -p mingling_caozuo_fu --example 写入任务材料 -- <任务标识> <产出材料> <验证材料>
//! 验证：写入后真实流水线召回材料，准圣验收看到材料齐全 → 道祖通过 → 交付回填

use jiyi_chengzai_fu::{总纲, 本质, 阶段};
use mingling_caozuo_fu::{写入_按格位, 退出码, 默认记忆库路径};

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.len() < 3 {
        eprintln!("用法：写入任务材料 <任务标识> <产出材料> <验证材料>");
        std::process::exit(退出码::材料错误);
    }
    let 任务标识 = args[0].as_str();
    let 产出 = args[1].as_str();
    let 验证 = args[2].as_str();
    // 执行×产出：真实产出（代码/设计/文档），供准圣验收「非框架空壳」判据
    写入_按格位(
        默认记忆库路径,
        总纲::执行,
        本质::产出,
        阶段::实施,
        产出,
        任务标识,
    )
    .expect("产出材料写入失败");
    // 执行×验证：真实验证结果（测试/断言），供准圣验收「可证伪」判据
    写入_按格位(
        默认记忆库路径,
        总纲::执行,
        本质::验证,
        阶段::实施,
        验证,
        任务标识,
    )
    .expect("验证材料写入失败");
    println!("已写入任务材料：{} => 产出/验证", 任务标识);
}
