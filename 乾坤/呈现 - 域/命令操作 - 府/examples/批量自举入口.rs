fn 任务单(
    标识: &str, 目标文件: &str, 需求: &str, 验收: &str, 可证伪: &str
) -> 自举任务单 {
    let mut 参数 = HashMap::new();
    参数.insert("标识".to_string(), 标识.to_string());
    参数.insert("目标文件".to_string(), 目标文件.to_string());
    参数.insert("需求描述".to_string(), 需求.to_string());
    参数.insert("验收命令".to_string(), 验收.to_string());
    参数.insert("可证伪命题".to_string(), 可证伪.to_string());
    参数.insert("decided_by".to_string(), "界主".to_string());
    自举任务单::从参数解析(&参数).expect("任务单解析失败")
}

