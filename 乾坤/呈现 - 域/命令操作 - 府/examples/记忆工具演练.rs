//! 记忆工具演练 - 八件套玉玺链端到端（写/读/按格位/确认玉玺/世界事实/读仓/查全部/永驻摘要 + 任务闭环）
//!
//! 决策锚：260827-AI助手自给自足（36 格位记忆机制）+ 260828 玉玺机制（确认格位记忆/登记世界事实）
//! 演练内容（8 件套全链）：
//!   1. 写任务记忆：向 程序/实施 格位写入（来源 LLM 权档，无玉玺）
//!   2. 读任务记忆：任务描述 → 相关格位记忆命中
//!   3. 写入_按格位：向 经历/归档 合法格位写入
//!   4. 确认格位记忆（盖玉玺）：来源人类+decided_by界主 → 链头切到确认版
//!   5. 登记世界事实：世界 范畴由代码写入（来源可信度 3 最高）
//!   6. 读格位仓库：精确深挖单一格位分区（同范畴不同阶段隔离）
//!   7. 查全部记忆：持久库全部记忆文本
//!   8. 工具永驻摘要：36 行心智模型摘要
//!   9. 任务记忆闭环：任务前读 + 任务后写 + 永驻摘要联动
//!
//! 用法：cargo run -p mingling_caozuo_fu --example 记忆工具演练
//! falsifiable：退出码 0 且输出含 8 个关键节

use jiyi_chengzai_fu::{范畴, 阶段};
use mingling_caozuo_fu::{
    任务记忆闭环, 写入_按格位, 写入任务记忆, 工具永驻摘要, 查全部记忆, 登记世界事实, 确认格位记忆,
    读任务记忆, 读格位仓库,
};

fn main() {
    let 库 = std::env::temp_dir()
        .join("记忆工具演练.sq3")
        .to_str()
        .unwrap()
        .to_string();
    let _ = std::fs::remove_file(&库);
    println!("=== 记忆工具八件套玉玺链演练 ===");
    println!("数据库：{}", 库);

    // 第 1 件：写任务记忆（程序/实施，来源 LLM 权档，无玉玺）
    let id1 = 写入任务记忆(&库, "实现记忆工具演练示例", "八件套玉玺链").expect("写入任务记忆失败");
    println!("[1/8] 写任务记忆 ✓  id={}（程序/实施）", id1.0);

    // 第 2 件：读任务记忆（任务描述命中相关格位记忆）
    let 读记忆 = 读任务记忆(&库, "实现记忆工具演练示例");
    assert!(
        读记忆.iter().any(|m| m.contains("实现记忆工具演练示例")),
        "读任务记忆应命中刚写入的演练条目"
    );
    println!("[2/8] 读任务记忆 ✓  命中 {} 条", 读记忆.len());

    // 第 3 件：写入_按格位（经历/归档 合法格位）
    let id3 = 写入_按格位(
        &库,
        范畴::经历,
        阶段::归档,
        "演练踩坑沉淀：分区检索隔离验证",
        "演练归档",
    )
    .expect("写入_按格位失败");
    println!("[3/8] 写入_按格位 ✓  id={}（经历/归档）", id3.0);

    // 第 4 件：确认格位记忆（盖玉玺）：人类确认 → 来源人类+decided_by界主，链头切确认版
    let id4 = 确认格位记忆(
        &库,
        范畴::程序,
        阶段::实施,
        "界主确认：记忆工具演练示例审核通过",
        "玉玺确认",
    )
    .expect("确认格位记忆失败");
    let 仓库 = 读格位仓库(&库, 范畴::程序, 阶段::实施);
    assert!(
        仓库[0].contains("界主确认"),
        "盖玉玺后链头应切到人类确认版本"
    );
    println!(
        "[4/8] 确认格位记忆 ✓  id={}（来源=人类 链头切确认版）",
        id4.0
    );

    // 第 5 件：登记世界事实（世界/验收，来源代码 可信度3 最高）
    let id5 = 登记世界事实(&库, 阶段::验收, "326 测试全绿", "326-13-13 门禁").expect("登记世界事实失败");
    println!("[5/8] 登记世界事实 ✓  id={}（来源=代码 可信度3）", id5.0);

    // 第 6 件：读格位仓库（分区隔离：程序/实施 不含 经历/归档）
    let 仓库6 = 读格位仓库(&库, 范畴::程序, 阶段::实施);
    assert!(
        仓库6.iter().any(|m| m.contains("界主确认")),
        "程序/实施 分区应含确认版条目"
    );
    assert!(
        !仓库6.iter().any(|m| m.contains("演练归档")),
        "分区隔离：程序/实施 不应含 经历/归档 条目"
    );
    println!(
        "[6/8] 读格位仓库 ✓  程序/实施 分区 {} 条（隔离正确）",
        仓库6.len()
    );

    // 第 7 件：查全部记忆（4 条手写：写任务/按格位/确认/世界事实）
    let 全部 = 查全部记忆(&库);
    assert!(全部.len() >= 4, "至少含 4 条本次写入的条目");
    println!("[7/8] 查全部记忆 ✓  共 {} 条", 全部.len());

    // 第 8 件：工具永驻摘要（36 行心智模型，4 个格位有内容）
    let 摘要 = 工具永驻摘要(&库);
    assert_eq!(摘要.len(), 36, "永驻摘要固定 36 行（6 范畴 × 6 阶段）");
    let 有内容 = 摘要
        .iter()
        .filter(|s| s.contains(']') && !s.ends_with("] "))
        .count();
    assert_eq!(有内容, 3, "3 个格位有内容：程序/实施（写+确认）、经历/归档、世界/验收（写 4 条落 3 格位）");
    println!("[8/8] 工具永驻摘要 ✓  36 行中 {} 行有内容（程序/实施 + 经历/归档 + 世界/验收）", 有内容);

    // 任务记忆闭环：任务前读（命中玉玺确认版）+ 任务后写 + 永驻摘要联动
    let (读闭环, 摘要闭环) = 任务记忆闭环(&库, "实现记忆工具演练示例", "演练闭环完成");
    assert!(
        读闭环.iter().any(|m| m.contains("界主确认")),
        "闭环读应命中盖玉玺后的确认内容"
    );
    assert_eq!(摘要闭环.len(), 36, "闭环后永驻摘要仍 36 行");
    println!(
        "[9] 任务记忆闭环 ✓  读 {} 条 / 摘要 {} 行",
        读闭环.len(),
        摘要闭环.len()
    );

    let _ = std::fs::remove_file(&库);
    println!("=== 八件套玉玺链演练全部通过，临时库已清理 ===");
}
