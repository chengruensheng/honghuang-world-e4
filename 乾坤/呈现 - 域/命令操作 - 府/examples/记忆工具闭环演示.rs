//! 记忆工具闭环演示 - 六工具端到端（写/读/查/摘/按格位/分区深挖）
//!
//! 决策锚：260827-AI助手自给自足（36 格位记忆机制）
//! 演示内容：
//!   1. 写入任务记忆：固定 程序/实施 格位，来源 LLM，权档
//!   2. 写入_按格位：向 经历/归档 合法格位写入
//!   3. 读任务记忆：任务描述 → 相关记忆文本列表（可命中 1 的条目）
//!   4. 查全部记忆：持久库全部记忆文本
//!   5. 读格位仓库：精确深挖 经历/归档 分区，体现同范畴不同阶段隔离
//!   6. 工具永驻摘要：36 行心智模型，有内容行计数
//!
//! 用法：cargo run -p mingling_caozuo_fu --example 记忆工具闭环演示

use jiyi_chengzai_fu::{范畴, 阶段};
use mingling_caozuo_fu::{
    写入_按格位, 写入任务记忆, 工具永驻摘要, 查全部记忆, 读任务记忆, 读格位仓库,
};

fn main() {
    let 库 = std::env::temp_dir()
        .join("记忆工具闭环演示.sq3")
        .to_str()
        .unwrap()
        .to_string();
    let _ = std::fs::remove_file(&库);
    println!("=== 记忆工具六件套闭环演示 ===");
    println!("数据库：{}", 库);

    // 1. 写（固定格位：程序/实施）
    let id1 = 写入任务记忆(&库, "实现记忆工具闭环演示", "六工具闭环").expect("写入任务记忆失败");
    println!("[1/6] 写入任务记忆 ✓  id={}（程序/实施）", id1.0);

    // 2. 按格位写（经历/归档）
    let id2 = 写入_按格位(
        &库,
        范畴::经历,
        阶段::归档,
        "踩坑与沉淀：分区检索后示例演示",
        "分区检索示例",
    )
    .expect("写入_按格位失败");
    println!("[2/6] 写入_按格位 ✓  id={}（经历/归档）", id2.0);

    // 3. 读任务记忆（任务描述命中 程序/实施 新条目；返回内容字段）
    let 读记忆 = 读任务记忆(&库, "实现记忆工具闭环演示");
    assert!(
        读记忆.iter().any(|m| m.contains("实现记忆工具闭环演示")),
        "读任务记忆应命中刚写入的工具演示条目"
    );
    println!("[3/6] 读任务记忆 ✓  命中 {} 条", 读记忆.len());
    for 条 in &读记忆 {
        println!("       {}", 条);
    }

    // 4. 查全部记忆
    let 全部 = 查全部记忆(&库);
    println!("[4/6] 查全部记忆 ✓  共 {} 条", 全部.len());
    for 条 in &全部 {
        println!("       {}", 条);
    }

    // 5. 分区深挖（经历/归档）：只含第 2 步条目，不含 程序/实施
    let 仓库 = 读格位仓库(&库, 范畴::经历, 阶段::归档);
    assert_eq!(仓库.len(), 1, "经历/归档 分区应只含 1 条");
    assert!(
        !仓库[0].contains("六工具闭环"),
        "分区隔离：不应混入程序/实施 条目"
    );
    println!(
        "[5/6] 读格位仓库 ✓  经历/归档 分区 {} 条（隔离正确）",
        仓库.len()
    );

    // 6. 永驻摘要 36 行
    let 摘要 = 工具永驻摘要(&库);
    let 有内容 = 摘要
        .iter()
        .filter(|s| s.contains(']') && !s.ends_with("] "))
        .count();
    println!("[6/6] 工具永驻摘要 ✓  36 行中 {} 行有内容", 有内容);
    for 行 in 摘要
        .iter()
        .filter(|s| s.contains(']') && !s.ends_with("] "))
    {
        println!("       {}", 行);
    }

    let _ = std::fs::remove_file(&库);
    println!("=== 六件套全部通过，演示库已清理 ===");
}
