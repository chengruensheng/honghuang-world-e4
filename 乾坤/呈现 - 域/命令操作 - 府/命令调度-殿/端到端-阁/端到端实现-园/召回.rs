//! 四时机召回上下文：任务开始关键词召回 + 验收对比 + 玉玺裁决 + 遇阻下探
//!
//! 契约 §四/五：块=默认最新+按需召回历史（4 时机四维坐标定位）；召回块进临时上下文用完即弃。
//! 依赖 jiyi 格位中枢 + 读/查记忆工具 + 反向断言（模型可见⟺已记录）。

use jiyi_chengzai_fu::{总纲, 本质, 格位, 格位中枢, SQLite存储};

/// 四时机召回上下文（契约 §五）：按角色差异化注入，召回块进临时上下文用完即弃
pub(crate) struct 召回上下文 {
    /// 时机① 任务开始关键词召回（道祖及全角色基础）
    pub(crate) 任务开始: String,
    /// 时机③ 验收对比召回（准圣：历史验收块 执行×验证）
    pub(crate) 验收对比: String,
    /// 时机④ 玉玺裁决召回（道祖终裁：目标×当前/规则×规范/经历×决策 玉玺块）
    pub(crate) 玉玺裁决: String,
}

/// 反向可审计断言：凡注入 LLM 的记忆必可由持久库重建（可见⟺已记录）
///
/// 读任务记忆 返回 "[总纲] 内容"，查全部记忆 返回 "[总纲·本质] 内容"；
/// 按 "内容" 部分做子串匹配（不同总纲/本质的同内容条目视为可重建）。
pub(crate) fn 断言可重建(注入: &[String], 全部: &[String]) -> Result<(), String> {
    for 条 in 注入 {
        let 内容 = 条.split_once("] ").map(|(_, 内)| 内).unwrap_or(条.as_str());
        if !全部.iter().any(|全| 全.contains(内容)) {
            return Err(format!("注入记忆不可审计（持久库不可重建）：{}", 条));
        }
    }
    Ok(())
}

/// 组装记忆上下文：读任务相关记忆 + 反向断言（模型可见⟺已记录）
/// → 返回记忆条目列表（调用方拼接注入消息列表）。
/// falsifiable：临时库写已知条目后，返回含该条目文本；反向断言失败路径（库中不存在的内容）返回 Err。
pub(crate) fn 组装记忆上下文_按路径(
    记忆库路径: &str,
    任务标识: &str,
) -> Result<Vec<String>, String> {
    let 记忆 = crate::读任务记忆(记忆库路径, 任务标识);
    let 全部 = crate::查全部记忆(记忆库路径);
    断言可重建(&记忆, &全部)?;
    Ok(记忆)
}

/// 按路径组装召回上下文（契约 §五）：①任务开始关键词召回 ③验收对比 ④玉玺裁决
/// 时机② 遇阻下探由「打回重试循环」触发；复用时机①的反向断言
pub(crate) fn 组装召回上下文_按路径(
    记忆库路径: &str,
    任务标识: &str,
) -> Result<召回上下文, String> {
    let 任务开始记忆 = 组装记忆上下文_按路径(记忆库路径, 任务标识)?;
    let 验收对比 = 召回_验收对比(记忆库路径, 任务标识).join("\n");
    let 玉玺裁决 = 召回_玉玺裁决(记忆库路径).join("\n");
    Ok(召回上下文 {
        任务开始: 任务开始记忆.join("\n"),
        验收对比,
        玉玺裁决,
    })
}

/// 时机③ 验收对比召回：准圣读当前任务的验收块（执行×验证 格位分区，按绑定任务过滤，ID 降序）
/// 标注「最新基线」（最近一次验收）vs「历史」（更早验收），供准圣做回归/新增/修复差异对比
/// 按绑定任务隔离：跨任务验收块不混入（否则最新基线错位到旧任务验收，终裁验证旧产出）
///
/// 附加规则召回（界主拍板：规则是格位数据，动态生效）：
/// 追加「规则×门禁 + 规则×红线」最新块（全局规则不绑定任务），准圣据此按六维门禁验收，而非临场发挥。
pub(crate) fn 召回_验收对比(记忆库路径: &str, 任务标识: &str) -> Vec<String> {
    let 存储 = SQLite存储::文件新建(记忆库路径).expect("记忆库打开失败");
    let 中枢 = 格位中枢::新建(存储);
    let mut 块: Vec<String> = 中枢
        .读取_格位_分区(格位 {
            总纲: 总纲::执行,
            本质: 本质::验证,
        })
        .into_iter()
        .filter(|e| {
            e.块元数据
                .as_ref()
                .map(|m| m.绑定任务 == 任务标识)
                .unwrap_or(false)
        })
        .enumerate()
        .map(|(序, e)| {
            let 标注 = if 序 == 0 { "最新基线" } else { "历史" };
            format!("[验收·{}·{}] {}", e.本质.名称(), 标注, e.内容)
        })
        .collect();
    // 规则格位追加（规则×门禁/红线，玉玺优先，全局生效不绑定任务）
    for (规则总纲, 规则本质) in [(总纲::规则, 本质::门禁), (总纲::规则, 本质::红线)]
    {
        if let Some(e) = 中枢.读取_格位_玉玺优先(格位 {
            总纲: 规则总纲,
            本质: 规则本质,
        }) {
            块.push(format!("[规则·{}] {}", e.本质.名称(), e.内容));
        }
    }
    块
}

/// 时机④ 玉玺裁决召回：道祖终裁读玉玺块（目标×当前/规则×规范/经历×决策 玉玺优先）
pub(crate) fn 召回_玉玺裁决(记忆库路径: &str) -> Vec<String> {
    let 存储 = SQLite存储::文件新建(记忆库路径).expect("记忆库打开失败");
    let 中枢 = 格位中枢::新建(存储);
    let 玉玺格位 = [
        (总纲::目标, 本质::当前),
        (总纲::规则, 本质::规范),
        (总纲::经历, 本质::决策),
    ];
    let mut 块 = Vec::new();
    for (总纲, 本质) in 玉玺格位 {
        if let Some(e) = 中枢.读取_格位_玉玺优先(格位 { 总纲, 本质 }) {
            块.push(format!(
                "[玉玺·{}·{}] {}",
                e.总纲.名称(),
                e.本质.名称(),
                e.内容
            ));
        }
    }
    块
}

/// 时机② 遇阻下探召回：打回时读历史教训（经历×教训）+ 步骤（执行×步骤）块，供重投补充
pub(crate) fn 召回_遇阻下探(记忆库路径: &str) -> Vec<String> {
    let 存储 = SQLite存储::文件新建(记忆库路径).expect("记忆库打开失败");
    let 中枢 = 格位中枢::新建(存储);
    let 下探格位 = [(总纲::经历, 本质::教训), (总纲::执行, 本质::步骤)];
    let mut 块 = Vec::new();
    for (总纲, 本质) in 下探格位 {
        for e in 中枢.读取_格位_分区(格位 { 总纲, 本质 }) {
            块.push(format!(
                "[下探·{}·{}] {}",
                e.总纲.名称(),
                e.本质.名称(),
                e.内容
            ));
        }
    }
    块
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 断言可重建_正向通过() {
        let 注入 = vec!["[目标] 执行 100 项任务".to_string()];
        let 全部 = vec!["[目标·当前] 执行 100 项任务".to_string()];
        assert!(断言可重建(&注入, &全部).is_ok(), "同内容可重建");
    }

    #[test]
    fn 断言可重建_反向失败() {
        let 注入 = vec!["[目标] 不存在的内容".to_string()];
        let 全部 = vec!["[目标·当前] 其他内容".to_string()];
        assert!(断言可重建(&注入, &全部).is_err(), "不可重建应失败");
    }

    #[test]
    fn 召回_验收对比_含规则门禁红线() {
        let 库 = format!("规则召回_{}.sq3", std::process::id());
        let _ = std::fs::remove_file(&库);
        // 写规则格位（规则×门禁 + 规则×红线），来源 LLM 无玉玺
        crate::写入_按格位(
            &库,
            总纲::规则,
            本质::门禁,
            jiyi_chengzai_fu::阶段::实施,
            "准圣六维门禁内容",
            "六维",
        )
        .unwrap();
        crate::写入_按格位(
            &库,
            总纲::规则,
            本质::红线,
            jiyi_chengzai_fu::阶段::实施,
            "道祖三层红线内容",
            "三层",
        )
        .unwrap();
        // 召回验收对比：应含规则门禁 + 规则红线（全局规则不绑定任务）
        let 块 = 召回_验收对比(&库, "任意任务");
        assert!(
            块.iter().any(|s| s.contains("[规则·门禁]")),
            "应召回规则×门禁：{:?}",
            块
        );
        assert!(
            块.iter().any(|s| s.contains("[规则·红线]")),
            "应召回规则×红线：{:?}",
            块
        );
        assert!(
            块.iter().any(|s| s.contains("准圣六维门禁内容")),
            "规则门禁内容应完整注入：{:?}",
            块
        );
        let _ = std::fs::remove_file(&库);
    }
}
