/// 三档投影读取：时间维度（档位）在读取侧生效——首因 / 近因 / 会话
///
/// 对齐 传承殿 记忆模型 三维正交（范畴 × 档位 × 来源）：
/// - 首因：每个格位最早的 经档 条目（经典不变，ID 最小）
/// - 近因：每个格位最新的 权档 条目（因时制宜，ID 最大）
/// - 会话：全部 行档 条目（当下行动，按 ID 降序）
///
/// E 盘自主设计（不照搬 D 盘）：档位维度首次落到读取侧。
pub fn 读取_三档投影(记忆库路径: &str) -> (Vec<String>, Vec<String>, Vec<String>) {
    let 存储 = SQLite存储::文件新建(记忆库路径).expect("记忆库打开失败");
    let 全部 = 存储.查_全部();
    // 首因：每格位最早的经档（取 id.0 最小）
    let mut 首因: Vec<&记忆条目> = Vec::new();
    for 条目 in &全部 {
        if matches!(条目.档位, 档位::经档) {
            if let Some(已有) = 首因
                .iter_mut()
                .find(|e| e.范畴 == 条目.范畴 && e.阶段 == 条目.阶段)
            {
                if 条目.id.0 < 已有.id.0 {
                    *已有 = 条目;
                }
            } else {
                首因.push(条目);
            }
        }
    }
    // 近因：每格位最新的权档（取 id.0 最大）
    let mut 近因: Vec<&记忆条目> = Vec::new();
    for 条目 in &全部 {
        if matches!(条目.档位, 档位::权档) {
            if let Some(已有) = 近因
                .iter_mut()
                .find(|e| e.范畴 == 条目.范畴 && e.阶段 == 条目.阶段)
            {
                if 条目.id.0 > 已有.id.0 {
                    *已有 = 条目;
                }
            } else {
                近因.push(条目);
            }
        }
    }
    // 会话：行档按 ID 降序
    let mut 会话: Vec<&记忆条目> = 全部
        .iter()
        .filter(|e| matches!(e.档位, 档位::行档))
        .collect();
    会话.sort_by_key(|e| std::cmp::Reverse(e.id.0));
    let 格位键 = |e: &&记忆条目| format!("{}·{}", e.范畴.名称(), e.阶段.名称());
    let 格式化 = |v: &mut Vec<&记忆条目>| {
        v.sort_by_key(|e| 格位键(e));
        v.iter()
            .map(|条目| format!("[{}] {}", 格位键(条目), 条目.内容))
            .collect()
    };
    let 首因文本 = 格式化(&mut 首因);
    let 近因文本 = 格式化(&mut 近因);
    let 会话文本 = 格式化(&mut 会话);
    (首因文本, 近因文本, 会话文本)
}

/// 记会话：工作记忆完整保留（执行轨迹逐行写入 经历/实施，来源 LLM，权档，无玉玺）
///
/// 无人开发方向（2026-08-28）：AI 执行过程完整可回溯，不依赖人类记录。
/// 每行轨迹格式：[序号] 行内容（任务：任务标识），任务标识作锚点供 查会话 检索。
pub fn 记会话(记忆库路径: &str, 任务标识: &str, 轨迹: &[String]) -> Vec<记忆ID> {
    let 摘要 = format!("会话记录·{}", 任务标识);
    let mut ids = Vec::new();
    for (i, 行) in 轨迹.iter().enumerate() {
        let 内容 = format!("[{}] {}（任务：{}）", i + 1, 行, 任务标识);
        if let Ok(id) = 写入_按格位(记忆库路径, 范畴::经历, 阶段::实施, &内容, &摘要)
        {
            ids.push(id);
        }
    }
    ids
}

/// 查会话：按任务标识读回工作记忆（经历/实施 中含任务标识锚点的轨迹行）
pub fn 查会话(记忆库路径: &str, 任务标识: &str) -> Vec<String> {
    读格位仓库(记忆库路径, 范畴::经历, 阶段::实施)
        .into_iter()
        .filter(|s| s.contains(&format!("（任务：{}）", 任务标识)))
        .collect()
}

/// 终点归档：任务结束收尾——读会话轨迹 → 地道精炼（教训/机制/波及）→ 返回精炼条数
pub fn 终点归档(记忆库路径: &str, 任务标识: &str, 执行结果: &str) -> usize {
    let 会话 = 查会话(记忆库路径, 任务标识);
    let mut 结果 = 执行结果.to_string();
    if !会话.is_empty() {
        结果.push_str(&format!("（会话轨迹 {} 行）", 会话.len()));
    }
    地道精炼(记忆库路径, 任务标识, &结果).len()
}

/// 地道精炼：执行结果自动提炼 教训/机制/波及 写入 经历 格位（来源 LLM，权档，无玉玺）
///
/// 无人开发方向（2026-08-28）：AI 执行收尾时自动沉淀可复用经验，不依赖人类。
/// 信号词规则（E 盘自主设计，不照搬 D 盘）：
/// - 教训：含 失败/踩坑/修/缺陷/问题 → 经历/归档（可复用教训）
/// - 机制：含 实现/落地/接入/新增 → 经历/实施（关键机制）
/// - 波及：含 测试/项/数 → 经历/验收（规模事实）
pub fn 地道精炼(
    记忆库路径: &str, 任务标识: &str, 执行结果: &str
) -> Vec<记忆ID> {
    let 摘要 = format!("地道精炼·{}", 任务标识);
    let 首行 = 执行结果.split(['\n', '，', ',']).next().unwrap_or(执行结果);
    let 提炼 = |前缀: &str| {
        let 截断 = if 首行.chars().count() > 40 {
            let mut s: String = 首行.chars().take(40).collect();
            s.push('…');
            s
        } else {
            首行.to_string()
        };
        format!("{}：{}（来自 [{}]）", 前缀, 截断, 任务标识)
    };
    let mut ids = Vec::new();
    if 执行结果.contains("失败")
        || 执行结果.contains("踩坑")
        || 执行结果.contains("修")
        || 执行结果.contains("缺陷")
        || 执行结果.contains("问题")
    {
        if let Ok(id) = 写入_按格位(记忆库路径, 范畴::经历, 阶段::归档, &提炼("教训"), &摘要)
        {
            ids.push(id);
        }
    }
    if 执行结果.contains("实现")
        || 执行结果.contains("落地")
        || 执行结果.contains("接入")
        || 执行结果.contains("新增")
    {
        if let Ok(id) = 写入_按格位(记忆库路径, 范畴::经历, 阶段::实施, &提炼("机制"), &摘要)
        {
            ids.push(id);
        }
    }
    if 执行结果.contains("测试") || 执行结果.contains("项") || 执行结果.contains("数")
    {
        if let Ok(id) = 写入_按格位(记忆库路径, 范畴::经历, 阶段::验收, &提炼("波及"), &摘要)
        {
            ids.push(id);
        }
    }
    ids
}

/// 播种格位36：36 格位（6 范畴 × 6 阶段）模拟内容自主落地（来源 LLM，无玉玺，可执行）
///
/// 无人开发方向（2026-08-28 界主校准）：不依赖人类确认——AI 自主生成内容
/// （玉玺语义：LLM 生成无玉玺、可执行、权威性低；界主日后可 确认格位记忆 盖玉玺）。
/// 空库先触发种子（5 条权威）；已有条目的格位跳过（幂等）；返回本次补齐数。
pub fn 播种格位36(记忆库路径: &str) -> usize {
    let 范畴集 = [
        范畴::目标,
        范畴::规则,
        范畴::自我,
        范畴::程序,
        范畴::世界,
        范畴::经历,
    ];
    let 阶段集 = [
        阶段::提案,
        阶段::审阅,
        阶段::拍板,
        阶段::实施,
        阶段::验收,
        阶段::归档,
    ];
    // 空库触发种子（权威格位）
    crate::记忆读取_殿::读取方法_阁::读取实现_园::读取任务相关记忆_持久(
        记忆库路径,
        "播种格位36",
    );
    let 存储 = SQLite存储::文件新建(记忆库路径).expect("记忆库打开失败");
    let 既有 = 存储.查_全部();
    let mut 补数 = 0;
    for 范畴 in 范畴集 {
        for 阶段 in 阶段集 {
            // 只播本质×阶段合法格位（合法 23：目标3/规则6/自我2/程序6/世界2/经历4）
            if !本质阶段合法性(范畴, 阶段) {
                continue;
            }
            let 已有 = 既有.iter().any(|e| e.范畴 == 范畴 && e.阶段 == 阶段);
            if !已有 {
                let 内容 = format!(
                    "{}·{} 模拟内容（AI 生成，无玉玺可执行；界主确认后盖玉玺）",
                    范畴.名称(),
                    阶段.名称()
                );
                写入_按格位(记忆库路径, 范畴, 阶段, &内容, "播种格位36").expect("播种写入失败");
                补数 += 1;
            }
        }
    }
    补数
}

