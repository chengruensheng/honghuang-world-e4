/// 格位仓库深挖：精确检索单一格位（范畴×阶段）内全部记忆文本（ID 降序，最近优先）
pub fn 读格位仓库(记忆库路径: &str, 范畴: 范畴, 阶段: 阶段) -> Vec<String> {
    let 存储 = SQLite存储::文件新建(记忆库路径).expect("记忆库打开失败");
    let 中枢 = 格位中枢::新建(存储);
    中枢
        .读取_格位_分区(格位 { 范畴, 阶段 })
        .iter()
        .map(|条目| format!("[{}·{}] {}", 条目.范畴.名称(), 条目.阶段.名称(), 条目.内容))
        .collect()
}

/// 读记忆工具：任务描述 → 相关记忆文本列表（持久库）
pub fn 读任务记忆(记忆库路径: &str, 任务描述: &str) -> Vec<String> {
    crate::记忆读取_殿::读取方法_阁::读取实现_园::读取任务相关记忆_持久(
        记忆库路径,
        任务描述,
    )
}

/// 查记忆工具：持久库全部记忆文本（[范畴·阶段] 内容）
pub fn 查全部记忆(记忆库路径: &str) -> Vec<String> {
    let 存储 = SQLite存储::文件新建(记忆库路径).expect("记忆库打开失败");
    存储
        .查_全部()
        .iter()
        .map(|条目| format!("[{}·{}] {}", 条目.范畴.名称(), 条目.阶段.名称(), 条目.内容))
        .collect()
}

/// 永驻摘要工具：持久库 36 行心智模型摘要
pub fn 工具永驻摘要(记忆库路径: &str) -> Vec<String> {
    let 存储 = SQLite存储::文件新建(记忆库路径).expect("记忆库打开失败");
    let 中枢 = 格位中枢::新建(存储);
    中枢.永驻摘要()
}

/// 任务记忆闭环：任务前读相关记忆 → 任务后写程序/实施记忆 → 永驻摘要
///
/// 返回 (任务前读取的相关记忆, 写入后的 36 行永驻摘要)
pub fn 任务记忆闭环(
    记忆库路径: &str,
    任务标识: &str,
    执行结果: &str,
) -> (Vec<String>, Vec<String>) {
    let 读 = 读任务记忆(记忆库路径, 任务标识);
    写入任务记忆(记忆库路径, 执行结果, 任务标识).expect("任务记忆写入失败");
    let 摘 = 工具永驻摘要(记忆库路径);
    (读, 摘)
}

