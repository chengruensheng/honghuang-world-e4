/// 任务记忆闭环：任务前读相关记忆 → 任务后写程序/实施记忆 → 永驻摘要
///
/// 返回 (任务前读取的相关记忆, 写入后的 36 行永驻摘要)
pub fn 任务记忆闭环(
    记忆库路径: &str,
    任务标识: &str,
    执行结果: &str,
) -> (Vec<String>, Vec<String>) {
    let 读 = 读任务记忆(记忆库路径, 任务标识);
    写入任务记忆(记忆库路径, 执行结果, 任务标识).expect("任务记忆写入失败");
    let 摘 = 工具永驻摘要(记忆库路径);
    (读, 摘)
}

