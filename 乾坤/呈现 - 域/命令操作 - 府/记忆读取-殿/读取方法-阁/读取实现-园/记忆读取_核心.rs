#[cfg(test)]
#[allow(non_snake_case)]
mod 测试 {
    use super::*;

    #[test]
    fn 任务命中执行记忆() {
        let 记忆 = 读取任务相关记忆("实现 Cargo 测试");
        assert!(记忆.iter().any(|m| m.contains("36 格位闭环 API")));
        assert!(记忆.iter().any(|m| m.contains("执行")));
    }

    #[test]
    fn 任务命中经历记忆() {
        let 记忆 = 读取任务相关记忆("回顾过去踩坑教训");
        assert!(记忆.iter().any(|m| m.contains("踩坑")));
        assert!(记忆.iter().any(|m| m.contains("经历")));
    }

    #[test]
    fn 无关键词返回全部兜底() {
        let 记忆 = 读取任务相关记忆("与记忆无关的未知词");
        assert_eq!(记忆.len(), 5);
    }

    #[test]
    fn 持久首次调用自动初始化种子() {
        let 路径 = std::env::temp_dir().join("记忆库_首次.db");
        let _ = std::fs::remove_file(&路径);
        let 记忆 = 读取任务相关记忆_持久(路径.to_str().unwrap(), "实现 Cargo 测试");
        assert!(记忆.iter().any(|m| m.contains("36 格位闭环 API")));
        let _ = std::fs::remove_file(&路径);
    }

    #[test]
    fn 持久二次调用不重复初始化() {
        let 路径 = std::env::temp_dir().join("记忆库_二次.db");
        let _ = std::fs::remove_file(&路径);
        let _ = 读取任务相关记忆_持久(路径.to_str().unwrap(), "目标");
        let 存储 = SQLite存储::文件新建(路径.to_str().unwrap()).unwrap();
        assert_eq!(存储.查_全部().len(), 5, "二次调用不应重复初始化种子");
        let _ = std::fs::remove_file(&路径);
    }

    #[test]
    fn 持久手动写入后跨进程恢复() {
        let 路径 = std::env::temp_dir().join("记忆库_跨进程.db");
        let _ = std::fs::remove_file(&路径);
        {
            let 存储 = SQLite存储::文件新建(路径.to_str().unwrap()).unwrap();
            let mut 中枢 = 格位中枢::新建(存储);
            写入种子记忆(&mut 中枢);
            中枢
                .写入_格位(
                    格位 {
                        总纲: 总纲::执行,
                        本质: 本质::工具,
                    },
                    阶段::实施,
                    "持久化新记忆",
                    "新摘要",
                    档位::权档,
                    来源::LLM,
                    "界主",
                    "术",
                )
                .unwrap();
        }
        let 记忆 = 读取任务相关记忆_持久(路径.to_str().unwrap(), "实现 Cargo 测试");
        assert!(记忆.iter().any(|m| m.contains("持久化新记忆")));
        let _ = std::fs::remove_file(&路径);
    }

    #[test]
    fn 种子来源与内容合规() {
        let 路径 = std::env::temp_dir().join("记忆库_种子合规.db");
        let _ = std::fs::remove_file(&路径);
        let _ = 读取任务相关记忆_持久(路径.to_str().unwrap(), "实现 Cargo 测试");
        let 存储 = SQLite存储::文件新建(路径.to_str().unwrap()).unwrap();
        let 全部 = 存储.查_全部();
        assert_eq!(全部.len(), 5);
        let 规则 = 全部
            .iter()
            .find(|e| e.总纲 == 总纲::规则 && e.本质 == 本质::门禁)
            .unwrap();
        assert_eq!(规则.来源, 来源::人类, "命名门禁为界主决策 → 来源 人类");
        let 执行 = 全部
            .iter()
            .find(|e| e.总纲 == 总纲::执行 && e.本质 == 本质::工具)
            .unwrap();
        assert_eq!(
            执行.来源,
            来源::代码,
            "36 格位闭环 API 为代码事实 → 来源 代码"
        );
        let 外在 = 全部
            .iter()
            .find(|e| e.总纲 == 总纲::外在 && e.本质 == 本质::数据)
            .unwrap();
        assert!(
            外在.内容.contains("316"),
            "外在×数据 内容应为当前测试数：{}",
            外在.内容
        );
        let _ = std::fs::remove_file(&路径);
    }
}
