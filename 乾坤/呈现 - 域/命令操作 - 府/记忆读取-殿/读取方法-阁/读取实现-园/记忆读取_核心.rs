//! 记忆读取-殿 · 读取实现-园 - 任务前自动读取相关格位
//!
//! 决策锚：260827-AI助手自给自足 Step4（传承殿/10-地基/25-AI助手自给自足-实施方案.md）
//! falsifiable：读取任务相关记忆("实现 Cargo 测试") 返回含执行记忆；
//!             读取任务相关记忆("回顾教训") 返回含经历记忆
//!
//! 机制：任务进来 → 读取任务相关记忆(任务描述) → 命中相关总纲记忆 → 注入 LLM 上下文

use jiyi_chengzai_fu::{
    总纲, 本质, 来源, 格位, 格位中枢, 档位, 记忆存储, 阶段, SQLite存储
};

/// 读取任务相关记忆：任务前自动读取相关格位，返回相关记忆文本列表（内存种子）
pub fn 读取任务相关记忆(任务描述: &str) -> Vec<String> {
    let 存储 = SQLite存储::内存新建().expect("SQLite 内存新建失败");
    let mut 中枢 = 格位中枢::新建(存储);
    写入种子记忆(&mut 中枢);
    格式化成文(&中枢, 任务描述)
}

/// 读取任务相关记忆（持久版）：文件 SQLite 记忆库
///
/// 空库（首次）→ 自动初始化种子并落盘；已有内容 → 直接用持久化记忆。
pub fn 读取任务相关记忆_持久(记忆库路径: &str, 任务描述: &str) -> Vec<String> {
    let 存储 = SQLite存储::文件新建(记忆库路径).expect("记忆库打开失败");
    let mut 中枢 = 格位中枢::新建(存储);
    if 中枢.存储().查_全部().is_empty() {
        写入种子记忆(&mut 中枢);
    }
    格式化成文(&中枢, 任务描述)
}

/// 相关记忆 → 文本列表（[总纲] 内容）
/// 任务隔离：执行总纲的步骤/验证/产出块按绑定任务隔离（否则跨任务旧产出被误当当前任务产出验证）；
/// 执行×命令/技术栈/工具 + 其余总纲（规则/经历/目标/外在/内部）为全局知识，跨任务共享不过滤。
fn 格式化成文(中枢: &格位中枢<SQLite存储>, 任务描述: &str) -> Vec<String> {
    中枢
        .读取_相关格位(任务描述)
        .iter()
        .filter(|条目| match 条目.总纲 {
            总纲::执行 => match 条目.本质 {
                本质::步骤 | 本质::验证 | 本质::产出 => 条目
                    .块元数据
                    .as_ref()
                    .map(|m| m.绑定任务 == 任务描述)
                    .unwrap_or(false),
                _ => true,
            },
            _ => true,
        })
        .map(|条目| format!("[{}] {}", 条目.总纲.名称(), 条目.内容))
        .collect()
}

/// 种子记忆（演示真实项目记忆；正式由持久化 36 格位库加载）
fn 写入种子记忆(中枢: &mut 格位中枢<SQLite存储>) {
    写入(
        中枢,
        总纲::目标,
        本质::未来,
        阶段::拍板,
        "25号 AI 自给自足目标",
        "36 格位闭环",
        档位::经档,
        来源::人类,
    );
    写入(
        中枢,
        总纲::规则,
        本质::门禁,
        阶段::实施,
        "命名门禁规则",
        "祖孙判据",
        档位::权档,
        来源::人类,
    );
    写入(
        中枢,
        总纲::执行,
        本质::工具,
        阶段::实施,
        "36 格位闭环 API",
        "格位中枢 读取_相关格位",
        档位::权档,
        来源::代码,
    );
    写入(
        中枢,
        总纲::外在,
        本质::数据,
        阶段::验收,
        "316 测试全绿",
        "13-13 门禁",
        档位::行档,
        来源::代码,
    );
    写入(
        中枢,
        总纲::经历,
        本质::归档,
        阶段::归档,
        "踩坑：中文标识符含缩写触发 clippy",
        "用纯中文命名",
        档位::行档,
        来源::代码,
    );
}

fn 写入(
    中枢: &mut 格位中枢<SQLite存储>,
    总纲: 总纲,
    本质: 本质,
    阶段: 阶段,
    内容: &str,
    摘要: &str,
    档位: 档位,
    来源: 来源,
) {
    中枢
        .写入_格位(
            格位 { 总纲, 本质 },
            阶段,
            内容,
            摘要,
            档位,
            来源,
            "界主",
            "术·DSH",
        )
        .expect("写入_格位 失败");
}

