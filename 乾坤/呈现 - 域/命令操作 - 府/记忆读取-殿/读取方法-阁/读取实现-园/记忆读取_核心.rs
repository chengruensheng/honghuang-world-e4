//! 记忆读取-殿 · 读取实现-园 - 任务前自动读取相关格位
//!
//! 决策锚：260827-AI助手自给自足 Step4（传承殿/10-地基/25-AI助手自给自足-实施方案.md）
//! falsifiable：读取任务相关记忆("实现 Cargo 测试") 返回含程序记忆；
//!             读取任务相关记忆("回顾教训") 返回含经历记忆
//!
//! 机制：任务进来 → 读取任务相关记忆(任务描述) → 命中相关范畴记忆 → 注入 LLM 上下文
//!
//! 两版读取：
//! - 读取任务相关记忆：内存种子（演示闭环，进程内有效）
//! - 读取任务相关记忆_持久：文件 SQLite 库（空库自动初始化种子落盘，跨进程可复用）

use jiyi_chengzai_fu::{
    来源, 格位, 格位中枢, 档位, 范畴, 记忆存储, 阶段, SQLite存储
};

/// 读取任务相关记忆：任务前自动读取相关格位，返回相关记忆文本列表（内存种子）
///
/// 演示专用：流水线只走持久版（读任务记忆 → 读取任务相关记忆_持久），本函数仅演示闭环用。
pub fn 读取任务相关记忆(任务描述: &str) -> Vec<String> {
    let 存储 = SQLite存储::内存新建().expect("SQLite 内存新建失败");
    let mut 中枢 = 格位中枢::新建(存储);
    写入种子记忆(&mut 中枢);
    格式化成文(&中枢, 任务描述)
}

/// 读取任务相关记忆（持久版）：文件 SQLite 记忆库
///
/// 空库（首次）→ 自动初始化种子并落盘；已有内容 → 直接用持久化记忆。
/// falsifiable：首次命中程序记忆；二次调用不再重复初始化（条目数不变）；手动写入后跨进程恢复命中
pub fn 读取任务相关记忆_持久(记忆库路径: &str, 任务描述: &str) -> Vec<String> {
    let 存储 = SQLite存储::文件新建(记忆库路径).expect("记忆库打开失败");
    let mut 中枢 = 格位中枢::新建(存储);
    if 中枢.存储().查_全部().is_empty() {
        写入种子记忆(&mut 中枢);
    }
    格式化成文(&中枢, 任务描述)
}

/// 相关记忆 → 文本列表（[范畴] 内容）
fn 格式化成文(中枢: &格位中枢<SQLite存储>, 任务描述: &str) -> Vec<String> {
    中枢
        .读取_相关格位(任务描述)
        .iter()
        .map(|条目| format!("[{}] {}", 条目.范畴.名称(), 条目.内容))
        .collect()
}

/// 种子记忆（演示真实项目记忆；正式由持久化 36 格位库加载）
fn 写入种子记忆(中枢: &mut 格位中枢<SQLite存储>) {
    写入(
        中枢,
        范畴::目标,
        阶段::拍板,
        "25号 AI 自给自足目标",
        "36 格位闭环",
        档位::经档,
        来源::人类,
    );
    写入(
        中枢,
        范畴::规则,
        阶段::实施,
        "命名门禁规则",
        "祖孙判据",
        档位::权档,
        来源::人类,
    );
    写入(
        中枢,
        范畴::程序,
        阶段::实施,
        "36 格位闭环 API",
        "格位中枢 读取_相关格位",
        档位::权档,
        来源::代码,
    );
    写入(
        中枢,
        范畴::世界,
        阶段::验收,
        "316 测试全绿",
        "13-13 门禁",
        档位::行档,
        来源::代码,
    );
    写入(
        中枢,
        范畴::经历,
        阶段::归档,
        "踩坑：中文标识符含缩写触发 clippy",
        "用纯中文命名",
        档位::行档,
        来源::代码,
    );
}

fn 写入(
    中枢: &mut 格位中枢<SQLite存储>,
    范畴: 范畴,
    阶段: 阶段,
    内容: &str,
    摘要: &str,
    档位: 档位,
    来源: 来源,
) {
    中枢
        .写入_格位(
            格位 { 范畴, 阶段 },
            内容,
            摘要,
            档位,
            来源,
            "界主",
            "术·DSH",
        )
        .expect("写入_格位 失败");
}

// ============================================================================
// 单元测试
