#[path = "接口-殿/模块.rs"]
pub mod 接口_殿;

// 重导出对外的公开函数
pub use 实现_殿::校验和_方法_阁::实现_逻辑_园::crc32;
pub use 实现_殿::校验和_方法_阁::实现_逻辑_园::字节转十六进制;

#[cfg(test)]
mod 测试 {
    use super::*;

    // 标准校验向量测试
    #[test]
    fn 标准校验向量() {
        // 著名的 CRC-32 标准测试向量：输入 "123456789"，输出 0xCBF43926
        assert_eq!(crc32(b"123456789"), 0xCBF43926);
    }

    // 空输入测试
    #[test]
    fn 空输入校验() {
        // 空字节序列的 CRC-32 值应为 0
        assert_eq!(crc32(b""), 0);
    }

    // 十六进制往返测试
    #[test]
    fn 十六进制往返() {
        // 字节序列转十六进制应为小写无前缀形式
        assert_eq!(字节转十六进制(&[0xDE, 0xAD, 0xBE, 0xEF]), "deadbeef");
    }
}
