// 校验和具体实现
use crate::接口_殿::校验和_契约_阁::契约_实现_园::校验和契约;

// 表驱动校验工具结构体
pub struct 表驱动校验工具;

// 生成 CRC-32 查找表的辅助常量
const 多项式反转: u32 = 0xEDB88320;

// 内部 CRC-32 查表法实现
fn 计算_crc32(数据: &[u8]) -> u32 {
    // 初始化 CRC 寄存器为全 1
    let mut 累加值: u32 = 0xFFFFFFFF;
    // 遍历每个字节进行查表计算
    for 字节 in 数据 {
        // 取出当前字节并与 CRC 低 8 位异或
        let 索引: usize = ((累加值 ^ (*字节 as u32)) & 0xFF) as usize;
        // 生成查找表（使用栈上临时数组，避免全局静态初始化的复杂性）
        // 这里采用即时计算表项的方式
        let mut 表项: u32 = 索引 as u32;
        for _ in 0..8 {
            if 表项 & 1 != 0 {
                表项 = (表项 >> 1) ^ 多项式反转;
            } else {
                表项 >>= 1;
            }
        }
        // 更新累加值
        累加值 = (累加值 >> 8) ^ 表项;
    }
    // 最终取反
    累加值 ^ 0xFFFFFFFF
}

// 公开的 CRC-32 函数（不使用第三方依赖）
pub fn crc32(数据: &[u8]) -> u32 {
    // 调用内部计算函数
    计算_crc32(数据)
}

// 公开的字节转十六进制函数
pub fn 字节转十六进制(数据: &[u8]) -> String {
    // 构建小写十六进制字符串
    let mut 输出 = String::with_capacity(数据.len() * 2);
    for 字节 in 数据 {
        // 高 4 位转十六进制字符
        let 高位 = (字节 >> 4) & 0x0F;
        // 低 4 位转十六进制字符
        let 低位 = 字节 & 0x0F;
        输出.push(十六进制字符(高位));
        输出.push(十六进制字符(低位));
    }
    输出
}

// 4 位值转十六进制字符辅助函数
fn 十六进制字符(值: u8) -> char {
    if 值 < 10 {
        // 0-9 范围
        (b'0' + 值) as char
    } else {
        // a-f 范围
        (b'a' + 值 - 10) as char
    }
}

// 为表驱动校验工具实现校验和契约
impl 校验和契约 for 表驱动校验工具 {
    // CRC-32 实现
    fn crc32(&self, 数据: &[u8]) -> u32 {
        // 委托给公开函数
        crc32(数据)
    }

    // 字节转十六进制实现
    fn 字节转十六进制(&self, 数据: &[u8]) -> String {
        // 委托给公开函数
        字节转十六进制(数据)
    }
}
