//! 数据校验·园·重铸实现
//! 道祖终裁 → 大罗执行 → 准圣验收
//! 自举·滚动校验字重铸（自举任务单：自举-滚动校验字重铸）
//!
//! 算法契约（可证伪）：
//!   位置加权和(b"abc") == 590
//!   滚动校验字(b"ABCDEFGH") == 0x0C040404
//!   滚动校验字(b"12345") == 0x34333204
//!   滚动校验字(b"") == 0xFFFFFFFF（空输入哨兵）

/// 位置加权和：每个字节值乘以位置权重（首字节权重 1，逐字节递增 1）后求和。
///
/// 验算：b"abc" → 0x61×1 + 0x62×2 + 0x63×3 = 97 + 196 + 297 = 590
///
/// # 参数
/// * `数据` - 待计算字节切片
///
/// # 返回
/// 每个字节值与其位置（1 基）乘积的 u64 求和
pub fn 位置加权和(数据: &[u8]) -> u64 {
    数据
        .iter()
        .enumerate()
        .map(|(位置, 字节)| (*字节 as u64) * (位置 as u64 + 1))
        .sum()
}

/// 滚动校验字：把字节序列每 4 字节划为一组，组内按小端序（首字节为最低位）
/// 拼成 u32，所有组按位异或得到结果。空输入返回哨兵 0xFFFFFFFF。
///
/// 验算：
///   b"ABCDEFGH" → [0x41,0x42,0x43,0x44] ^ [0x45,0x46,0x47,0x48]
///               = 0x44434241 ^ 0x48474645 = 0x0C040404
///   b"12345"    → [0x31,0x32,0x33,0x34] ^ [0x35]
///               = 0x34333231 ^ 0x00000035 = 0x34333204
///   b""         → 0xFFFFFFFF（空输入哨兵）
///
/// # 参数
/// * `数据` - 待计算字节切片
///
/// # 返回
/// 所有 4 字节组按小端拼成 u32 后异或的结果；空输入返回 0xFFFFFFFF
pub fn 滚动校验字(数据: &[u8]) -> u32 {
    if 数据.is_empty() {
        return 0xFFFF_FFFF;
    }
    数据
        .chunks(4)
        .map(|组| {
            组.iter()
                .enumerate()
                .map(|(偏移, 字节)| (*字节 as u32) << (偏移 * 8))
                .sum::<u32>()
        })
        .fold(0u32, |累加, 项| 累加 ^ 项)
}
