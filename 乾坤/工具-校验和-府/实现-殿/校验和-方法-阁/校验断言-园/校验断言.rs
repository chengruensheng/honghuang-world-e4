#[cfg(test)]
mod 测试 {
    use crate::实现_殿::校验和_方法_阁::数据校验_园::{
        位置加权和, 滚动校验字
    };

    /// 验项：位置加权和标准用例（b"abc" = 97×1 + 98×2 + 99×3 = 590）
    #[test]
    fn 位置加权和_标准用例() {
        assert_eq!(位置加权和(b"abc"), 590);
        assert_eq!(位置加权和(&[]), 0, "空输入位置加权和为 0");
    }

    /// 验项：滚动校验字整组用例（8 字节 = 两组各 4 字节小端，组间异或）
    #[test]
    fn 滚动校验字_整组用例() {
        assert_eq!(滚动校验字(b"ABCDEFGH"), 0x0C040404);
    }

    /// 验项：滚动校验字末组不足四字节用例（5 字节 = 4 + 1，末组单字节小端）
    #[test]
    fn 滚动校验字_末组不足四字节() {
        assert_eq!(滚动校验字(b"12345"), 0x34333204);
    }

    /// 验项：空输入哨兵——空输入必须返回哨兵 0xFFFFFFFF（区分「无数据」与「校验字恰为 0」）
    #[test]
    fn 滚动校验字_空输入返回哨兵() {
        assert_eq!(
            滚动校验字(&[]),
            0xFFFF_FFFF,
            "空输入必须返回哨兵 0xFFFFFFFF（区分「无数据」与「校验字恰为 0」）"
        );
    }
}
