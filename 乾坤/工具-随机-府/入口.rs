/// 确定性随机数（LCG）
pub fn 随机数(种子值: u64, 范围: u64) -> u64 {
    if 范围 == 0 {
        return 0;
    }
    let 状态 = 种子值
        .wrapping_mul(6364136223846793005)
        .wrapping_add(1442695040888963407);
    状态 % 范围
}

#[cfg(test)]
mod 测试 {
    use super::*;
    #[test]
    fn 随机数_确定性() {
        assert_eq!(随机数(42, 100), 随机数(42, 100));
    }
    #[test]
    fn 随机数_范围内() {
        for i in 0..100 {
            let r = 随机数(i, 10);
            assert!(r < 10);
        }
    }
    #[test]
    fn 随机数_零范围() {
        assert_eq!(随机数(1, 0), 0);
    }
}
