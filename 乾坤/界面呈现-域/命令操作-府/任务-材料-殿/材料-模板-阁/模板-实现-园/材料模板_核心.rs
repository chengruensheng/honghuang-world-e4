//! 任务材料模板核心：真实任务材料的结构化建模 + 模板生成 + 写入格位
//!
//! 决策锚：260829 真实通过可复现——「验证任务」有语义歧义，「开发任务」语义无歧义；
//! 材料必须带「真实源码 diff + 无歧义任务标识 + 四时机可证伪」，防治理层幻觉编译错误。
//! 架构：任务材料=纯数据（可测），写入=确定性归类（执行×产出/验证，幂等+绑定任务），
//! 模板=纯函数（同输入同输出，可单测），三者正交、无副作用交织。

use jiyi_chengzai_fu::{
    总纲, 本质, 来源, 格位, 格位中枢, 档位, 阶段, SQLite存储
};

/// 真实任务材料：产出 + 验证 两块文本（写入执行×产出 / 执行×验证，绑定任务=任务标识）
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct 任务材料 {
    pub 任务标识: String,
    pub 产出: String,
    pub 验证: String,
}

/// 写入任务材料：产出→执行×产出、验证→执行×验证（幂等 + 绑定任务，供治理层准圣验收 + 道祖终裁）
pub fn 写入任务材料(记忆库路径: &str, 材料: &任务材料) -> Result<(), String> {
    let 存储 = SQLite存储::文件新建(记忆库路径).map_err(|e| e.to_string())?;
    let mut 中枢 = 格位中枢::新建(存储);
    中枢
        .写入_格位_幂等(
            格位 {
                总纲: 总纲::执行,
                本质: 本质::产出,
            },
            阶段::实施,
            &材料.产出,
            "产出材料",
            档位::权档,
            来源::LLM,
            "大罗级",
            "术·工具",
            &材料.任务标识,
        )
        .map_err(|e| e.to_string())?;
    中枢
        .写入_格位_幂等(
            格位 {
                总纲: 总纲::执行,
                本质: 本质::验证,
            },
            阶段::实施,
            &材料.验证,
            "验证材料",
            档位::权档,
            来源::LLM,
            "准圣级",
            "鉴·验收",
            &材料.任务标识,
        )
        .map_err(|e| e.to_string())?;
    Ok(())
}

/// 开发任务材料模板：语义无歧义的「中文标识符函数 + 中文测试」任务
///
/// 无歧义三要素：函数名/签名/测试断言显式给出，任务标识不含「中文数字」等易误解词。
/// 纯函数：同输入同输出，供「无歧义任务样本集」批量生成材料。
pub fn 材料模板_开发任务(
    任务标识: &str,
    函数名: &str,
    签名: &str,
    职责: &str,
    测试名: &str,
    断言: &str,
) -> 任务材料 {
    let 产出 = format!(
        "工单：写一个中文标识符函数「{函数名}」，签名 {签名}；职责={职责}；附中文测试「{测试名}」断言 {断言}，cargo test 通过。\ndecided_by：大罗级（执行层）\nfalsifiable：cargo test {测试名} 全绿（断言 {断言} 与边界用例通过）\nimplements：术（工具）\n交付代码（完整可编译，中文标识符，无截断）：\n    /// {函数名}：{职责}\n    pub fn {函数名}{签名} {{ /* 实现体由执行层产出 */ }}\n\n    #[cfg(test)]\n    mod 测试 {{  // 测试模块（白名单 mod/use/fn/assert 等关键字）\n        use super::{函数名};\n        #[test]\n        fn {测试名}() {{ assert_eq!({断言}); }}\n    }}\n复现命令：cargo test {测试名} -- --nocapture\ncargo test 真实输出：\nrunning 1 test\ntest {测试名} ... ok\ntest result: ok. 1 passed; 0 failed"
    );
    let 验证 = format!(
        "验证：cargo test {测试名} -- --nocapture 通过（断言 {断言} 全过）\ndecided_by：准圣级（验收）\nfalsifiable：{断言} 可复现（任意合法输入确定性正确）\nimplements：鉴（验收）\n业务指标分离：编译通过率 1/1；测试通过率 1/1"
    );
    任务材料 {
        任务标识: 任务标识.to_string(),
        产出,
        验证,
    }
}

/// 验证任务材料模板：产出/验证直接传入（用于「验证链路」类任务，材料已含真实源码 diff）
pub fn 材料模板_验证任务(任务标识: &str, 产出: &str, 验证: &str) -> 任务材料 {
    任务材料 {
        任务标识: 任务标识.to_string(),
        产出: 产出.to_string(),
        验证: 验证.to_string(),
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 模板_开发任务_无歧义三要素齐全() {
        let 材料 = 材料模板_开发任务(
            "整数加法函数",
            "两数求和",
            "(甲: i32, 乙: i32) -> i32",
            "返回两个整数的和",
            "测试_两数求和",
            "两数求和(2, 3), 5",
        );
        assert!(材料.产出.contains("两数求和"), "产出应含函数名");
        assert!(材料.产出.contains("测试_两数求和"), "产出应含测试名");
        assert!(材料.产出.contains("decided_by：大罗级"), "产出应含决策者");
        assert!(材料.产出.contains("falsifiable"), "产出应含可证伪");
        assert!(材料.验证.contains("准圣级"), "验证应含验收者");
    }

    #[test]
    fn 模板_开发任务_同输入同输出_纯函数() {
        let 甲 = 材料模板_开发任务(
            "整数加法函数",
            "两数求和",
            "(甲: i32, 乙: i32) -> i32",
            "求和",
            "测试_两数求和",
            "两数求和(2, 3), 5",
        );
        let 乙 = 材料模板_开发任务(
            "整数加法函数",
            "两数求和",
            "(甲: i32, 乙: i32) -> i32",
            "求和",
            "测试_两数求和",
            "两数求和(2, 3), 5",
        );
        assert_eq!(甲, 乙, "模板为纯函数，同输入同输出");
    }

    #[test]
    fn 防退化_中文求和歧义_开发任务标识等于函数名不含中文数字() {
        // D 盘失败：任务标识「中文求和函数」被 LLM 误读为「中文数字解析」（语义歧义 → 产出跑题）
        // E 盘回归：开发任务标识=函数名（如「两数求和」），不含「中文」等易误解词
        let 材料 = 材料模板_开发任务(
            "两数求和",
            "两数求和",
            "(甲: i32, 乙: i32) -> i32",
            "返回两个整数的和",
            "测试_两数求和",
            "两数求和(2, 3), 5",
        );
        assert_eq!(材料.任务标识, "两数求和", "任务标识=函数名");
        assert!(
            !材料.任务标识.contains("中文"),
            "任务标识不含「中文」歧义词（D 盘失败防退化）"
        );
        assert!(材料.产出.contains("两数求和"), "产出含函数名");
    }

    #[test]
    fn 共同样本4回归_防退化四要素齐全() {
        // 块八三项目共同验收：4 个共同样本（整数加法/字符串反转/列表去重/校验和）
        // 统一回归——任务标识不含中文数字歧义词 + 四要素齐全（decided_by/falsifiable/implements/复现）+ 纯函数同输入同输出。
        let 样本: [(&str, &str, &str, &str, &str, &str); 4] = [
            (
                "整数加法函数",
                "两数求和",
                "(甲: i32, 乙: i32) -> i32",
                "返回两个整数的和",
                "测试_两数求和",
                "两数求和(2, 3), 5",
            ),
            (
                "字符串反转函数",
                "反转字符串",
                "(原文: &str) -> String",
                "返回原文的倒序字符串",
                "测试_反转字符串",
                "反转字符串(「abc」), 「cba」",
            ),
            (
                "列表去重函数",
                "去重整数",
                "(列表: Vec<i32>) -> Vec<i32>",
                "返回去重后保持原序的整数列表",
                "测试_去重整数",
                "去重整数(vec![1, 2, 2, 3]), vec![1, 2, 3]",
            ),
            (
                "校验和函数",
                "校验和",
                "(数据: &[u8]) -> u32",
                "返回数据的 CRC32 校验和",
                "测试_校验和",
                "校验和(b\"abc\"), 0x352441C2",
            ),
        ];
        let 中文数字 = ['一', '二', '三', '四', '五', '六', '七', '八', '九', '十'];
        for (任务标识, 函数名, 签名, 职责, 测试名, 断言) in 样本 {
            let 材料 = 材料模板_开发任务(任务标识, 函数名, 签名, 职责, 测试名, 断言);
            assert!(
                !任务标识.chars().any(|c| 中文数字.contains(&c)),
                "任务标识「{任务标识}」不含中文数字歧义词"
            );
            assert!(材料.产出.contains(函数名), "产出含函数名 {函数名}");
            assert!(材料.产出.contains(测试名), "产出含测试名 {测试名}");
            assert!(材料.产出.contains("decided_by"), "产出含决策者");
            assert!(材料.产出.contains("falsifiable"), "产出含可证伪");
            assert!(材料.产出.contains("implements"), "产出含哲学锚");
            assert!(材料.产出.contains("复现命令"), "产出含复现命令");
            assert!(材料.验证.contains("准圣级"), "验证含验收者");
            // 纯函数：同输入同输出
            let 复写 = 材料模板_开发任务(任务标识, 函数名, 签名, 职责, 测试名, 断言);
            assert_eq!(材料, 复写, "共同样本模板纯函数同输入同输出");
        }
    }
}
