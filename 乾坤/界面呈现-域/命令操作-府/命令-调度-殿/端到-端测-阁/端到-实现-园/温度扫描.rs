//! 温度扫描：对 N 档终裁温度各跑 M 次真实任务，输出「温度→通过率」表
//!
//! 决策锚：100项任务 任务1 终裁温度系统性调优（真实通过可复现核心）
//! 可复现 = 同温度连跑通过率高且稳定；温度非真实通过复现的决定性因素（实测 0.1 首过 1/1 连 3 打回 0/3），
//! 复现需确定性机制（多次采样多数投票/材料对齐），本命令保留为可复现实验工具。

use crate::跑流水线_真实_llm;

/// 跑温度扫描：逐档设 LLM_终裁温度 env → 每档跑 N 次真实流水线 → 统计「温度→通过率」
/// 通过判定 = 流水线输出含「登记并交付」标记（终裁通过才交付）。
pub fn 温度扫描(任务标识: &str, 每档次数: usize, 温度列表: &[String]) -> String {
    let mut 输出 = format!(
        "=== 终裁温度扫描：任务「{}」每档 {} 次 ===\n",
        任务标识, 每档次数
    );
    for 温度 in 温度列表 {
        std::env::set_var("LLM_终裁温度", 温度);
        let mut 通过 = 0usize;
        let mut 打回 = 0usize;
        for _ in 0..每档次数 {
            let 结果 = 跑流水线_真实_llm(任务标识);
            let 交付 = 结果.输出.contains("[交付] 登记并交付");
            if 交付 {
                通过 += 1;
            } else {
                打回 += 1;
            }
        }
        let 通过率 = (通过 * 100).checked_div(每档次数).unwrap_or(0);
        输出.push_str(&format!(
            "温度 {}: 通过 {}/{} = {}%（打回 {}）\n",
            温度, 通过, 每档次数, 通过率, 打回
        ));
    }
    输出
}
