//! 终裁判定核心：终裁结论结构化判定 + 解析 + 多数裁决 + 质量门禁 + 打回要求提取
//!
//! 决策锚：100项任务 任务4（多次采样取多数，对冲 LLM 采样非确定）
//! 纯函数簇：同输入同输出，可单测；与端到端调度/真实连接正交，不持有连接状态。

/// 终裁结论：结构化判定（替代 contains("打回") 脆弱字符串判定）
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) enum 终裁结论 {
    通过,
    打回,
}

/// 解析终裁结论：打回词优先（打回/不通过/驳回/暂不通过/不予通过/重做），通过需明确通过词（通过/认可/准予/予以通过/同意），
/// 无打回词也无通过词 → 打回（保守：沉默不代表通过，直击「框架空壳」——终裁必须明确裁决，不允许自评失真蒙混）
pub(crate) fn 解析终裁结论(内容: &str) -> 终裁结论 {
    const 打回词: [&str; 6] = ["打回", "不通过", "驳回", "暂不通过", "不予通过", "重做"];
    const 通过词: [&str; 5] = ["通过", "认可", "准予", "予以通过", "同意"];
    // 结论区截断：结论只出现在「可证伪/理由/备注/历史包袱」标题之前；
    // 之后是理由与可证伪条件说明（常写「证伪失败→终裁打回」），不计入结论。
    let 结论区: String = 内容
        .lines()
        .take_while(|行| {
            // 结论区截断只在「标题行（# 开头）」或「行首词」触发；
            // 表格行（如「| falsifiable 自洽 |」）不截断，避免误伤其后的总判/终裁结论。
            let 行 = 行.trim_start();
            let 标题 = 行.starts_with('#');
            let 截断词 = 行.contains("可证伪")
                || 行.contains("falsifiable")
                || 行.contains("证伪")
                || 行.contains("理由")
                || 行.contains("备注")
                || 行.contains("历史包袱");
            let 行首词 = 行.starts_with("可证伪")
                || 行.starts_with("falsifiable")
                || 行.starts_with("证伪")
                || 行.starts_with("理由")
                || 行.starts_with("备注")
                || 行.starts_with("历史包袱");
            !(行首词 || (标题 && 截断词))
        })
        .collect::<Vec<_>>()
        .join("\n");
    // 结论行优先：只在「终裁/决策/结论/裁决」行判结论；
    // 但若这些行全是标题（如「## 四、终裁」）而无裁决词，回退结论区全量，
    // 不丢弃真正的结论行（如「# ✅ 通过（收档）」）——直击真实终裁「通过」被误判「打回」。
    let 结论行: Vec<&str> = 结论区
        .lines()
        .filter(|行| {
            行.contains("终裁") || 行.contains("决策") || 行.contains("结论") || 行.contains("裁决")
        })
        .collect();
    let 结论行有效 = 结论行.iter().any(|行| {
        打回词.iter().any(|词| 行.contains(词)) || 通过词.iter().any(|词| 行.contains(词))
    });
    let 候选: Vec<&str> = if 结论行有效 {
        结论行
    } else {
        结论区.lines().collect()
    };
    // 打回词优先：不通过 含「通过」子串，必须先判打回词避免误判通过
    // 排除两类非任务打回语境：①「打回精炼/精炼阶段」是 falsifiable 字段修正；②「驳回理由：无」是无驳回。
    for 行 in &候选 {
        let 精炼语境 = 行.contains("精炼");
        let 无驳回 = 行.contains("驳回理由") && (行.contains("无") || 行.contains("None"));
        if 打回词.iter().any(|词| 行.contains(词)) && !精炼语境 && !无驳回 {
            return 终裁结论::打回;
        }
    }
    for 行 in &候选 {
        if 通过词.iter().any(|词| 行.contains(词)) {
            return 终裁结论::通过;
        }
    }
    终裁结论::打回
}

/// 多数裁决：对多次终裁采样取多数（通过=+1，打回=-1），平票或全弃权→打回（保守）
///
/// 决策锚：100项任务 任务4 终裁多次采样取多数——对冲 LLM 采样非确定，确定性裁决纯函数（同输入同输出）。
/// 3 次采样 2 通过 1 打回 → 通过；2 打回 1 通过 → 打回；1:1:1（1 弃权）→ 打回。
pub(crate) fn 多数裁决(裁决列表: &[终裁结论]) -> 终裁结论 {
    let 净票: i32 = 裁决列表
        .iter()
        .map(|c| match c {
            终裁结论::通过 => 1,
            终裁结论::打回 => -1,
        })
        .sum();
    if 净票 > 0 {
        终裁结论::通过
    } else {
        终裁结论::打回
    }
}

/// 质量门禁四要素：产出必须显式标注 decided_by（谁决策）+ falsifiable（可证伪命题）+ implements（哲学锚）+ 复现（cargo test/验证命令）
/// 直击「框架空壳」：空壳产出无四要素，门禁否决终裁通过（命名合规由道祖角色卡铁律 + 静态门禁脚本执行）
/// 中英双语义词：decided_by/决策者，falsifiable/可证伪，复现/验证/cargo test（角色卡 prompt 用英文 decided_by + 中文可证伪条件，真实产出复述其一即命中）
pub(crate) fn 质量门禁校验(产出: &str) -> Vec<&'static str> {
    let mut 缺项 = Vec::new();
    if !产出.contains("decided_by") && !产出.contains("决策者") {
        缺项.push("decided_by");
    }
    if !产出.contains("falsifiable") && !产出.contains("可证伪") {
        缺项.push("falsifiable");
    }
    if !产出.contains("implements") {
        缺项.push("implements");
    }
    if !产出.contains("复现") && !产出.contains("验证") && !产出.contains("cargo test") {
        缺项.push("复现");
    }
    缺项
}

/// 打回理由结构化：从终裁内容提取「可执行修订要求」（致命修复/验收判据/复现命令 行）
/// 直击「打回报告空泛」：重投时执行角色明确知道必须修什么，而非从全文里自找（真实打回报告含 F1/F2/F3 致命修复表）
pub(crate) fn 提取修订要求(终裁内容: &str) -> String {
    const 关键词: [&str; 6] = [
        "致命修复",
        "验收判据",
        "复现命令",
        "修复项",
        "缺一即打回",
        "必须满足",
    ];
    let mut 要求: Vec<&str> = Vec::new();
    for 行 in 终裁内容.lines() {
        let 命中 = 关键词.iter().any(|k| 行.contains(k))
            || 行.contains("F1")
            || 行.contains("F2")
            || 行.contains("F3");
        if 命中 {
            要求.push(行);
        }
    }
    if 要求.is_empty() {
        // 无结构化修复项，回退到原文前 20 行（保留裁决结论与理由，避免全文注入稀释）
        终裁内容.lines().take(20).collect::<Vec<_>>().join("\n")
    } else {
        要求.join("\n")
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 解析终裁结论_打回变体覆盖() {
        assert_eq!(解析终裁结论("打回"), 终裁结论::打回);
        assert_eq!(解析终裁结论("本次任务暂不通过"), 终裁结论::打回);
        assert_eq!(解析终裁结论("不予通过"), 终裁结论::打回);
        assert_eq!(解析终裁结论("驳回"), 终裁结论::打回);
        assert_eq!(解析终裁结论("终裁：通过"), 终裁结论::通过);
        assert_eq!(解析终裁结论("予以通过"), 终裁结论::通过);
        assert_eq!(解析终裁结论("重做"), 终裁结论::打回);
        // 终裁质量：沉默=打回（不允许无明确裁决蒙混通过）
        assert_eq!(解析终裁结论("[mock LLM 响应]"), 终裁结论::打回);
        assert_eq!(解析终裁结论("材料已补齐"), 终裁结论::打回);
    }

    #[test]
    fn 解析终裁结论_通过结论含可证伪打回词不误判() {
        // 通过结论的可证伪条件里写「证伪失败→终裁打回」，结论行优先不得误判打回
        assert_eq!(
            解析终裁结论("【终裁决策】通过\n可证伪条件：证伪失败（终裁打回）"),
            终裁结论::通过
        );
        assert_eq!(
            解析终裁结论(
                "## 一、决策结论 **通过。**\n## 二、可证伪条件\n任一失败即为终裁打回"
            ),
            终裁结论::通过
        );
        // 真打回仍判打回（结论行含打回）
        assert_eq!(解析终裁结论("# 道祖终裁：打回补正"), 终裁结论::打回);
    }

    #[test]
    fn 解析终裁结论_真实终裁通过收档含驳回理由无_不误判打回() {
        // 真实 MiniMax-M3 终裁输出：标题「## 四、终裁」下才是「# ✅ 通过（收档）」，
        // 且正文含「驳回理由：无」——旧逻辑只看标题行无裁决词即回退打回，把通过误判打回。
        let 真实 = "## 四、终裁\n\n# ✅ **通过（收档）**\n\n---\n\n- **decided_by**：**道祖级（决策）** ✅\n- **驳回理由**：**无**\n- **依据**：\n  1. 铁律一（命名合规）—— 零违规\n- **falsifiable**：`cargo test` 任一失败即证伪";
        assert_eq!(解析终裁结论(真实), 终裁结论::通过);
    }

    #[test]
    fn 解析终裁结论_打回精炼语境不误判任务打回() {
        // 真实 MiniMax-M3 终裁输出：falsifiable 字段录入错误被裁决「打回精炼阶段修正」，
        // 但任务总判「交付 7/7 通过，采纳入档」——精炼语境的打回不是任务打回。
        let 真实 = "## 二、终裁矩阵\n| 维度 | 裁决 |\n| falsifiable 自洽 | ❌ 基线 split-brain | **打回精炼** | 三方矛盾 |\n**总判**：交付 **7/7 通过**，采纳入档；falsifiable **打回精炼阶段修正**。\n道祖终裁：通过";
        assert_eq!(解析终裁结论(真实), 终裁结论::通过);
        // 真打回重做仍判打回（无精炼语境）
        assert_eq!(解析终裁结论("# 道祖终裁：打回重做"), 终裁结论::打回);
    }

    #[test]
    fn 多数裁决_两通过一打回取通过() {
        assert_eq!(
            多数裁决(&[终裁结论::通过, 终裁结论::通过, 终裁结论::打回]),
            终裁结论::通过
        );
    }

    #[test]
    fn 多数裁决_两打回一通过取打回() {
        assert_eq!(
            多数裁决(&[终裁结论::打回, 终裁结论::打回, 终裁结论::通过]),
            终裁结论::打回
        );
    }

    #[test]
    fn 多数裁决_平票或全打回取打回_保守() {
        assert_eq!(多数裁决(&[终裁结论::通过, 终裁结论::打回]), 终裁结论::打回);
        assert_eq!(多数裁决(&[终裁结论::打回, 终裁结论::打回]), 终裁结论::打回);
        assert_eq!(多数裁决(&[]), 终裁结论::打回, "全弃权（空）也应保守打回");
    }
}
