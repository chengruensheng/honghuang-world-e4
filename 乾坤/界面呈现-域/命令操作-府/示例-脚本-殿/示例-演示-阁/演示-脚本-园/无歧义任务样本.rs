//! 无歧义任务样本 - 批量生成 3 个语义无歧义的开发任务材料并写入格位
//!
//! 决策锚：260829 真实通过可复现——「验证任务」「中文求和」类标识有语义歧义；
//! 开发任务三要素（函数名/签名/断言）显式给出，任务标识不含「中文数字」等易误解词。
//! 用法：cargo run -p mingling_caozuo_fu --example 无歧义任务样本
//! 验收：cargo run -p mingling_caozuo_fu --example 自举审计 -- <各任务标识> 均回填 1 块

use mingling_caozuo_fu::{写入任务材料, 材料模板_开发任务, 默认记忆库路径};

fn main() {
    let 样本: [(&str, &str, &str, &str, &str, &str); 4] = [
        (
            "整数加法函数",
            "两数求和",
            "(甲: i32, 乙: i32) -> i32",
            "返回两个整数的和",
            "测试_两数求和",
            "两数求和(2, 3), 5",
        ),
        (
            "字符串反转函数",
            "反转字符串",
            "(原文: &str) -> String",
            "返回原文的倒序字符串",
            "测试_反转字符串",
            "反转字符串(「abc」), 「cba」",
        ),
        (
            "列表去重函数",
            "去重整数",
            "(列表: Vec<i32>) -> Vec<i32>",
            "返回去重后保持原序的整数列表",
            "测试_去重整数",
            "去重整数(vec![1, 2, 2, 3]), vec![1, 2, 3]",
        ),
        (
            "校验和函数",
            "校验和",
            "(数据: &[u8]) -> u32",
            "返回数据的 CRC32 校验和（IEEE 802.3 标准多项式 0xEDB88320 查表法）",
            "测试_校验和",
            "校验和(b\"abc\"), 0x352441C2",
        ),
    ];

    for (任务标识, 函数名, 签名, 职责, 测试名, 断言) in 样本 {
        let 材料 = 材料模板_开发任务(任务标识, 函数名, 签名, 职责, 测试名, 断言);
        写入任务材料(默认记忆库路径, &材料).expect("材料写入失败");
        println!("已写入无歧义任务材料：{} => {}{}", 任务标识, 函数名, 签名);
    }
}
