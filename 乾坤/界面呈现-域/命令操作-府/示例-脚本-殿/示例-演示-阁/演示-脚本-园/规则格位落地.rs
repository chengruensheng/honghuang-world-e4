//! 规则格位落地（example）：把阶段 3 真实回归学到的验收规则写进「规则」格位
//!
//! 架构语义（界主拍板）：质量/规则是格位数据——人类可编辑、动态生效、LLM 可自迭代。
//! 本 example 用确定性程序把「准圣六维 + 道祖三层警示」落进规则格位，
//! 来源=LLM（无玉玺，可执行），人类日后确认可盖玉玺（确认格位记忆）。
//! 用法：cargo run -p mingling_caozuo_fu --example 规则格位落地

use jiyi_chengzai_fu::{总纲, 本质, 阶段};
use mingling_caozuo_fu::{写入_按格位, 默认记忆库路径};

fn main() {
    let 库 = 默认记忆库路径;

    // 准圣验收六维 → 规则×门禁
    let 六维 = 写入_按格位(
        库,
        总纲::规则,
        本质::门禁,
        阶段::实施,
        "准圣验收六维门禁：①真实落盘（目标文件存在且字节数>0，纸面声明不算，未落盘即打回）②命名合规（标识符/目录/注释全中文，白名单 SQLite/P0-P3/LLM）③编译通过（cargo build 退出码 0，系统级硬证据）④漂移护栏（版本/常量精确匹配，无旧值残留）⑤标识符零缩写（中文标识符不得缩写）⑥字面量精确（版本号/阶段字面量逐一比对）",
        "准圣六维",
    )
    .expect("准圣六维写规则门禁格位失败");
    println!("[规则格位] 准圣六维 → 规则×门禁 id={}", 六维.0);

    // 道祖终裁三层警示 → 规则×红线
    let 三层 = 写入_按格位(
        库,
        总纲::规则,
        本质::红线,
        阶段::实施,
        "道祖终裁三层警示：①纸面声明≠交付（自检全过但磁盘无文件=画饼充饥，玉玺不盖）②os error 123=ERROR_INVALID_NAME（Windows 内核级拒绝，非网络/权限/并发，须根因排查）③落盘后立即自证（第一行输出 Test-Path→True 与实际字节数，不得跳步）",
        "道祖三层",
    )
    .expect("道祖三层写规则红线格位失败");
    println!("[规则格位] 道祖三层 → 规则×红线 id={}", 三层.0);

    // 大罗执行四要素门禁 → 规则×门禁（角色卡铁律迁格位：四要素是决策契约核心）
    let 四要素 = 写入_按格位(
        库,
        总纲::规则,
        本质::门禁,
        阶段::实施,
        "大罗执行四要素门禁：产出必须显式标注 ①decided_by（决策者）②falsifiable（可证伪命题）③implements（哲学锚）④复现（cargo test/验证命令），四要素缺一即打回；产出需中文标识符（代码/注释/目录全中文）+ cargo build 通过 + Cargo.toml 工具链强制字段保留 ASCII",
        "大罗四要素",
    )
    .expect("大罗四要素写规则门禁格位失败");
    println!("[规则格位] 大罗四要素 → 规则×门禁 id={}", 四要素.0);

    println!("规则格位落地完成（来源=LLM，无玉玺；人类确认后盖玉玺）");
}
