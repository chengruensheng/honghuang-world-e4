/// 告警级别（4 级）
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum 告警级 {
    P3提示,
    P2次要,
    P1重要,
    P0紧急,
}

impl 告警级 {
    pub fn 名称(self) -> &'static str {
        match self {
            告警级::P3提示 => "P3提示",
            告警级::P2次要 => "P2次要",
            告警级::P1重要 => "P1重要",
            告警级::P0紧急 => "P0紧急",
        }
    }
}

/// 告警状态
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 告警状态 {
    已触发,
    已确认,
    已解决,
}

/// 应急级别（4 级，升级路径对接告警 P0-P3）
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum 应急级 {
    大罗级,
    准圣级,
    圣人级,
    道祖级,
}

impl 应急级 {
    pub fn 名称(self) -> &'static str {
        match self {
            应急级::大罗级 => "大罗级",
            应急级::准圣级 => "准圣级",
            应急级::圣人级 => "圣人级",
            应急级::道祖级 => "道祖级",
        }
    }
}

/// 升级路径映射（P 告警级 → 应急级）
pub fn 升级路径(告警级: 告警级) -> 应急级 {
    match 告警级 {
        告警级::P0紧急 => 应急级::道祖级,
        告警级::P1重要 => 应急级::圣人级,
        告警级::P2次要 => 应急级::准圣级,
        告警级::P3提示 => 应急级::大罗级,
    }
}

/// 应急流程
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum 响应模式 {
    自动,
    半自动,
    手动,
}

#[derive(Clone, Debug, PartialEq)]
pub struct 应急流程 {
    pub 级别: 应急级,
    pub 触发条件: String,
    pub 动作: String,
    pub 负责人: String,
    pub 响应模式: 响应模式,
}

impl 应急流程 {
    pub fn 新建(
        级别: 应急级, 触发条件: &str, 动作: &str, 负责人: &str, 模式: 响应模式
    ) -> Self {
        Self {
            级别,
            触发条件: 触发条件.to_string(),
            动作: 动作.to_string(),
            负责人: 负责人.to_string(),
            响应模式: 模式,
        }
    }
}

/// 应急流程库（4 级 + 升级路径）
pub fn 应急流程库(告警: &告警) -> 应急流程 {
    let 级别 = 升级路径(告警.级别);
    let (动作, 负责人, 模式) = match 告警.级别 {
        告警级::P0紧急 => crate::告警_响应_殿::P0_紧急_阁::应急配置(),
        告警级::P1重要 => crate::告警_响应_殿::P1_重要_阁::应急配置(),
        告警级::P2次要 => crate::告警_响应_殿::P2_次要_阁::应急配置(),
        告警级::P3提示 => crate::告警_响应_殿::P3_提示_阁::应急配置(),
    };
    let 触发条件 = format!(
        "{} 级告警触发：{} = {}",
        告警.级别.名称(),
        告警.指标名,
        告警.当前值
    );
    应急流程::新建(级别, &触发条件, 动作, 负责人, 模式)
}

/// 告警
#[derive(Clone, Debug, PartialEq)]
pub struct 告警 {
    pub 级别: 告警级,
    pub 指标名: String,
    pub 当前值: f64,
    pub 阈值: f64,
    pub 状态: 告警状态,
    pub 时间戳: u64,
}

impl 告警 {
    pub fn 新建(级别: 告警级, 指标名: &str, 当前值: f64, 阈值: f64) -> Self {
        Self {
            级别,
            指标名: 指标名.to_string(),
            当前值,
            阈值,
            状态: 告警状态::已触发,
            时间戳: 0,
        }
    }

    /// 升级到对应应急级
    pub fn 升级应急(&mut self) -> 应急级 {
        let 级别 = 升级路径(self.级别);
        if self.级别 == 告警级::P0紧急 {
            self.状态 = 告警状态::已确认;
        }
        级别
    }
}

/// 告警引擎
pub struct 告警引擎 {
    pub 告警列表: Vec<告警>,
}

impl 告警引擎 {
    pub fn 新建() -> Self {
        Self {
            告警列表: Vec::new(),
        }
    }

    /// 接收指标变化 → 匹配阈值 → 触发告警
    pub fn 接收指标(&mut self, 指标: &指标) {
        if let Some(告警) = 触发告警(指标) {
            self.告警列表.push(告警);
        }
    }

    pub fn 严重数(&self) -> usize {
        self.告警列表
            .iter()
            .filter(|a| a.级别 == 告警级::P0紧急)
            .count()
    }
}

/// 单指标告警触发判定
pub fn 触发告警(指标: &指标) -> Option<告警> {
    if 指标.严重() {
        return Some(告警::新建(
            告警级::P0紧急,
            &指标.名称,
            指标.值,
            指标.阈值_危急.unwrap_or(f64::MAX),
        ));
    }
    if 指标.警告() {
        return Some(告警::新建(
            告警级::P1重要,
            &指标.名称,
            指标.值,
            指标.阈值_警告.unwrap_or(f64::MAX),
        ));
    }
    None
}

