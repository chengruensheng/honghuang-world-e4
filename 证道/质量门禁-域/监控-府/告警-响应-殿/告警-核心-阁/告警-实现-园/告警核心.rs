    #[test]
    fn 测试_e2e_全链路() {
        // 1. 创建 4 类指标
        let uptime = 指标::新建("uptime", 指标类::可用性, 99.95);
        let mut p99 = 指标::新建("p99延迟", 指标类::性能, 200.0);
        p99.阈值_危急 = Some(100.0);
        let mut cpu = 指标::新建("cpu", 指标类::资源, 95.0);
        cpu.阈值_危急 = Some(90.0);
        let mut 通过率 = 指标::新建("通过率", 指标类::正确性, 0.5);
        通过率.阈值_警告 = Some(0.8);

        // 2. 4 类指标入监控报告
        use crate::指标_采集_殿::监控报告;
        let mut 报告 = 监控报告::新建();
        报告.添加(uptime.clone());
        报告.添加(p99.clone());
        报告.添加(cpu.clone());
        报告.添加(通过率.clone());
        assert_eq!(报告.指标列表.len(), 4);
        assert_eq!(报告.严重数(), 2, "p99 + cpu 严重");
        assert_eq!(报告.警告数(), 0, "通过率 0.5 < 0.8 不警告");

        // 3. 4 级告警 + 升级路径
        let mut 引擎 = 告警引擎::新建();
        引擎.接收指标(&p99);
        引擎.接收指标(&cpu);
        引擎.接收指标(&通过率);
        assert_eq!(引擎.严重数(), 2);
        let 升级P0 = 升级路径(告警级::P0紧急);
        let 升级P1 = 升级路径(告警级::P1重要);
        let 升级P2 = 升级路径(告警级::P2次要);
        let 升级P3 = 升级路径(告警级::P3提示);
        assert_eq!(升级P0, 应急级::道祖级);
        assert_eq!(升级P1, 应急级::圣人级);
        assert_eq!(升级P2, 应急级::准圣级);
        assert_eq!(升级P3, 应急级::大罗级);
    }
