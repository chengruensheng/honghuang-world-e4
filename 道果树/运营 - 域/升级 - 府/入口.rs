//! falsifiable：3 类升级 + 错峰 < 5 分钟 + 复用经验入 36 格位 + ≥ 8 单元测试

#![allow(non_snake_case)]

#[path = "升级策略-殿/模块.rs"]
pub mod 升级策略_殿;
#[path = "经验复用-殿/模块.rs"]
pub mod 经验复用_殿;

pub use 升级策略_殿::{升级类型, 升级计划, 回滚, 错峰升级};
pub use 经验复用_殿::{v3复用经验, 写入格位信息, 复用经验};

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 测试_3类升级枚举() {
        assert_eq!(
            3,
            [升级类型::补丁, 升级类型::小版本, 升级类型::大版本].len()
        );
    }

    #[test]
    fn 测试_升级计划_补丁窗口() {
        let p = 升级计划::新建(升级类型::补丁, "1.0.0", "1.0.1", "devops");
        assert_eq!(p.类型, 升级类型::补丁);
        assert_eq!(p.影响窗口_秒, 60);
        assert!(p.回滚方案.contains("revert"));
    }

    #[test]
    fn 测试_升级计划_小版本窗口() {
        let p = 升级计划::新建(升级类型::小版本, "1.0.0", "1.1.0", "devops");
        assert_eq!(p.影响窗口_秒, 180);
        assert!(p.影响窗口_分钟() == 3);
    }

    #[test]
    fn 测试_升级计划_大版本窗口() {
        let p = 升级计划::新建(升级类型::大版本, "1.0.0", "2.0.0", "devops");
        assert_eq!(p.影响窗口_秒, 300);
        assert_eq!(p.影响窗口_分钟(), 5);
    }

    #[test]
    fn 测试_错峰升级总耗时() {
        let p = 升级计划::新建(升级类型::小版本, "1.0.0", "1.1.0", "devops");
        let 错峰 = 错峰升级::新建(p, 10);
        // 180秒 = 3分钟 + 10分钟 = 13分钟总耗时
        assert_eq!(错峰.总耗时分钟(), 13);
    }

    #[test]
    fn 测试_回滚_步骤() {
        let p = 升级计划::新建(升级类型::大版本, "1.0.0", "2.0.0", "devops");
        let r = 回滚::新建(p, "v1.0.0-stable");
        assert_eq!(r.快照, "v1.0.0-stable");
        assert_eq!(r.步骤.len(), 5);
        assert!(r.步骤[0].contains("停止"));
    }

    #[test]
    fn 测试_复用经验_36格位写入() {
        let r = 复用经验::新建("test", "decision", "reuse", "test-phase");
        assert_eq!(r.写入格位.范畴, "经历");
        assert_eq!(r.写入格位.阶段, "归档");
        assert!(r.写入格位.路径.contains("复用经验"));
    }

    #[test]
    fn 测试_v3复用经验_10阶段() {
        let 经验s = v3复用经验();
        assert_eq!(经验s.len(), 10, "v3 阶段 1-10 应有 10 条复用经验");
        // 验证每条都有合理的关联阶段
        for e in &经验s {
            assert!(e.关联阶段.contains("阶段"));
        }
    }
}
