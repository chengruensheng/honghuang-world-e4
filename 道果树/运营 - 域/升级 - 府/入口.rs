/// 升级类型（3 类）
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum 升级类型 {
    /// 补丁（x.y.z -> x.y.z+1）
    补丁,
    /// 小版本（x.y -> x.y+1）
    小版本,
    /// 大版本（x -> x+1）
    大版本,
}

impl 升级类型 {
    pub fn 名称(self) -> &'static str {
        match self {
            升级类型::补丁 => "补丁",
            升级类型::小版本 => "小版本",
            升级类型::大版本 => "大版本",
        }
    }
}

/// 升级计划
#[derive(Clone, Debug, PartialEq)]
pub struct 升级计划 {
    pub 类型: 升级类型,
    pub 从版本: String,
    pub 到版本: String,
    pub 影响窗口_秒: u32,
    pub 责任人: String,
    pub 回滚方案: String,
}

impl 升级计划 {
    pub fn 新建(类型: 升级类型, 从: &str, 到: &str, 责任人: &str) -> Self {
        let (窗口, 回滚) = match 类型 {
            升级类型::补丁 => (60, format!("git revert {}", 到)),
            升级类型::小版本 => (180, "快照回滚 + 重新部署".to_string()),
            升级类型::大版本 => (300, "灰度回滚 + 数据库迁移反向".to_string()),
        };
        Self {
            类型,
            从版本: 从.to_string(),
            到版本: 到.to_string(),
            影响窗口_秒: 窗口,
            责任人: 责任人.to_string(),
            回滚方案: 回滚,
        }
    }

    pub fn 影响窗口_分钟(&self) -> u32 {
        self.影响窗口_秒 / 60
    }
}

// ============================================================================
// 错峰升级 + 回滚
// ============================================================================

/// 错峰升级（错开时间窗口避免全部同时升级）
pub struct 错峰升级 {
    pub 计划: 升级计划,
    pub 错峰分钟: u32,
}

impl 错峰升级 {
    pub fn 新建(计划: 升级计划, 错峰分钟: u32) -> Self {
        Self {
            计划, 错峰分钟
        }
    }

    /// 总耗时（含错峰）
    pub fn 总耗时分钟(&self) -> u32 {
        self.计划.影响窗口_分钟() + self.错峰分钟
    }
}

/// 回滚（从快照恢复）
pub struct 回滚 {
    pub 计划: 升级计划,
    pub 快照: String,
    pub 步骤: Vec<String>,
}

impl 回滚 {
    pub fn 新建(计划: 升级计划, 快照: &str) -> Self {
        Self {
            计划,
            快照: 快照.to_string(),
            步骤: vec![
                "1. 停止服务".to_string(),
                format!("2. git checkout {}", 快照),
                "3. 重新构建 + 部署".to_string(),
                "4. 验证服务".to_string(),
                "5. 恢复流量".to_string(),
            ],
        }
    }
}

