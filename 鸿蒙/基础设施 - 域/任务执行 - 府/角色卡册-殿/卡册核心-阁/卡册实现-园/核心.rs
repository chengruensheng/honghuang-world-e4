/// 角色分类（接 4-分类抽象决策）
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum 角色分类 {
    道祖级,
    圣人级,
    准圣级,
    大罗金仙级,
}

impl 角色分类 {
    pub fn 名称(self) -> &'static str {
        match self {
            角色分类::道祖级 => "道祖级",
            角色分类::圣人级 => "圣人级",
            角色分类::准圣级 => "准圣级",
            角色分类::大罗金仙级 => "大罗金仙级",
        }
    }
}

// ============================================================================
// 角色卡
// ============================================================================

/// 角色卡（每分类 1 张：道祖卡/圣人卡/准圣卡/大罗卡）
#[derive(Clone, Debug)]
#[allow(non_snake_case)]
pub struct 角色卡 {
    pub 分类: 角色分类,
    pub 名称: String,
    pub 权限: Vec<String>,
    pub decided_by: String,
    pub LLM池: String,
    pub 工具偏好: Vec<String>,
}

/// 4 张具体角色卡的工厂函数（每分类 1 张）
///
/// 决策锚：260826-2210 4-分类抽象 § 流水线
/// - 道祖：化要求 / 派遣 / 终裁 / 定档
/// - 圣人：设计 / 评审
/// - 大罗：按道分工（实现）
/// - 准圣：六维验收 / 打回
pub fn 分类_角色卡(分类: 角色分类) -> 角色卡 {
    match 分类 {
        角色分类::道祖级 => 道祖卡(),
        角色分类::圣人级 => 圣人卡(),
        角色分类::准圣级 => 准圣卡(),
        角色分类::大罗金仙级 => 大罗卡(),
    }
}

// ============================================================================
// 错误
// ============================================================================

/// 错误
#[derive(Debug, Clone, PartialEq, Eq)]
#[allow(clippy::enum_variant_names)]
pub enum 错误 {
    任务标识为空,
    任务描述为空,
    分类不匹配 {
        期望: 角色分类,
        实际: 角色分类,
    },
    decided_by为空,
}

impl std::fmt::Display for 错误 {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            错误::任务标识为空 => write!(f, "任务标识必填"),
            错误::任务描述为空 => write!(f, "任务描述必填"),
            错误::分类不匹配 { 期望, 实际 } => {
                write!(f, "分类不匹配：期望 {:?}，实际 {:?}", 期望, 实际)
            }
            错误::decided_by为空 => write!(f, "decided_by 必填"),
        }
    }
}

impl std::error::Error for 错误 {}

