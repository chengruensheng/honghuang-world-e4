// ============================================================================
// 分类机械判定
// ============================================================================

/// 分类机械判定：硬编码 4 分类规则，无 LLM 调用即可通过/拒绝
///
/// 决策锚：260826-2210 § 流水线
/// 规则：
/// 1. 任务标识必填（非空）
/// 2. 任务描述必填（非空）
/// 3. decided_by 必填（非空）
/// 4. 分类匹配：任务的"分类"字段必须与传入的 分类 参数一致
pub fn 分类_机械判定(任务: &任务, 分类: 角色分类) -> Result<(), 错误> {
    if 任务.标识.is_empty() {
        return Err(错误::任务标识为空);
    }
    if 任务.描述.is_empty() {
        return Err(错误::任务描述为空);
    }
    if 任务.decided_by.is_empty() {
        return Err(错误::decided_by为空);
    }
    if 任务.分类 != 分类 {
        return Err(错误::分类不匹配 {
            期望: 分类,
            实际: 任务.分类,
        });
    }
    Ok(())
}
