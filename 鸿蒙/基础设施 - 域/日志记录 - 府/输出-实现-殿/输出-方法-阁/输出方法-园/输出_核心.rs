//! 输出实现 - 标准输出日志的 trait impl

use crate::日志_接口_殿::日志契约_阁::日志契约定义_园::日志;
use crate::级别;
use crate::输出_实现_殿::输出_结构_阁::输出结构定义_园::标准输出日志;

impl 日志 for 标准输出日志 {
    fn 输出(&self, 级别: 级别, 消息: &str) {
        let 前缀 = match 级别 {
            级别::跟踪 => "[TRC]",
            级别::调试 => "[DBG]",
            级别::信息 => "[INF]",
            级别::警告 => "[WRN]",
            级别::错误 => "[ERR]",
        };
        println!("{} {}", 前缀, 消息);
    }
}
