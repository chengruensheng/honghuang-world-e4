// ============================================================================
// 4 分类 ↔ 4 阶段 映射
// ============================================================================

/// 分类 → 默认阶段（接单时按分类起跳）
pub fn 分类_默认阶段(分类: 分类) -> 阶段 {
    match 分类 {
        分类::道祖级 => 阶段::道祖,
        分类::圣人级 => 阶段::圣人,
        分类::准圣级 => 阶段::准圣,
        分类::大罗金仙级 => 阶段::大罗,
    }
}

/// 阶段 → 分类（反向映射）
pub fn 阶段_分类(阶段: 阶段) -> 分类 {
    match 阶段 {
        阶段::道祖 => 分类::道祖级,
        阶段::圣人 => 分类::圣人级,
        阶段::大罗 => 分类::大罗金仙级,
        阶段::准圣 => 分类::准圣级,
    }
}

// ============================================================================
// 跳层 / 反序 判定
// ============================================================================

/// 是否跳层：跳过至少 1 个中间正向阶段
///
/// 顺向一步：道祖→圣人 / 圣人→大罗 / 大罗→准圣 / 准圣→道祖（终裁）= 合法
/// 反向一步（打回回路）：准圣→大罗 / 大罗→准圣 = 合法
/// 跳层：跳过 ≥1 个阶段
///   - 道祖直接验收（道祖→准圣）
///   - 道祖直接执行（道祖→大罗）
///   - 圣人直接终裁（圣人→道祖）
///   - 圣人跳过执行（圣人→准圣）
///   - 大罗直接回到道祖（大罗→道祖）
pub fn 是否跳层(从: 阶段, 到: 阶段) -> bool {
    use 阶段::*;
    if 从 == 到 {
        return false;
    }
    matches!(
        (从, 到),
        (道祖, 准圣) | (道祖, 大罗) | (圣人, 准圣) | (圣人, 道祖) | (大罗, 道祖)
    )
}

/// 是否反序：跳过中间正向阶段（不含打回回路）
///
/// 反序对：(大罗→圣人) 大罗重做时不应该回调设计阶段
/// 合法反向：仅 (准圣→大罗) 打回 + (大罗→准圣) 复验
pub fn 是否反序(从: 阶段, 到: 阶段) -> bool {
    use 阶段::*;
    if 从 == 到 {
        return false;
    }
    // 显式枚举反序对
    matches!(
        (从, 到),
        (大罗, 圣人) |    // 大罗重做时不允许回调设计
        (准圣, 圣人) // 准圣不应回到设计阶段
    )
}

/// 综合判定：合法跳转（既非跳层也非反序）
pub fn 是否合法跳转(从: 阶段, 到: 阶段) -> bool {
    !是否跳层(从, 到) && !是否反序(从, 到)
}

// ============================================================================
// 给定当前阶段与请求跳转，返回合法下一阶段或 None（拒绝）
// ============================================================================

pub fn 下一阶段(当前: 阶段, 请求: 跳转) -> Option<阶段> {
    use 阶段::*;
    match (当前, 请求) {
        (道祖, 跳转::圣人设计) => Some(圣人),
        (圣人, 跳转::大罗执行) => Some(大罗),
        (大罗, 跳转::准圣验收) => Some(准圣),
        (准圣, 跳转::道祖终裁) => Some(道祖),
        (准圣, 跳转::大罗重做) => Some(大罗),
        (大罗, 跳转::准圣复验) => Some(准圣),
        // 跳层与反序：均拒绝（None）
        _ => None,
    }
}

