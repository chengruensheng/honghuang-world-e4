use std::collections::HashMap;

// 跨殿引用：分类与阶段定义在各自殿中（六层返工后改用 crate:: 路径）
use crate::流水线分类_殿::分类;
use crate::流水线阶段_殿::{跳转, 阶段};

// ============================================================================
// 4 分类 ↔ 4 阶段 映射
// ============================================================================

/// 分类 → 默认阶段（接单时按分类起跳）
pub fn 分类_默认阶段(分类: 分类) -> 阶段 {
    match 分类 {
        分类::道祖级 => 阶段::道祖,
        分类::圣人级 => 阶段::圣人,
        分类::准圣级 => 阶段::准圣,
        分类::大罗金仙级 => 阶段::大罗,
    }
}

/// 阶段 → 分类（反向映射）
pub fn 阶段_分类(阶段: 阶段) -> 分类 {
    match 阶段 {
        阶段::道祖 => 分类::道祖级,
        阶段::圣人 => 分类::圣人级,
        阶段::大罗 => 分类::大罗金仙级,
        阶段::准圣 => 分类::准圣级,
    }
}

// ============================================================================
// 跳层 / 反序 判定
// ============================================================================

/// 是否跳层：跳过至少 1 个中间正向阶段
///
/// 顺向一步：道祖→圣人 / 圣人→大罗 / 大罗→准圣 / 准圣→道祖（终裁）= 合法
/// 反向一步（打回回路）：准圣→大罗 / 大罗→准圣 = 合法
/// 跳层：跳过 ≥1 个阶段
///   - 道祖直接验收（道祖→准圣）
///   - 道祖直接执行（道祖→大罗）
///   - 圣人直接终裁（圣人→道祖）
///   - 圣人跳过执行（圣人→准圣）
///   - 大罗直接回到道祖（大罗→道祖）
pub fn is_跳层(从: 阶段, 到: 阶段) -> bool {
    use 阶段::*;
    if 从 == 到 {
        return false;
    }
    matches!(
        (从, 到),
        (道祖, 准圣) | (道祖, 大罗) | (圣人, 准圣) | (圣人, 道祖) | (大罗, 道祖)
    )
}

/// 是否反序：跳过中间正向阶段（不含打回回路）
///
/// 反序对：(大罗→圣人) 大罗重做时不应该回调设计阶段
/// 合法反向：仅 (准圣→大罗) 打回 + (大罗→准圣) 复验
pub fn is_反序(从: 阶段, 到: 阶段) -> bool {
    use 阶段::*;
    if 从 == 到 {
        return false;
    }
    // 显式枚举反序对
    matches!(
        (从, 到),
        (大罗, 圣人) |    // 大罗重做时不允许回调设计
        (准圣, 圣人) // 准圣不应回到设计阶段
    )
}

/// 综合判定：合法跳转（既非跳层也非反序）
pub fn is_合法跳转(从: 阶段, 到: 阶段) -> bool {
    !is_跳层(从, 到) && !is_反序(从, 到)
}

// ============================================================================
// 给定当前阶段与请求跳转，返回合法下一阶段或 None（拒绝）
// ============================================================================

pub fn 下一阶段(当前: 阶段, 请求: 跳转) -> Option<阶段> {
    use 阶段::*;
    match (当前, 请求) {
        (道祖, 跳转::圣人设计) => Some(圣人),
        (圣人, 跳转::大罗执行) => Some(大罗),
        (大罗, 跳转::准圣验收) => Some(准圣),
        (准圣, 跳转::道祖终裁) => Some(道祖),
        (准圣, 跳转::大罗重做) => Some(大罗),
        (大罗, 跳转::准圣复验) => Some(准圣),
        // 跳层与反序：均拒绝（None）
        _ => None,
    }
}

// ============================================================================
// 循环打回计数（任务级状态）
// ============================================================================

/// 任务级循环打回计数（HashMap 模拟阶段 5 内存状态；阶段 9+ 接 SQLite）
#[derive(Default)]
pub struct 循环打回状态 {
    打回计数: HashMap<String, u32>,
}

impl 循环打回状态 {
    pub fn 新建() -> Self {
        Self::default()
    }

    /// 增加打回计数；返回新的打回次数
    pub fn 增加打回(&mut self, 任务ID: &str) -> u32 {
        let 计数 = self.打回计数.entry(任务ID.to_string()).or_insert(0);
        *计数 += 1;
        *计数
    }

    /// 获取当前打回次数
    pub fn 打回次数(&self, 任务ID: &str) -> u32 {
        self.打回计数.get(任务ID).copied().unwrap_or(0)
    }

    /// 是否需要升级道祖终裁（≥3 轮时返回 true）
    pub fn 应升级道祖(&self, 任务ID: &str) -> bool {
        self.打回次数(任务ID) >= 3
    }

    /// 重置（任务完成时调用）
    pub fn 重置(&mut self, 任务ID: &str) {
        self.打回计数.remove(任务ID);
    }
}

// ============================================================================
// 单元测试
// ============================================================================

#[cfg(test)]
mod 测试 {
    use super::*;

    // ---------- 4 分类 ↔ 4 阶段 映射 ----------

    #[test]
    fn 分类_阶段_一一对应() {
        for 分类 in [分类::道祖级, 分类::圣人级, 分类::准圣级, 分类::大罗金仙级]
        {
            let 阶段 = 分类_默认阶段(分类);
            assert_eq!(阶段_分类(阶段), 分类);
        }
    }

    // ---------- 跳层判定 ----------

    #[test]
    fn 跳层道祖直接验收拒绝() {
        assert!(is_跳层(阶段::道祖, 阶段::准圣));
    }

    #[test]
    fn 跳层圣人直接终裁拒绝() {
        assert!(is_跳层(阶段::圣人, 阶段::道祖));
    }

    #[test]
    fn 跳层圣人跳到执行拒绝() {
        assert!(is_跳层(阶段::圣人, 阶段::准圣));
    }

    #[test]
    fn 顺向一步不算跳层() {
        assert!(!is_跳层(阶段::道祖, 阶段::圣人));
        assert!(!is_跳层(阶段::圣人, 阶段::大罗));
        assert!(!is_跳层(阶段::大罗, 阶段::准圣));
        assert!(!is_跳层(阶段::准圣, 阶段::道祖)); // 终裁
    }

    #[test]
    fn 打回一步不算跳层() {
        assert!(!is_跳层(阶段::准圣, 阶段::大罗));
        assert!(!is_跳层(阶段::大罗, 阶段::准圣));
    }

    // ---------- 反序判定 ----------

    #[test]
    fn 反序大罗回到圣人拒绝() {
        // 注：实际业务中允许（大罗重做后可能回调设计），但在标准流水线上为反序
        // 阶段5 暂定：打回回路只允许 准圣→大罗→准圣，不允许 大罗→圣人
        assert!(is_反序(阶段::大罗, 阶段::圣人));
    }

    #[test]
    fn 顺向合法() {
        assert_eq!(下一阶段(阶段::道祖, 跳转::圣人设计), Some(阶段::圣人));
        assert_eq!(下一阶段(阶段::圣人, 跳转::大罗执行), Some(阶段::大罗));
        assert_eq!(下一阶段(阶段::大罗, 跳转::准圣验收), Some(阶段::准圣));
        assert_eq!(下一阶段(阶段::准圣, 跳转::道祖终裁), Some(阶段::道祖));
    }

    #[test]
    fn 跳层拒绝() {
        // 道祖直接验收 → 拒绝（跳层）
        assert_eq!(下一阶段(阶段::道祖, 跳转::准圣验收), None);
        // 圣人直接终裁 → 拒绝
        assert_eq!(下一阶段(阶段::圣人, 跳转::道祖终裁), None);
    }

    #[test]
    fn 反序拒绝() {
        // 大罗不能先于圣人设计
        assert_eq!(下一阶段(阶段::大罗, 跳转::圣人设计), None);
    }

    #[test]
    fn 打回回路() {
        assert_eq!(下一阶段(阶段::准圣, 跳转::大罗重做), Some(阶段::大罗));
        assert_eq!(下一阶段(阶段::大罗, 跳转::准圣复验), Some(阶段::准圣));
    }

    // ---------- 循环打回计数 ----------

    #[test]
    fn 初始打回次数为0() {
        let 状态 = 循环打回状态::新建();
        assert_eq!(状态.打回次数("task-001"), 0);
        assert!(!状态.应升级道祖("task-001"));
    }

    #[test]
    fn 打回3次升级道祖() {
        let mut 状态 = 循环打回状态::新建();
        状态.增加打回("task-001");
        状态.增加打回("task-001");
        assert_eq!(状态.打回次数("task-001"), 2);
        assert!(!状态.应升级道祖("task-001"));
        状态.增加打回("task-001");
        assert_eq!(状态.打回次数("task-001"), 3);
        assert!(状态.应升级道祖("task-001"));
    }

    #[test]
    fn 任务完成后重置打回计数() {
        let mut 状态 = 循环打回状态::新建();
        状态.增加打回("task-001");
        状态.增加打回("task-001");
        状态.重置("task-001");
        assert_eq!(状态.打回次数("task-001"), 0);
    }

    #[test]
    fn 多任务打回计数独立() {
        let mut 状态 = 循环打回状态::新建();
        状态.增加打回("task-001");
        状态.增加打回("task-001");
        状态.增加打回("task-002");
        assert_eq!(状态.打回次数("task-001"), 2);
        assert_eq!(状态.打回次数("task-002"), 1);
    }
}
