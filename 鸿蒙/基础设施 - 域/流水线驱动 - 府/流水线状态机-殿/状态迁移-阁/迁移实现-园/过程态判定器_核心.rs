//! 过程态判定器 - 13 过程态的转移判定（推进 + 不可跳层校验）
//!
//! 决策锚：260826-2210 4-分类抽象 § 流水线
//! 关联文档：04-设计/状态机/01-流水线.md § 三（状态转移函数）+ § 四（不可跳层校验）
//! falsifiable：跳层次数 = 0 + 反序次数 = 0 + 循环超限升级率 < 10%
//!
//! 与 4 分类职责态状态机的关系（缺陷5 修正）：
//! - 4 态状态机（状态机_核心.rs 的 下一阶段）= 权威职责态，已实现
//! - 本判定器 = 13 过程态的细粒度转移（每职责拆「待 X」+「X 中」）
//! - 二者共享同一哲学：不可跳层不可反序 + 循环打回 ≤ 3 轮升级

use crate::流水线阶段_殿::{事件, 正向序列, 过程态};

// ============================================================================
// 过程态转移错误
// ============================================================================

/// 过程态转移错误
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 过程态错误 {
    非法转移,
}

// ============================================================================
// 13 过程态推进（状态转移函数）
// ============================================================================

/// 13 过程态转移判定器——给定当前态 + 事件 + 打回计数，返回下一态或拒绝
///
/// 打回计数由外部「循环打回状态」持有（计数内化，事件仅触发判定，
/// 不携带外部计数——防调用方永远传 1 绕过 3 轮上限）。
/// 判定阈值：打回计数 ≥ 3 → 循环超限升级（道祖人工裁决）。
pub fn 推进(
    当前: 过程态, 事件: 事件, 打回计数: u32
) -> Result<过程态, 过程态错误> {
    use 过程态::*;
    match (当前, 事件) {
        (待化要求, 事件::化要求完成) => Ok(化要求中),
        (化要求中, 事件::要求书就绪) => Ok(待设计),
        (待设计, 事件::设计开始) => Ok(设计中),
        (设计中, 事件::方案就绪) => Ok(待实现),
        (待实现, 事件::实现开始) => Ok(实现中),
        (实现中, 事件::产物就绪) => Ok(待验收),
        (待验收, 事件::验收开始) => Ok(验收中),
        (验收中, 事件::验收通过) => Ok(待终裁),
        (验收中, 事件::验收打回) => Ok(已打回待重做),
        (待终裁, 事件::终裁开始) => Ok(终裁中),
        (终裁中, 事件::定档完成) => Ok(已定档),
        // 循环计数由状态机内部持有，事件仅触发判定
        (已打回待重做, 事件::循环计数) => {
            if 打回计数 >= 3 {
                Ok(循环超限升级)
            } else {
                Ok(待实现)
            }
        }
        // 第五十轮修复：循环超限升级缺出边死锁，补 道祖裁决 → 终裁中
        (循环超限升级, 事件::道祖裁决) => Ok(终裁中),
        _ => Err(过程态错误::非法转移),
    }
}

// ============================================================================
// 不可跳层不可反序的机械校验
// ============================================================================

/// 校验「当前 → 下一」是否满足不可跳层不可反序
///
/// 先判特殊转移（打回/超限不在正向序列），避免序列索引越界；
/// 再对正向序列做「下一索引 == 当前索引 + 1」的紧邻校验。
pub fn 校验不可跳层(当前: 过程态, 下一: 过程态) -> bool {
    use 过程态::*;
    // 特殊转移（打回回路 + 超限升级），不在正向序列中
    if (当前, 下一) == (验收中, 已打回待重做) {
        return true;
    }
    if (当前, 下一) == (已打回待重做, 待实现) {
        return true;
    }
    if (当前, 下一) == (已打回待重做, 循环超限升级) {
        return true;
    }
    if (当前, 下一) == (循环超限升级, 终裁中) {
        return true;
    }
    // 正向序列紧邻校验
    let 当前索引 = 正向序列.iter().position(|s| *s == 当前);
    let 下一索引 = 正向序列.iter().position(|s| *s == 下一);
    match (当前索引, 下一索引) {
        (Some(a), Some(b)) => b == a + 1,
        _ => false,
    }
}

// ============================================================================
// 单元测试
// ============================================================================

#[cfg(test)]
mod 测试 {
    use super::*;
    use 过程态::*;

    #[test]
    fn 推进_正向全链路_十一步到已定档() {
        let 步骤 = [
            (待化要求, 事件::化要求完成, 化要求中),
            (化要求中, 事件::要求书就绪, 待设计),
            (待设计, 事件::设计开始, 设计中),
            (设计中, 事件::方案就绪, 待实现),
            (待实现, 事件::实现开始, 实现中),
            (实现中, 事件::产物就绪, 待验收),
            (待验收, 事件::验收开始, 验收中),
            (验收中, 事件::验收通过, 待终裁),
            (待终裁, 事件::终裁开始, 终裁中),
            (终裁中, 事件::定档完成, 已定档),
        ];
        for (当前, 事件, 期望) in 步骤 {
            assert_eq!(推进(当前, 事件, 0), Ok(期望));
        }
    }

    #[test]
    fn 推进_打回_未超限回待实现() {
        assert_eq!(推进(验收中, 事件::验收打回, 0), Ok(已打回待重做));
        // 第 1 次打回后计数 1 < 3 → 回待实现
        assert_eq!(推进(已打回待重做, 事件::循环计数, 1), Ok(待实现));
        // 第 2 次打回后计数 2 < 3 → 回待实现
        assert_eq!(推进(已打回待重做, 事件::循环计数, 2), Ok(待实现));
    }

    #[test]
    fn 推进_循环超限_三连打回升级道祖裁决() {
        // 第 3 次打回后计数 3 ≥ 3 → 循环超限升级
        assert_eq!(推进(已打回待重做, 事件::循环计数, 3), Ok(循环超限升级));
        // 道祖裁决 → 终裁中 → 定档完成（出边闭环）
        assert_eq!(推进(循环超限升级, 事件::道祖裁决, 3), Ok(终裁中));
        assert_eq!(推进(终裁中, 事件::定档完成, 3), Ok(已定档));
    }

    #[test]
    fn 推进_非法转移_拒绝() {
        // 待化要求 不能直接 设计开始（跳层）
        assert_eq!(推进(待化要求, 事件::设计开始, 0), Err(过程态错误::非法转移));
        // 待设计 不能 验收通过（反序）
        assert_eq!(推进(待设计, 事件::验收通过, 0), Err(过程态错误::非法转移));
        // 已定档（终态）不能再推进
        assert_eq!(推进(已定档, 事件::定档完成, 0), Err(过程态错误::非法转移));
    }

    #[test]
    fn 校验不可跳层_顺向一步合法() {
        assert!(校验不可跳层(待化要求, 化要求中));
        assert!(校验不可跳层(化要求中, 待设计));
        assert!(校验不可跳层(实现中, 待验收));
        assert!(校验不可跳层(验收中, 待终裁));
    }

    #[test]
    fn 校验不可跳层_跳层拒绝() {
        // 跳过至少一个正向态
        assert!(!校验不可跳层(待化要求, 待设计));
        assert!(!校验不可跳层(待化要求, 设计中));
        assert!(!校验不可跳层(设计中, 待验收));
    }

    #[test]
    fn 校验不可跳层_打回与超限合法() {
        assert!(校验不可跳层(验收中, 已打回待重做));
        assert!(校验不可跳层(已打回待重做, 待实现));
        assert!(校验不可跳层(已打回待重做, 循环超限升级));
        assert!(校验不可跳层(循环超限升级, 终裁中));
    }
}
