// ============================================================================
// 13 过程态（4 分类职责态的过程态下钻）
// ============================================================================

/// 13 过程态——4 职责各拆「待 X」+「X 中」，外加 3 中间态
///
/// 正向序列：待化要求 → 化要求中 → 待设计 → 设计中 → 待实现 → 实现中
///   → 待验收 → 验收中 → 待终裁 → 终裁中 → 已定档（11 个）
/// 中间态：已打回待重做（准圣打回）、循环超限升级（异常升级）
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum 过程态 {
    待化要求,     // 道祖入口（待化要求）
    化要求中,     // 道祖化要求
    待设计,       // 已化要求，待圣人
    设计中,       // 圣人设计
    待实现,       // 已设计，待大罗
    实现中,       // 大罗金仙实现
    待验收,       // 已实现，待准圣
    验收中,       // 准圣验收
    待终裁,       // 已验收，待道祖
    终裁中,       // 道祖终裁
    已定档,       // 终态（frozen outcome）
    已打回待重做, // 中间态（准圣打回）
    循环超限升级, // 异常态（打回 ≥3 轮升级）
}

impl 过程态 {
    /// 过程态中文名
    pub fn 名称(self) -> &'static str {
        match self {
            过程态::待化要求 => "待化要求",
            过程态::化要求中 => "化要求中",
            过程态::待设计 => "待设计",
            过程态::设计中 => "设计中",
            过程态::待实现 => "待实现",
            过程态::实现中 => "实现中",
            过程态::待验收 => "待验收",
            过程态::验收中 => "验收中",
            过程态::待终裁 => "待终裁",
            过程态::终裁中 => "终裁中",
            过程态::已定档 => "已定档",
            过程态::已打回待重做 => "已打回待重做",
            过程态::循环超限升级 => "循环超限升级",
        }
    }

    /// 是否为终态
    pub fn 是否终态(self) -> bool {
        matches!(self, 过程态::已定档)
    }

    /// 过程态 → 4 分类职责态（权威粒度映射）
    ///
    /// 每职责拆「待 X」+「X 中」归同一职责；3 中间态归属：
    /// - 已定档 / 终裁中 / 待终裁 → 道祖（终裁职责）
    /// - 已打回待重做 → 准圣（打回由准圣触发）
    /// - 循环超限升级 → 道祖（人工裁决）
    pub fn 职责态(self) -> 阶段 {
        match self {
            过程态::待化要求 | 过程态::化要求中 => 阶段::道祖,
            过程态::待设计 | 过程态::设计中 => 阶段::圣人,
            过程态::待实现 | 过程态::实现中 => 阶段::大罗,
            过程态::待验收 | 过程态::验收中 | 过程态::已打回待重做 => {
                阶段::准圣
            }
            过程态::待终裁 | 过程态::终裁中 | 过程态::已定档 | 过程态::循环超限升级 => {
                阶段::道祖
            }
        }
    }
}

// ============================================================================
// 事件（13 态状态机的转移触发）
// ============================================================================

/// 流水线事件——每个正向步骤 + 打回 + 循环计数 + 道祖裁决
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 事件 {
    化要求完成, // 待化要求 → 化要求中
    要求书就绪, // 化要求中 → 待设计
    设计开始,   // 待设计 → 设计中
    方案就绪,   // 设计中 → 待实现
    实现开始,   // 待实现 → 实现中
    产物就绪,   // 实现中 → 待验收
    验收开始,   // 待验收 → 验收中
    验收通过,   // 验收中 → 待终裁
    验收打回,   // 验收中 → 已打回待重做
    终裁开始,   // 待终裁 → 终裁中
    定档完成,   // 终裁中 → 已定档
    循环计数,   // 已打回待重做 → 待实现（<3）或 循环超限升级（≥3）
    道祖裁决,   // 循环超限升级 → 终裁中
}

