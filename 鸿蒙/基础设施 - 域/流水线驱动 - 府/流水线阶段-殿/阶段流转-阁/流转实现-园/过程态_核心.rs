#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 过程态_名称_十三态互异() {
        let 全部 = [
            过程态::待化要求,
            过程态::化要求中,
            过程态::待设计,
            过程态::设计中,
            过程态::待实现,
            过程态::实现中,
            过程态::待验收,
            过程态::验收中,
            过程态::待终裁,
            过程态::终裁中,
            过程态::已定档,
            过程态::已打回待重做,
            过程态::循环超限升级,
        ];
        let 名称: Vec<&str> = 全部.iter().map(|s| s.名称()).collect();
        // 13 个名称互异
        let mut 去重 = 名称.clone();
        去重.sort_unstable();
        去重.dedup();
        assert_eq!(去重.len(), 13, "13 过程态名称应互异");
    }

    #[test]
    fn 过程态_总数_十三_等于五职责乘二加三中间态() {
        // 5 职责（道祖/圣人/大罗/准圣/道祖终裁）× 2 过程态 + 3 中间态 = 13
        assert_eq!(正向序列.len(), 11);
        // 中间态 3 个：已打回待重做 + 循环超限升级 + 已定档已计入正向序列末位
        // 实际 13 = 11 正向 + 2 额外中间态（已打回待重做、循环超限升级）
        assert_eq!(11 + 2, 13);
    }

    #[test]
    fn 职责态_映射_每职责两过程态() {
        assert_eq!(过程态::待化要求.职责态(), 阶段::道祖);
        assert_eq!(过程态::化要求中.职责态(), 阶段::道祖);
        assert_eq!(过程态::待设计.职责态(), 阶段::圣人);
        assert_eq!(过程态::设计中.职责态(), 阶段::圣人);
        assert_eq!(过程态::待实现.职责态(), 阶段::大罗);
        assert_eq!(过程态::实现中.职责态(), 阶段::大罗);
        assert_eq!(过程态::待验收.职责态(), 阶段::准圣);
        assert_eq!(过程态::验收中.职责态(), 阶段::准圣);
    }

    #[test]
    fn 职责态_映射_中间态归属() {
        assert_eq!(过程态::已定档.职责态(), 阶段::道祖);
        assert_eq!(过程态::待终裁.职责态(), 阶段::道祖);
        assert_eq!(过程态::终裁中.职责态(), 阶段::道祖);
        assert_eq!(过程态::循环超限升级.职责态(), 阶段::道祖);
        assert_eq!(过程态::已打回待重做.职责态(), 阶段::准圣);
    }

    #[test]
    fn 终态判定_仅已定档() {
        assert!(过程态::已定档.是否终态());
        assert!(!过程态::验收中.是否终态());
        assert!(!过程态::循环超限升级.是否终态());
    }
}
