//! 36 格位 SQLite 应用 - 记忆承载验证
//!
//! 决策锚：260827-AI助手自给自足（Round 11.5）
//! 验证：SQLite 存储写入/读取 36 格位记忆（6 范畴 × 6 阶段）

use jiyi_chengzai_fu::记忆存储_殿::SQLite存储_阁::SQLite实现_园::SQLite存储;
use jiyi_chengzai_fu::{
    所有格位, 来源, 格位总数, 档位, 范畴, 记忆存储, 记忆条目, 阶段
};

fn main() {
    println!("=== 36 格位 SQLite 应用 ===");
    println!("格位总数：{}", 格位总数);

    // 1. 创建 SQLite 内存存储
    let mut 存储 = SQLite存储::内存新建().expect("SQLite 内存新建失败");
    println!("✓ SQLite 存储创建成功");

    // 2. 写入 3 个 36 格位记忆条目
    let 条目1 = 记忆条目::新建(
        1,
        范畴::目标,
        阶段::拍板,
        档位::经档,
        来源::人类,
        "统一六层风格目标",
        "21/21 crate 全部 ≥2 殿",
        "界主",
        "术·分层",
    );
    let 条目2 = 记忆条目::新建(
        2,
        范畴::规则,
        阶段::实施,
        档位::权档,
        来源::LLM,
        "命名门禁规则",
        "祖孙三层语义判据",
        "界主",
        "鉴·门禁",
    );
    let 条目3 = 记忆条目::新建(
        3,
        范畴::程序,
        阶段::验收,
        档位::行档,
        来源::代码,
        "一键全验 13 项",
        "13/13 门禁全绿",
        "界主",
        "术·DSH",
    );
    存储.写(条目1).expect("写入条目1失败");
    存储.写(条目2).expect("写入条目2失败");
    存储.写(条目3).expect("写入条目3失败");
    println!("✓ 写入 3 个记忆条目");

    // 3. 读取验证
    let 全部 = 存储.查_全部();
    println!("✓ 查_全部：{} 条", 全部.len());
    for 条目 in &全部 {
        println!(
            "  [{}] 范畴={:?} 阶段={:?} 档位={:?} 来源={:?} 内容={}",
            条目.id.0, 条目.范畴, 条目.阶段, 条目.档位, 条目.来源, 条目.内容
        );
    }

    // 4. 按 id 读取
    let 读回 = 存储.读(jiyi_chengzai_fu::记忆ID(1)).expect("读回条目1失败");
    println!("✓ 读回 id=1：{}", 读回.内容);

    // 5. 遍历所有格位
    println!("\n=== 36 格位遍历 ===");
    let mut 计数 = 0;
    for 格位 in 所有格位 {
        计数 += 1;
        if 计数 <= 5 {
            println!("  格位 {}：{:?}", 计数, 格位);
        }
    }
    println!("  ... 共 {} 格位", 计数);
    println!("\n=== 36 格位 SQLite 应用验证通过 ===");
}
