//! 36 格位闭环端到端演示 - 验证 写入_格位 + 读取_相关格位
//!
//! 决策锚：260827-AI助手自给自足 Step2（传承殿/10-地基/25-AI助手自给自足-实施方案.md）
//! falsifiable：任务描述含关键词 → 读取_相关格位 命中对应范畴记忆；无关键词 → 返回全部兜底
//!
//! 机制：AI 任务进来 → 读取_相关格位 组合心智模型 → 执行后 写入_格位 沉淀

use jiyi_chengzai_fu::{来源, 档位, 范畴, 阶段, 格位, 格位中枢, SQLite存储};

fn 写入(
    中枢: &mut 格位中枢<SQLite存储>,
    范畴: 范畴,
    阶段: 阶段,
    内容: &str,
    摘要: &str,
    档位: 档位,
    来源: 来源,
) {
    中枢
        .写入_格位(格位 { 范畴, 阶段 }, 内容, 摘要, 档位, 来源, "界主", "术·DSH")
        .expect("写入_格位 失败");
}

fn main() {
    println!("=== 36 格位闭环端到端演示 ===");

    // 1. 创建 SQLite 内存存储 + 格位中枢（写入/读取闭环的枢纽）
    let 存储 = SQLite存储::内存新建().expect("SQLite 内存新建失败");
    let mut 中枢 = 格位中枢::新建(存储);
    println!("✓ 格位中枢创建成功（包装 SQLite 内存存储）");

    // 2. 写入 5 条真实项目记忆到不同格位（范畴×阶段）
    写入(&mut 中枢, 范畴::目标, 阶段::拍板, "25号 AI 自给自足目标", "36 格位闭环", 档位::经档, 来源::人类);
    写入(&mut 中枢, 范畴::规则, 阶段::实施, "命名门禁规则", "祖孙判据", 档位::权档, 来源::LLM);
    写入(&mut 中枢, 范畴::程序, 阶段::实施, "36 格位闭环 API", "格位中枢 写入_格位 读取_相关格位", 档位::权档, 来源::LLM);
    写入(&mut 中枢, 范畴::世界, 阶段::验收, "292 测试全绿", "13-13 门禁", 档位::行档, 来源::代码);
    写入(&mut 中枢, 范畴::经历, 阶段::归档, "踩坑：中文标识符含缩写触发 clippy", "用纯中文命名", 档位::行档, 来源::代码);
    println!("✓ 写入 5 条记忆到 5 个格位");

    // 3. 模拟 AI 任务：读取_相关格位
    println!("\n--- 任务1：实现 Cargo 测试 ---");
    let 命中1 = 中枢.读取_相关格位("实现 Cargo 测试");
    for 条目 in &命中1 {
        println!("  [{}] {}", 条目.范畴.名称(), 条目.内容);
    }
    println!("  命中 {} 条（期望 1 条：程序）", 命中1.len());

    println!("--- 任务2：回顾过去踩坑教训 ---");
    let 命中2 = 中枢.读取_相关格位("回顾过去踩坑教训");
    for 条目 in &命中2 {
        println!("  [{}] {}", 条目.范畴.名称(), 条目.内容);
    }
    println!("  命中 {} 条（期望 1 条：经历）", 命中2.len());

    println!("--- 任务3：与记忆无关的未知词 ---");
    let 命中3 = 中枢.读取_相关格位("与记忆无关的未知词");
    println!("  无关键词命中 → 返回全部 {} 条（兜底）", 命中3.len());

    println!("\n=== 36 格位闭环端到端演示验证通过 ===");
}
