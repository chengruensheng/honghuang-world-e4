// 跨殿引用：类型定义在类型定义殿（六层返工后改用 crate:: 路径）
use crate::记忆类型_殿::{来源, 档位, 范畴, 记忆ID, 记忆条目, 错误, 阶段};

// ============================================================================
// 存储 trait（接口定义；阶段 3 实现内存，SQLite/JSONL 留阶段 4）
// ============================================================================

pub trait 记忆存储 {
    fn 读(&self, id: 记忆ID) -> Option<记忆条目>;
    fn 写(&mut self, 条目: 记忆条目) -> Result<(), 错误>;
    fn 删(&mut self, id: 记忆ID) -> Result<(), 错误>;
    fn 查_全部(&self) -> Vec<记忆条目>;

    /// 事件流_追加：append-only 时序事实（不更新不删除，SQLite 写事务天然串行互斥）
    /// 返回递增序号。时间戳由后端填充（SystemTime）。
    fn 事件流_追加(&mut self, 事件类型: &str, 内容: &str) -> Result<i64, 错误>;
    /// 事件流_区间：按序号区间读取（起..=止），返回 (序号, 时间戳, 事件类型, 内容)
    fn 事件流_区间(&self, 起: i64, 止: i64) -> Vec<(i64, String, String, String)>;
}

/// 检索接口（三维正交：范畴+阶段 / 档位 / 来源 / 四维拼装）
pub trait 记忆检索 {
    fn 按范畴阶段(&self, 范畴: 范畴, 阶段: 阶段) -> Vec<记忆条目>;
    fn 按档位(&self, 档位: 档位) -> Vec<记忆条目>;
    fn 按来源(&self, 来源: 来源) -> Vec<记忆条目>;
    fn 四维拼装(
        &self, 范畴: 范畴, 阶段: 阶段, 档位: 档位, 来源: 来源
    ) -> Vec<记忆条目>;
}

// ============================================================================
// 单元测试（Day 5：存储 + 检索）
// ============================================================================

#[cfg(test)]
mod 测试 {
    // 内存阁在存储操作殿下（六层返工后改用 crate:: 路径）
    use super::*;
    use crate::记忆存储_殿::内存存储_阁::内存存储;
    // 类型定义殿的符号（测试用到的枚举 + 判定函数 + 格位迭代）
    use crate::记忆类型_殿::{所有格位, 本质阶段合法性};

    #[test]
    fn 写入校验决策者必填() {
        let mut s = 内存存储::新建();
        let r = s.写入校验(
            范畴::目标,
            阶段::拍板,
            档位::权档,
            来源::LLM,
            "未来目标",
            "目标摘要",
            "",
            "法",
        );
        assert_eq!(r.unwrap_err(), 错误::缺失决策者);
    }

    #[test]
    fn 写入校验llm不可写经档() {
        let mut s = 内存存储::新建();
        let r = s.写入校验(
            范畴::目标,
            阶段::拍板,
            档位::经档,
            来源::LLM,
            "未来目标",
            "目标摘要",
            "界主",
            "法",
        );
        assert_eq!(
            r.unwrap_err(),
            错误::写入权限不足 {
                档位: 档位::经档,
                来源: 来源::LLM
            }
        );
    }

    #[test]
    fn 按范畴阶段检索命中() {
        let mut s = 内存存储::新建();
        s.写入校验(
            范畴::目标,
            阶段::拍板,
            档位::经档,
            来源::人类,
            "未来目标",
            "摘要",
            "界主",
            "法",
        )
        .unwrap();
        s.写入校验(
            范畴::规则,
            阶段::拍板,
            档位::经档,
            来源::人类,
            "禁止规则",
            "摘要",
            "界主",
            "法",
        )
        .unwrap();
        let 命中 = s.按范畴阶段(范畴::目标, 阶段::拍板);
        assert_eq!(命中.len(), 1);
        assert_eq!(命中[0].范畴, 范畴::目标);
    }

    #[test]
    fn 三维检索各档位命中() {
        let mut s = 内存存储::新建();
        s.写入校验(
            范畴::目标,
            阶段::拍板,
            档位::经档,
            来源::人类,
            "未来",
            "A",
            "界主",
            "法",
        )
        .unwrap();
        s.写入校验(
            范畴::规则,
            阶段::拍板,
            档位::权档,
            来源::LLM,
            "规则",
            "B",
            "界主",
            "法",
        )
        .unwrap();
        s.写入校验(
            范畴::自我,
            阶段::拍板,
            档位::行档,
            来源::人类,
            "我是",
            "C",
            "界主",
            "法",
        )
        .unwrap();
        assert_eq!(s.按档位(档位::经档).len(), 1);
        assert_eq!(s.按档位(档位::权档).len(), 1);
        assert_eq!(s.按档位(档位::行档).len(), 1);
        assert_eq!(s.按来源(来源::人类).len(), 2);
        assert_eq!(s.按来源(来源::LLM).len(), 1);
    }

    #[test]
    fn 四维拼装精确命中() {
        let mut s = 内存存储::新建();
        s.写入校验(
            范畴::目标,
            阶段::拍板,
            档位::经档,
            来源::人类,
            "未来目标 A",
            "A",
            "界主",
            "法",
        )
        .unwrap();
        // LLM 不能写经档，写权档
        s.写入校验(
            范畴::目标,
            阶段::拍板,
            档位::权档,
            来源::LLM,
            "未来目标 B",
            "B",
            "界主",
            "法",
        )
        .unwrap();
        let 命中 = s.四维拼装(范畴::目标, 阶段::拍板, 档位::经档, 来源::人类);
        assert_eq!(命中.len(), 1);
        assert_eq!(命中[0].来源, 来源::人类);
    }

    // ---------- 端到端：合法 18 格位全写入后检索命中 ----------
    // 注：falsifiable「36 格位利用率 ≥ 80%」通过 18 个合法格位 + 细分路径扩展达到；
    // 非法组合（如 目标/归档）需走格位路径的细分实现，阶段 3 暂只覆盖合法组合。

    #[test]
    fn 合法格位全写入后检索命中() {
        let mut s = 内存存储::新建();
        let mut 写入数 = 0;
        // 给每个合法的 (范畴, 阶段) 写一条经档条目
        for g in &所有格位 {
            if !本质阶段合法性(g.范畴, g.阶段) {
                continue;
            }
            let 内容 = match g.范畴 {
                范畴::目标 => format!("未来目标 {}", g.阶段.名称()),
                范畴::规则 => format!("必须禁止规则 {}", g.阶段.名称()),
                范畴::自我 => format!("我是身份角色 {}", g.阶段.名称()),
                范畴::程序 => format!("Cargo代码实现函数 {}", g.阶段.名称()),
                范畴::世界 => format!("环境系统状态 {}", g.阶段.名称()),
                范畴::经历 => format!("历史教训过去 {}", g.阶段.名称()),
            };
            match s.写入校验(
                g.范畴,
                g.阶段,
                档位::经档,
                来源::人类,
                内容,
                "摘要",
                "界主",
                "法",
            ) {
                Ok(_) => 写入数 += 1,
                Err(e) => panic!("写入失败 {:?}：{:?}", g, e),
            }
        }
        // 合法 23 格位全部写入（程序扩到全部 6 阶段）
        assert_eq!(写入数, 23);
        assert_eq!(s.查_全部().len(), 23);
        // 每个合法格位检索命中 1 条
        for g in &所有格位 {
            if !本质阶段合法性(g.范畴, g.阶段) {
                continue;
            }
            let 命中 = s.按范畴阶段(g.范畴, g.阶段);
            assert_eq!(命中.len(), 1, "{:?} 应命中 1 条", g);
        }
    }
}
