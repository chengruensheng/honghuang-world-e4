//! 双工流水线：前端执行 ∥ 后端整理（契约 §六/§七）
//!
//! 决策锚：260829-记忆架构契约 §六「双工流水线」+ §七「任务债务」
//! 可证伪：前端交付后债务 +1 且立即返回（不等待后端）；后端整理后债务 −1；无债不空转；
//! 债务超上限降级归档（跳过提炼、快照暂存待补）；水位峰值/谷值随交付归档涨落
//!
//! 语义：
//! - 前端交付即发即弃：账本_标记交付 后立即返回，从不等待后端
//! - 后端整理：从债务队列（账本_债务队列，先进先出）取最早一个已交付任务 → 归档
//! - 债务上限 + 降级：超限时后端跳过 LLM 提炼，完整快照暂存（标记待补提炼），不丢质量
//! - 债务监控：水位 / 峰值 / 高峰低谷标记
//! - 唯一共享 = 账本 + 格位存储，靠状态标记协作，不直接通信

use crate::记忆存储_殿::记忆存储;
use crate::记忆类型_殿::错误;

/// 整理结果：后端整理一个债务任务的产物
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum 整理结果 {
    正常归档(String), // 债务未超限，正常提炼回填后归档
    降级归档(String), // 债务超限，跳过提炼、完整快照暂存待补
}

/// 双工流水线：包装任意 记忆存储（账本），编排前端/后端双工
pub struct 双工流水线<S: 记忆存储> {
    存储: S,
    债务上限: i64,
    水位峰值: i64,
    水位谷值: i64,
}

impl<S: 记忆存储> 双工流水线<S> {
    /// 新建双工流水线（默认债务上限 10）
    pub fn 新建(存储: S) -> Self {
        Self::新建_带上限(存储, 10)
    }

    /// 新建双工流水线（指定债务上限）
    pub fn 新建_带上限(存储: S, 债务上限: i64) -> Self {
        Self {
            存储,
            债务上限,
            水位峰值: 0,
            水位谷值: 0,
        }
    }

    /// 前端_登记：新任务事件触发前端（账本_登记 幂等，登记为执行中）
    pub fn 前端_登记(&mut self, 任务标识: &str) -> Result<(), 错误> {
        self.存储.账本_登记(任务标识)
    }

    /// 前端_交付：终裁通过后标记交付，即发即弃（立即返回，从不等待后端）
    pub fn 前端_交付(&mut self, 任务标识: &str) -> Result<(), 错误> {
        self.存储.账本_标记交付(任务标识)
    }

    /// 后端_整理_一个：正常归档（无降级判定），返回任务标识（无债则 None）
    pub fn 后端_整理_一个(&mut self) -> Result<Option<String>, 错误> {
        match self.后端_整理_一个_带降级()? {
            Some(整理结果::正常归档(任务)) | Some(整理结果::降级归档(任务)) => {
                Ok(Some(任务))
            }
            None => Ok(None),
        }
    }

    /// 后端_整理_一个_带降级：取最早债务任务；债务超上限→降级归档（跳过提炼、快照暂存），否则正常归档
    pub fn 后端_整理_一个_带降级(&mut self) -> Result<Option<整理结果>, 错误> {
        self.后端_整理_一个_带整理(|_| true)
    }

    /// 后端_整理_一个_带整理：取最早债务任务；超限或整理失败→降级归档（快照暂存待补），否则正常归档
    ///
    /// 整理回调（提炼回填）：正常分支调用，返回 false 视为提炼失败→降级（完整快照暂存待补提炼）；
    /// 上层 worker 注入「LLM 提炼 + 回填器写格位」，把 §六 双工 与 §四 回填 串成后端闭环
    pub fn 后端_整理_一个_带整理(
        &mut self,
        mut 整理: impl FnMut(&str) -> bool,
    ) -> Result<Option<整理结果>, 错误> {
        let 队列 = self.存储.账本_债务队列()?;
        let 任务 = match 队列.into_iter().next() {
            Some(任务) => 任务,
            None => return Ok(None),
        };
        let 债务 = self.存储.账本_债务()?;
        // 监控：归档前水位更新（峰值/谷值）
        self.水位峰值 = self.水位峰值.max(债务);
        self.水位谷值 = self.水位谷值.min(债务);
        let 超限 = 债务 > self.债务上限;
        let 需降级 = 超限 || !整理(&任务);
        if 需降级 {
            // 完整快照持久化登记（契约 §六 降级快照持久化，进程重启不丢待补提炼）
            self.存储.快照_登记(&任务)?;
        }
        self.存储.账本_标记归档(&任务)?;
        Ok(Some(if 需降级 {
            整理结果::降级归档(任务)
        } else {
            整理结果::正常归档(任务)
        }))
    }

    /// 债务水位：已交付 − 已归档
    pub fn 债务(&self) -> Result<i64, 错误> {
        self.存储.账本_债务()
    }

    /// 债务队列：已交付未归档任务标识（先进先出，供监控/还债）
    pub fn 债务队列(&self) -> Result<Vec<String>, 错误> {
        self.存储.账本_债务队列()
    }

    /// 债务上限：超限触发降级
    pub fn 债务上限(&self) -> i64 {
        self.债务上限
    }

    /// 水位峰值：历史最高债务（归档前采样）
    pub fn 水位峰值(&self) -> i64 {
        self.水位峰值
    }

    /// 水位谷值：历史最低债务（归档前采样）
    pub fn 水位谷值(&self) -> i64 {
        self.水位谷值
    }

    /// 待补提炼：降级归档任务标识（完整快照持久化，跨进程恢复）
    pub fn 待补提炼(&self) -> Result<Vec<String>, 错误> {
        self.存储.快照_全部()
    }

    /// 高峰标记：当前债务 ≥ 上限一半（有债才算高峰）
    pub fn 处于高峰(&self) -> Result<bool, 错误> {
        let 债 = self.存储.账本_债务()?;
        Ok(债 > 0 && 债 >= self.债务上限 / 2)
    }

    /// 低谷标记：当前债务 == 0
    pub fn 处于低谷(&self) -> Result<bool, 错误> {
        Ok(self.存储.账本_债务()? == 0)
    }
}

