#[cfg(test)]
mod 测试 {
    use super::*;
    use crate::记忆存储_殿::内存存储_阁::内存存储;
    use crate::记忆存储_殿::SQLite存储_阁::SQLite存储;

    #[test]
    fn 双工_降级快照_持久库跨进程恢复() {
        let 库 = format!("降级快照持久化_{}.sq3", std::process::id());
        let _ = std::fs::remove_file(&库);
        {
            let 存储 = SQLite存储::文件新建(&库).unwrap();
            let mut 流 = 双工流水线::新建_带上限(存储, 1);
            for 任务 in ["任务甲", "任务乙"] {
                流.前端_登记(任务).unwrap();
                流.前端_交付(任务).unwrap();
            }
            // 债务 2 > 上限 1 → 降级归档 → 快照登记（持久化）
            let 结 = 流.后端_整理_一个_带降级().unwrap();
            assert!(matches!(结, Some(整理结果::降级归档(_))), "超限降级归档");
            assert_eq!(
                流.待补提炼().unwrap(),
                vec!["任务甲".to_string()],
                "任务甲进待补提炼快照"
            );
        }
        // 重新打开库（跨进程语义）：待补提炼快照持久化，不丢
        {
            let 存储 = SQLite存储::文件新建(&库).unwrap();
            let 流 = 双工流水线::新建_带上限(存储, 1);
            assert_eq!(
                流.待补提炼().unwrap(),
                vec!["任务甲".to_string()],
                "重新打开库后待补提炼快照不丢（降级快照持久化）"
            );
        }
        let _ = std::fs::remove_file(&库);
    }

    #[test]
    fn 双工_前端交付即发即弃债务加一() {
        let mut 流 = 双工流水线::新建(内存存储::新建());
        流.前端_登记("任务甲").unwrap();
        流.前端_交付("任务甲").unwrap();
        assert_eq!(流.债务().unwrap(), 1, "交付后债务=1");
    }

    #[test]
    fn 双工_后端整理一个先进先出债务减一() {
        let mut 流 = 双工流水线::新建(内存存储::新建());
        流.前端_登记("任务甲").unwrap();
        流.前端_登记("任务乙").unwrap();
        流.前端_交付("任务甲").unwrap();
        流.前端_交付("任务乙").unwrap();
        assert_eq!(流.债务().unwrap(), 2);
        let 归 = 流.后端_整理_一个().unwrap();
        assert_eq!(归.as_deref(), Some("任务甲"), "先进先出：先交付先归档");
        assert_eq!(流.债务().unwrap(), 1);
    }

    #[test]
    fn 双工_无债不空转() {
        let mut 流 = 双工流水线::新建(内存存储::新建());
        assert_eq!(流.后端_整理_一个().unwrap(), None, "无债返回 None 不空转");
    }

    #[test]
    fn 双工_债务超上限降级归档() {
        let mut 流 = 双工流水线::新建_带上限(内存存储::新建(), 2);
        for 任务 in ["任务甲", "任务乙", "任务丙"] {
            流.前端_登记(任务).unwrap();
            流.前端_交付(任务).unwrap();
        }
        // 债务 = 3 > 上限 2 → 降级归档
        let 结 = 流.后端_整理_一个_带降级().unwrap();
        assert!(matches!(结, Some(整理结果::降级归档(_))), "超限降级归档");
        assert_eq!(
            流.待补提炼().unwrap(),
            vec!["任务甲".to_string()],
            "降级任务进待补提炼快照"
        );
    }

    #[test]
    fn 双工_债务未超限正常归档() {
        let mut 流 = 双工流水线::新建_带上限(内存存储::新建(), 10);
        流.前端_登记("任务甲").unwrap();
        流.前端_交付("任务甲").unwrap();
        let 结 = 流.后端_整理_一个_带降级().unwrap();
        assert!(matches!(结, Some(整理结果::正常归档(_))), "未超限正常归档");
        assert!(流.待补提炼().unwrap().is_empty());
    }

    #[test]
    fn 双工_水位峰值谷值与高峰低谷标记() {
        let mut 流 = 双工流水线::新建_带上限(内存存储::新建(), 4);
        for 任务 in ["任务甲", "任务乙", "任务丙"] {
            流.前端_登记(任务).unwrap();
            流.前端_交付(任务).unwrap();
        }
        // 债务 3（≥ 上限 4 的一半 2 → 高峰）
        assert!(流.处于高峰().unwrap(), "债务 3 应处高峰");
        流.后端_整理_一个_带降级().unwrap();
        assert_eq!(流.水位峰值(), 3, "归档前水位 3 记入峰值");
        流.后端_整理_一个_带降级().unwrap();
        流.后端_整理_一个_带降级().unwrap();
        assert_eq!(流.水位谷值(), 0, "债务清零记入谷值");
        assert!(流.处于低谷().unwrap(), "债务清零应处低谷");
    }
}
