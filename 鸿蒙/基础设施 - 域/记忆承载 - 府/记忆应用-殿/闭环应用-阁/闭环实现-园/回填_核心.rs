//! 回填：交付才回填，两步分离（契约 §四）
//!
//! 决策锚：260829-记忆架构契约 §四「回填机制」
//! 可证伪：回填前无块；回填后按类别写预期格位；同任务同格位幂等覆盖、不同格位各自独立；元决策隔离带注脚

use super::闭环_核心::格位中枢;
use crate::记忆存储_殿::记忆存储;
use crate::记忆类型_殿::{
    内容类别, 总纲, 本质, 来源, 格位, 档位, 记忆ID, 错误, 阶段
};

/// 归类映射：内容类别 → 格位列表（一任务多格位，确定性归类，写入时归类 O(1) 无损）
pub fn 归类(类别: 内容类别) -> Vec<格位> {
    match 类别 {
        内容类别::决策 => vec![
            格位 {
                总纲: 总纲::目标,
                本质: 本质::当前,
            },
            格位 {
                总纲: 总纲::目标,
                本质: 本质::优先级,
            },
            格位 {
                总纲: 总纲::目标,
                本质: 本质::风险,
            },
        ],
        内容类别::设计 => vec![格位 {
            总纲: 总纲::执行,
            本质: 本质::步骤,
        }],
        内容类别::代码 => vec![格位 {
            总纲: 总纲::执行,
            本质: 本质::产出,
        }],
        内容类别::验收 => vec![格位 {
            总纲: 总纲::执行,
            本质: 本质::验证,
        }],
        内容类别::教训 => vec![格位 {
            总纲: 总纲::经历,
            本质: 本质::教训,
        }],
        内容类别::规则修正 => vec![格位 {
            总纲: 总纲::规则,
            本质: 本质::规范,
        }],
        内容类别::文档 => vec![格位 {
            总纲: 总纲::外在,
            本质: 本质::数据,
        }],
        内容类别::元决策 => vec![
            格位 {
                总纲: 总纲::规则,
                本质: 本质::规范,
            },
            格位 {
                总纲: 总纲::经历,
                本质: 本质::决策,
            },
        ],
    }
}

/// 回填器：包装 格位中枢，交付后执行「提炼 → 归类写格位」两步
pub struct 回填器<S: 记忆存储> {
    中枢: 格位中枢<S>,
}

impl<S: 记忆存储> 回填器<S> {
    pub fn 新建(中枢: 格位中枢<S>) -> Self {
        Self { 中枢 }
    }

    /// 回填：两步——①提炼（可注入，真实=LLM，测试=确定性）②归类写格位（幂等，一任务多格位）
    pub fn 回填(
        &mut self,
        类别: 内容类别,
        临时上下文: &str,
        绑定任务: &str,
        decided_by: &str,
        提炼: impl Fn(&str) -> String,
    ) -> Result<Vec<记忆ID>, 错误> {
        let 精炼 = 提炼(临时上下文);
        let 格位们 = 归类(类别);
        let mut 结果 = Vec::new();
        for 格位 in 格位们 {
            let id = self.中枢.写入_格位_幂等(
                格位,
                阶段::归档,
                &精炼,
                绑定任务,
                档位::行档,
                来源::LLM,
                decided_by,
                "鉴·回填",
                绑定任务,
            )?;
            结果.push(id);
        }
        // 元决策隔离：块加「元决策」注脚标记
        if 类别 == 内容类别::元决策 {
            for 格位 in 归类(内容类别::元决策) {
                self.中枢.标注_注脚_格位(格位, 绑定任务, "元决策")?;
            }
        }
        Ok(结果)
    }
}

// ============================================================================
