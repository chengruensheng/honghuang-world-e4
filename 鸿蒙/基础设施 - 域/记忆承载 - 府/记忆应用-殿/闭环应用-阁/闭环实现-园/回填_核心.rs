#[cfg(test)]
mod 测试 {
    use super::*;
    use crate::记忆存储_殿::内存存储_阁::内存存储;

    fn 器() -> 回填器<内存存储> {
        回填器::新建(格位中枢::新建(内存存储::新建()))
    }

    #[test]
    fn 归类_决策映射三格位() {
        let 格位们 = 归类(内容类别::决策);
        assert_eq!(格位们.len(), 3);
        assert_eq!(格位们[0].总纲, 总纲::目标);
        assert_eq!(格位们[0].本质, 本质::当前);
        assert_eq!(格位们[2].本质, 本质::风险);
    }

    #[test]
    fn 回填_提炼归类写格位() {
        let mut 器 = 器();
        let ids = 器
            .回填(
                内容类别::决策,
                "原始上下文带噪声",
                "任务X",
                "界主",
                |_| "精炼决策".to_string(),
            )
            .unwrap();
        assert_eq!(ids.len(), 3, "决策一任务回填 3 格位");
    }

    #[test]
    fn 回填_同任务同格位幂等覆盖() {
        let mut 器 = 器();
        器.回填(
            内容类别::设计,
            "第一次",
            "任务Y",
            "界主",
            |_| "步骤一".to_string(),
        )
        .unwrap();
        器.回填(
            内容类别::设计,
            "第二次",
            "任务Y",
            "界主",
            |_| "步骤二".to_string(),
        )
        .unwrap();
        let 分区 = 器.中枢.读取_格位_分区(格位 {
            总纲: 总纲::执行,
            本质: 本质::步骤,
        });
        assert_eq!(分区.len(), 1, "同任务同格位覆盖不新增");
        assert_eq!(分区[0].内容, "步骤二");
    }

    #[test]
    fn 回填_元决策带注脚() {
        let mut 器 = 器();
        器.回填(
            内容类别::元决策,
            "裁决",
            "任务Z",
            "界主",
            |_| "元决策内容".to_string(),
        )
        .unwrap();
        let 规范分区 = 器.中枢.读取_格位_分区(格位 {
            总纲: 总纲::规则,
            本质: 本质::规范,
        });
        assert_eq!(规范分区[0].块元数据.as_ref().unwrap().注脚, "元决策");
    }
}
