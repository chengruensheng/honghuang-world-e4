//! 记忆应用-殿 · 闭环实现-园 - 36 格位写入/读取闭环 API
//!
//! 决策锚：260827-AI助手自给自足 Step2（传承殿/10-地基/25-AI助手自给自足-实施方案.md）
//! falsifiable：①非法格位写入被拒（本质阶段不匹配）；②任务描述→相关格位读取命中
//!
//! 机制（AI 自给自足闭环）：任务进来 → 读取_相关格位 匹配相关范畴 → AI 组合心智模型
//! → 执行后 写入_格位 沉淀回 36 格位

use crate::记忆存储_殿::记忆存储;
use crate::记忆类型_殿::{
    所有范畴, 本质阶段合法性, 来源, 格位, 档位, 范畴, 记忆ID, 记忆条目, 错误,
};

/// 36 格位闭环中枢：写入_格位 / 读取_相关格位
pub struct 格位中枢<S: 记忆存储> {
    存储: S,
    下个编号: u64,
}

impl<S: 记忆存储> 格位中枢<S> {
    /// 新建中枢（包装任意 记忆存储 实现）
    pub fn 新建(存储: S) -> Self {
        Self {
            存储, 下个编号: 1
        }
    }

    /// 底层存储访问（供扩展）
    pub fn 存储(&self) -> &S {
        &self.存储
    }

    /// 写入_格位：向指定格位（范畴×阶段）写一条记忆
    ///
    /// 三层防护：①本质×阶段合法性（非法格位拒绝）；②decided_by 必填；③档位权限（LLM 不写经档）
    pub fn 写入_格位(
        &mut self,
        格位: 格位,
        内容: &str,
        摘要: &str,
        档位: 档位,
        来源: 来源,
        decided_by: &str,
        implements: &str,
    ) -> Result<记忆ID, 错误> {
        // ① 本质×阶段合法性（非法格位拒绝）
        if !本质阶段合法性(格位.范畴, 格位.阶段) {
            return Err(错误::本质阶段不匹配 {
                范畴: 格位.范畴,
                阶段: 格位.阶段,
            });
        }
        // ② 决策者必填
        if decided_by.trim().is_empty() {
            return Err(错误::缺失决策者);
        }
        // ③ 档位权限：LLM 不能写经档
        if 来源 == 来源::LLM && 档位 == 档位::经档 {
            return Err(错误::写入权限不足 { 档位, 来源 });
        }
        let id = 记忆ID(self.下个编号);
        let 条目 = 记忆条目::新建(
            id.0,
            格位.范畴,
            格位.阶段,
            档位,
            来源,
            内容,
            摘要,
            decided_by,
            implements,
        );
        self.存储.写(条目)?;
        self.下个编号 += 1;
        Ok(id)
    }

    /// 读取_相关格位：按任务描述匹配相关范畴，返回这些格位内的全部记忆
    ///
    /// 无关键词命中时返回全部记忆（AI 兜底拿到完整上下文）
    pub fn 读取_相关格位(&self, 任务描述: &str) -> Vec<记忆条目> {
        let 相关范畴 = 匹配范畴(任务描述);
        let 全部 = self.存储.查_全部();
        if 相关范畴.is_empty() {
            return 全部;
        }
        全部
            .into_iter()
            .filter(|e| 相关范畴.contains(&e.范畴))
            .collect()
    }
}

/// 任务描述 → 相关范畴（中文关键词匹配；Cargo/LLM/tag 为白名单标准词）
fn 匹配范畴(任务描述: &str) -> Vec<范畴> {
    let mut 命中 = Vec::new();
    for 范畴 in 所有范畴 {
        let 关键词: &[&str] = match 范畴 {
            范畴::目标 => &["目标", "目的", "愿望", "计划", "指标"],
            范畴::规则 => &["规则", "必须", "禁止", "约束", "铁律", "标准"],
            范畴::自我 => &["自我", "身份", "角色", "我是", "能力"],
            范畴::程序 => &["程序", "代码", "实现", "函数", "测试", "Cargo", "crate"],
            范畴::世界 => &["世界", "环境", "状态", "门禁", "构建", "版本", "tag"],
            范畴::经历 => &["经历", "教训", "历史", "过去", "踩坑", "经验"],
        };
        if 关键词.iter().any(|k| 任务描述.contains(k)) {
            命中.push(范畴);
        }
    }
    命中
}

