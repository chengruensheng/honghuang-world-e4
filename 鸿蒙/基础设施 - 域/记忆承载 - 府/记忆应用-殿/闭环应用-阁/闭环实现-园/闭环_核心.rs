    fn 分区检索按ID降序最近优先() {
        let mut 中枢 = 中枢();
        for 摘要 in ["首条", "次条", "最新"] {
            中枢
                .写入_格位(
                    格位 {
                        范畴: 范畴::经历,
                        阶段: 阶段::归档,
                    },
                    摘要,
                    摘要,
                    档位::行档,
                    来源::代码,
                    "界主",
                    "法",
                )
                .unwrap();
        }
        let 分区 = 中枢.读取_格位_分区(格位 {
            范畴: 范畴::经历,
            阶段: 阶段::归档,
        });
        assert_eq!(分区.len(), 3);
        assert_eq!(分区[0].内容, "最新", "ID 降序 → 最近优先");
        assert_eq!(分区[2].内容, "首条");
    }
