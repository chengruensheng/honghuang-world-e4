#[cfg(test)]
#[allow(non_snake_case)] // 中文函数名 + 标准缩写（ID/LLM）刻意保留
mod 测试 {
    use super::*;
    use crate::记忆存储_殿::内存存储_阁::内存存储;
    use crate::记忆类型_殿::阶段;

    fn 中枢() -> 格位中枢<内存存储> {
        格位中枢::新建(内存存储::新建())
    }

    #[test]
    fn 写入格位成功并返回ID() {
        let mut 中枢 = 中枢();
        let id = 中枢
            .写入_格位(
                格位 {
                    范畴: 范畴::目标,
                    阶段: 阶段::拍板,
                },
                "统一六层风格目标",
                "21/21 crate ≥2 殿",
                档位::经档,
                来源::人类,
                "界主",
                "术·分层",
            )
            .unwrap();
        assert_eq!(id, 记忆ID(1));
        let 全部 = 中枢.读取_相关格位("目标");
        assert_eq!(全部.len(), 1);
        assert_eq!(全部[0].内容, "统一六层风格目标");
    }

    #[test]
    fn 非法格位写入被拒() {
        // 目标/归档 本质×阶段不合法 → 拒绝
        let mut 中枢 = 中枢();
        let r = 中枢.写入_格位(
            格位 {
                范畴: 范畴::目标,
                阶段: 阶段::归档,
            },
            "非法内容",
            "摘要",
            档位::经档,
            来源::人类,
            "界主",
            "法",
        );
        assert!(matches!(r, Err(错误::本质阶段不匹配 { .. })));
    }

    #[test]
    fn 缺决策者写入被拒() {
        let mut 中枢 = 中枢();
        let r = 中枢.写入_格位(
            格位 {
                范畴: 范畴::规则,
                阶段: 阶段::拍板,
            },
            "规则",
            "摘要",
            档位::经档,
            来源::人类,
            "",
            "法",
        );
        assert_eq!(r.unwrap_err(), 错误::缺失决策者);
    }

    #[test]
    fn llm不可写经档() {
        let mut 中枢 = 中枢();
        let r = 中枢.写入_格位(
            格位 {
                范畴: 范畴::规则,
                阶段: 阶段::拍板,
            },
            "规则",
            "摘要",
            档位::经档,
            来源::LLM,
            "界主",
            "法",
        );
        assert_eq!(
            r.unwrap_err(),
            错误::写入权限不足 {
                档位: 档位::经档,
                来源: 来源::LLM
            }
        );
    }

    #[test]
    fn 读取相关格位按关键词命中() {
        let mut 中枢 = 中枢();
        中枢
            .写入_格位(
                格位 {
                    范畴: 范畴::程序,
                    阶段: 阶段::实施,
                },
                "命名门禁规则",
                "祖孙判据",
                档位::权档,
                来源::LLM,
                "界主",
                "鉴·门禁",
            )
            .unwrap();
        中枢
            .写入_格位(
                格位 {
                    范畴: 范畴::世界,
                    阶段: 阶段::验收,
                },
                "一键全验 13 项",
                "13/13 门禁全绿",
                档位::行档,
                来源::代码,
                "界主",
                "术·DSH",
            )
            .unwrap();
        let 命中 = 中枢.读取_相关格位("实现 Cargo 测试");
        assert_eq!(命中.len(), 1);
        assert_eq!(命中[0].范畴, 范畴::程序);
    }

    #[test]
    fn 无关键词命中返回全部() {
        let mut 中枢 = 中枢();
        中枢
            .写入_格位(
                格位 {
                    范畴: 范畴::程序,
                    阶段: 阶段::实施,
                },
                "代码实现",
                "摘要",
                档位::权档,
                来源::LLM,
                "界主",
                "法",
            )
            .unwrap();
        中枢
            .写入_格位(
                格位 {
                    范畴: 范畴::世界,
                    阶段: 阶段::验收,
                },
                "世界状态",
                "摘要",
                档位::行档,
                来源::代码,
                "界主",
                "法",
            )
            .unwrap();
        let 全部 = 中枢.读取_相关格位("与记忆无关的未知词");
        assert_eq!(全部.len(), 2);
    }
}
