/// 关键词表：任务描述 → 相关范畴 的可配置关键词映射
///
/// 默认表内嵌 6 范畴中文关键词（Cargo/LLM/tag 为白名单标准词）；
/// 可 增加关键词 定制，供 读取_相关格位_按表 使用
pub struct 关键词表 {
    词表: Vec<(范畴, Vec<String>)>,
}

impl 关键词表 {
    /// 默认关键词表（与历史 匹配范畴 行为完全一致）
    pub fn 默认() -> Self {
        fn 词(列表: &[&str]) -> Vec<String> {
            列表.iter().map(|s| s.to_string()).collect()
        }
        let 词表 = vec![
            (范畴::目标, 词(&["目标", "目的", "愿望", "计划", "指标"])),
            (
                范畴::规则,
                词(&["规则", "必须", "禁止", "约束", "铁律", "标准"]),
            ),
            (范畴::自我, 词(&["自我", "身份", "角色", "我是", "能力"])),
            (
                范畴::程序,
                词(&["程序", "代码", "实现", "函数", "测试", "Cargo", "crate"]),
            ),
            (
                范畴::世界,
                词(&["世界", "环境", "状态", "门禁", "构建", "版本", "tag"]),
            ),
            (
                范畴::经历,
                词(&["经历", "教训", "历史", "过去", "踩坑", "经验"]),
            ),
        ];
        Self { 词表 }
    }

    /// 为某范畴增加一个关键词（可重复调用；相同词自动去重）
    pub fn 增加关键词(&mut self, 范畴: 范畴, 关键词: &str) {
        if 关键词.trim().is_empty() {
            return;
        }
        let 词 = 关键词.trim().to_string();
        if let Some(条目) = self.词表.iter_mut().find(|(c, _)| *c == 范畴) {
            if !条目.1.contains(&词) {
                条目.1.push(词);
            }
        } else {
            self.词表.push((范畴, vec![词]));
        }
    }

    /// 任务描述 → 相关范畴（按本表关键词匹配）
    pub fn 匹配(&self, 任务描述: &str) -> Vec<范畴> {
        let mut 命中 = Vec::new();
        for (范畴, 关键词) in &self.词表 {
            if 关键词.iter().any(|k| 任务描述.contains(k.as_str())) {
                命中.push(*范畴);
            }
        }
        命中
    }
}

/// 36 格位闭环中枢：写入_格位 / 读取_相关格位
pub struct 格位中枢<S: 记忆存储> {
    存储: S,
    下个编号: u64,
}

impl<S: 记忆存储> 格位中枢<S> {
    /// 新建中枢（包装任意 记忆存储 实现）
    ///
    /// 文件库自动续接已有最大编号：避免每次新建都从 1 编号导致 INSERT OR REPLACE 覆盖旧条目
    pub fn 新建(存储: S) -> Self {
        let 下个编号 = 存储
            .查_全部()
            .iter()
            .map(|条目| 条目.id.0)
            .max()
            .unwrap_or(0)
            + 1;
        Self {
            存储, 下个编号
        }
    }

    /// 底层存储访问（供扩展）
    pub fn 存储(&self) -> &S {
        &self.存储
    }

    /// 写入_格位：向指定格位（范畴×阶段）写一条记忆
    ///
    /// 三层防护：①本质×阶段合法性（非法格位拒绝）；②decided_by 必填；③档位权限（LLM 不写经档）
    pub fn 写入_格位(
        &mut self,
        格位: 格位,
        内容: &str,
        摘要: &str,
        档位: 档位,
        来源: 来源,
        decided_by: &str,
        implements: &str,
    ) -> Result<记忆ID, 错误> {
        // ① 本质×阶段合法性（非法格位拒绝）
        if !本质阶段合法性(格位.范畴, 格位.阶段) {
            return Err(错误::本质阶段不匹配 {
                范畴: 格位.范畴,
                阶段: 格位.阶段,
            });
        }
        // ② 决策者必填
        if decided_by.trim().is_empty() {
            return Err(错误::缺失决策者);
        }
        // ③ 档位权限：LLM 不能写经档
        if 来源 == 来源::LLM && 档位 == 档位::经档 {
            return Err(错误::写入权限不足 { 档位, 来源 });
        }
        let id = 记忆ID(self.下个编号);
        let 条目 = 记忆条目::新建(
            id.0,
            格位.范畴,
            格位.阶段,
            档位,
            来源,
            内容,
            摘要,
            decided_by,
            implements,
        );
        self.存储.写(条目)?;
        self.下个编号 += 1;
        Ok(id)
    }

    /// 读取_相关格位：按任务描述匹配相关范畴，返回这些格位内的全部记忆
    ///
    /// 无关键词命中时返回全部记忆（AI 兜底拿到完整上下文）
    pub fn 读取_相关格位(&self, 任务描述: &str) -> Vec<记忆条目> {
        self.读取_相关格位_按表(任务描述, &关键词表::默认())
    }

    /// 读取_相关格位_按表：按自定义关键词表匹配相关范畴
    ///
    /// 无关键词命中时返回全部记忆（AI 兜底拿到完整上下文）
    pub fn 读取_相关格位_按表(
        &self, 任务描述: &str, 表: &关键词表
    ) -> Vec<记忆条目> {
        let 相关范畴 = 表.匹配(任务描述);
        let 全部 = self.存储.查_全部();
        if 相关范畴.is_empty() {
            return 全部;
        }
        全部
            .into_iter()
            .filter(|e| 相关范畴.contains(&e.范畴))
            .collect()
    }

    /// 读取_格位_分区：精确检索单一格位仓库（范畴×阶段）内的全部记忆
    ///
    /// 36 格位 = 36 个可独立深挖的仓库（按需启用）；结果按 ID 降序（最近优先）。
    /// falsifiable：写 A 格位 → 读 A 分区含该条、读 B 分区不含（同范畴不同阶段隔离）
    pub fn 读取_格位_分区(&self, 格位: 格位) -> Vec<记忆条目> {
        let mut 命中: Vec<记忆条目> = self
            .存储
            .查_全部()
            .into_iter()
            .filter(|e| e.范畴 == 格位.范畴 && e.阶段 == 格位.阶段)
            .collect();
        命中.sort_by_key(|e| std::cmp::Reverse(e.id.0));
        命中
    }

    /// 永驻摘要：36 格位各取最近 1 条（ID 最大），组合成心智模型摘要
    ///
    /// falsifiable：空库 → 36 行全空；写 5 格位 → 36 行中 5 行有内容；同格位 2 条 → 只取最近
    pub fn 永驻摘要(&self) -> Vec<String> {
        let 全部 = self.存储.查_全部();
        let mut 行 = Vec::with_capacity(36);
        for 格位 in 所有格位 {
            let 摘要 = 全部
                .iter()
                .filter(|e| e.范畴 == 格位.范畴 && e.阶段 == 格位.阶段)
                .max_by_key(|e| e.id.0)
                .map(|e| e.摘要.clone())
                .unwrap_or_default();
            行.push(format!(
                "[{}·{}] {}",
                格位.范畴.名称(),
                格位.阶段.名称(),
                摘要
            ));
        }
        行
    }
}

