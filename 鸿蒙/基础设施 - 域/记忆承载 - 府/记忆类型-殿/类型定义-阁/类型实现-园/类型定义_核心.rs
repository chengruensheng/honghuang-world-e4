/// 决策锚：100项任务 任务20 阶段转移判定器显式化（正向推进 + 打回回退 + 归档终态）。
/// 纯函数：同输入同输出，logicprobe 可验证无死锁。
pub fn 阶段可推进(当前: 阶段) -> Option<阶段> {
    use 阶段::*;
    match 当前 {
        提案 => Some(审阅),
        审阅 => Some(拍板),
        拍板 => Some(实施),
        实施 => Some(验收),
        验收 => Some(归档),
        归档 => None,
    }
}

/// 阶段可转移：决策状态机合法转移（正向推进 + 单步打回回退），归档终态不再转移
///
/// 打回语义：审阅不过→退回提案、拍板不过→退回审阅、验收不过→退回实施（只回退一步，不跳层）。
/// 失败/废弃不在此维度（由 生效状态::废止 + 废弃触发源 表达，与阶段正交）。
pub fn 阶段可转移(当前: 阶段, 下一: 阶段) -> bool {
    use 阶段::*;
    matches!(
        (当前, 下一),
        (提案, 审阅)
            | (审阅, 拍板)
            | (拍板, 实施)
            | (实施, 验收)
            | (验收, 归档)
            | (审阅, 提案)
            | (拍板, 审阅)
            | (验收, 实施)
    )
}

