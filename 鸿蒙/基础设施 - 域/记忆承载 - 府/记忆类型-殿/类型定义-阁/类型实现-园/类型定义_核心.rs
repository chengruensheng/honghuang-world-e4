    #[test]
    fn 算条目哈希_确定性_同输入同哈希不同输入不同哈希() {
        // 契约 §九 条目哈希：64-bit FNV-1a，确定性（同输入同哈希），字段敏感（不同输入不同哈希）
        let 甲 = 算条目哈希(
            1,
            总纲::执行,
            本质::产出,
            阶段::验收,
            档位::行档,
            来源::代码,
            "内容",
            "大罗",
        );
        let 甲复 = 算条目哈希(
            1,
            总纲::执行,
            本质::产出,
            阶段::验收,
            档位::行档,
            来源::代码,
            "内容",
            "大罗",
        );
        assert_eq!(甲, 甲复, "同输入同哈希（确定性）");
        let 乙 = 算条目哈希(
            2,
            总纲::执行,
            本质::产出,
            阶段::验收,
            档位::行档,
            来源::代码,
            "内容",
            "大罗",
        );
        assert_ne!(甲, 乙, "不同 id 不同哈希");
        let 丙 = 算条目哈希(
            1,
            总纲::执行,
            本质::产出,
            阶段::验收,
            档位::行档,
            来源::代码,
            "内容改",
            "大罗",
        );
        assert_ne!(甲, 丙, "不同内容不同哈希");
        let 丁 = 算条目哈希(
            1,
            总纲::执行,
            本质::产出,
            阶段::验收,
            档位::行档,
            来源::代码,
            "内容",
            "大罗改",
        );
        assert_ne!(甲, 丁, "不同 decided_by 不同哈希");
    }
