// 第一层（防污染）：本质 enum 的 36 个变体（编译期隔离）。
// 另按 6 总纲提供 wrapper 类型，禁止跨总纲赋值。

pub struct 内部条目(pub 记忆条目);
pub struct 外在条目(pub 记忆条目);
pub struct 规则条目(pub 记忆条目);
pub struct 执行条目(pub 记忆条目);
pub struct 目标条目(pub 记忆条目);
pub struct 经历条目(pub 记忆条目);

/// 第二层（防漂移）：格位路径（前 2 段 = 36 格位之一，可继续细分）
pub type 格位路径 = Vec<String>;

/// 构造格位路径（自动继承父的总纲 + 本质）
pub fn 格位路径_构造(总纲: 总纲, 本质: 本质, 细分: &[&str]) -> 格位路径 {
    let mut 路径 = vec![总纲.名称().to_string(), 本质.名称().to_string()];
    路径.extend(细分.iter().map(|s| s.to_string()));
    路径
}

/// 提取格位路径的"父格位"（前 2 段）
pub fn 格位路径_父格位(路径: &格位路径) -> Option<格位> {
    if 路径.len() < 2 {
        return None;
    }
    let 总纲 = match 路径[0].as_str() {
        "内部" => 总纲::内部,
        "外在" => 总纲::外在,
        "规则" => 总纲::规则,
        "执行" => 总纲::执行,
        "目标" => 总纲::目标,
        "经历" => 总纲::经历,
        _ => return None,
    };
    let 本质 = 所有本质
        .iter()
        .copied()
        .find(|b| b.名称() == 路径[1].as_str())?;
    Some(格位::新建(总纲, 本质))
}

/// 验证格位路径合法性（前 2 段必须是有效总纲 + 本质）
pub fn 格位路径_验证(路径: &格位路径) -> Result<(), 错误> {
    if 格位路径_父格位(路径).is_none() {
        return Err(错误::格位路径非法(路径.join("/")));
    }
    Ok(())
}

