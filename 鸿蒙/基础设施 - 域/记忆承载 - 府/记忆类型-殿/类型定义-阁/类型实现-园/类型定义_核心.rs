/// 总纲 × 本质 归属校验（本质必须属于该总纲的 6 个专属本质）
///
/// 按"验证分离"原则：写入接口做校验，LLM 只生成内容——LLM 不能决定本质归属。
/// 36 词以 03-记忆.md §2.3 实测为准（带总纲前缀 36/36 全对）。
pub fn 本质归属(总纲: 总纲, 本质: 本质) -> bool {
    matches!(
        (总纲, 本质),
        (
            总纲::内部,
            本质::角色 | 本质::能力 | 本质::职责 | 本质::状态 | 本质::记忆 | 本质::边界
        ) | (
            总纲::外在,
            本质::定位 | 本质::结构 | 本质::依赖 | 本质::接口 | 本质::环境 | 本质::数据
        ) | (
            总纲::规则,
            本质::禁止 | 本质::门禁 | 本质::规范 | 本质::流程 | 本质::例外 | 本质::红线
        ) | (
            总纲::执行,
            本质::命令 | 本质::技术栈 | 本质::步骤 | 本质::工具 | 本质::验证 | 本质::产出
        ) | (
            总纲::目标,
            本质::当前 | 本质::未来 | 本质::里程碑 | 本质::验收 | 本质::优先级 | 本质::风险
        ) | (
            总纲::经历,
            本质::事件 | 本质::教训 | 本质::决策 | 本质::来源 | 本质::时间 | 本质::归档
        )
    )
}

/// 内容总纲一致性（启发式：含某些关键词应归某总纲）
pub fn 内容总纲一致(内容: &str, 声称总纲: 总纲) -> bool {
    match 声称总纲 {
        总纲::内部 => 内容.contains("我是") || 内容.contains("身份") || 内容.contains("角色"),
        总纲::外在 => 内容.contains("结构") || 内容.contains("依赖") || 内容.contains("目录"),
        总纲::规则 => 内容.contains("必须") || 内容.contains("禁止") || 内容.contains("门禁"),
        总纲::执行 => 内容.contains("命令") || 内容.contains("构建") || 内容.contains("技术栈"),
        总纲::目标 => 内容.contains("目标") || 内容.contains("未来") || 内容.contains("阶段"),
        总纲::经历 => 内容.contains("已发生") || 内容.contains("历史") || 内容.contains("教训"),
    }
}

/// 本质判定校验（程序化规则，不让 LLM 推断）
pub fn 判定本质校验(
    内容: &str, 声称总纲: 总纲, 声称本质: 本质
) -> Result<(), 错误> {
    if !本质归属(声称总纲, 声称本质) {
        return Err(错误::总纲本质不匹配 {
            总纲: 声称总纲,
            本质: 声称本质,
        });
    }
    if !内容总纲一致(内容, 声称总纲) {
        return Err(错误::内容总纲不一致 {
            总纲: 声称总纲
        });
    }
    Ok(())
}

/// 档位允许写入检查（02-概念/记忆 § 2.3）
pub fn 档位_允许写入(档位: 档位, 来源: 来源) -> bool {
    match (档位, 来源) {
        (档位::经档, 来源::人类) => true, // 界主可写经档
        (档位::经档, 来源::代码) => true, // 代码生成经档（lint 派生）
        (档位::经档, 来源::LLM) => false, // LLM 不能直写经档
        (档位::权档, _) => true,          // 权档所有来源可写
        (档位::行档, _) => true,          // 行档所有来源可写
    }
}

