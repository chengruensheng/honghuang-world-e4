/// 6 总纲（格位第一维）——系统关心什么
///
/// 永久固定，不可新立、不可合并、不可废弃（02-概念/记忆 §2.2）
/// 内/外归属由总纲决定（§2.3 实测：带总纲 36/36 全对，脱离总纲仅 24/36）。
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum 总纲 {
    /// 内部·我：AI 自己的角色/能力/职责/状态/记忆/边界
    内部,
    /// 外在·项目：项目的定位/结构/依赖/接口/环境/数据
    外在,
    /// 规则·约束：必须遵守的禁止/门禁/规范/流程/例外/红线
    规则,
    /// 执行·行动：怎么做的命令/技术栈/步骤/工具/验证/产出
    执行,
    /// 目标·方向：往哪走的当前/未来/里程碑/验收/优先级/风险
    目标,
    /// 经历·历史：已经发生的事件/教训/决策/来源/时间/归档
    经历,
}

/// 总纲枚举数量（6）
pub const 总纲数: usize = 6;

/// 所有总纲（迭代顺序固定）
pub const 所有总纲: [总纲; 总纲数] = [
    总纲::内部,
    总纲::外在,
    总纲::规则,
    总纲::执行,
    总纲::目标,
    总纲::经历,
];

impl 总纲 {
    /// 返回中文名（用于序列化/日志/格位路径）
    pub fn 名称(self) -> &'static str {
        match self {
            总纲::内部 => "内部",
            总纲::外在 => "外在",
            总纲::规则 => "规则",
            总纲::执行 => "执行",
            总纲::目标 => "目标",
            总纲::经历 => "经历",
        }
    }

    /// 门面能力声明：6 总纲答「能干什么」（大队长层，只写能力声明不重复格位内容，性格各异正交）
    ///
    /// 决策锚：36格位三层问答语义（大队长=门面=6总纲；小队长=格位=36；士兵=块按需下探）。
    pub fn 门面(self) -> &'static str {
        match self {
            总纲::内部 => "我能告诉你：我是谁、我的角色、能力与局限（内部·我）。",
            总纲::外在 => "我能告诉你：项目定位、结构、依赖、接口、环境与数据（外在·项目）。",
            总纲::规则 => {
                "我能告诉你：什么能做、什么不能做、规范、流程、例外与红线（规则·约束）。"
            }
            总纲::执行 => {
                "我能告诉你：怎么做、命令、技术栈、步骤、工具、验证与产出（执行·行动）。"
            }
            总纲::目标 => {
                "我能告诉你：当前做什么、未来要什么、里程碑、验收、优先级与风险（目标·方向）。"
            }
            总纲::经历 => "我能告诉你：发生过什么、教训、决策、来源、时间与归档（经历·历史）。",
        }
    }

    /// 返回该总纲下 6 个专属本质（§2.3 顺序固定）
    pub fn 所有本质(self) -> [本质; 每总纲本质数] {
        let 起点 = self as usize * 每总纲本质数;
        let mut arr = [本质::角色; 每总纲本质数];
        let mut i = 0;
        while i < 每总纲本质数 {
            arr[i] = 所有本质[起点 + i];
            i += 1;
        }
        arr
    }
}

