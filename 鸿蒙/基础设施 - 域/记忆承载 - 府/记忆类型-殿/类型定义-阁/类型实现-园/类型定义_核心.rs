/// 加载档位：决定漏掉后果严重度（02-概念/记忆 § 2.6.1）
///
/// 编译期固定，不可由 LLM 动态变更（必须走决策契约）。
/// 迁移后按总纲判定（格位 = 总纲 × 本质，阶段独立）：
/// - 规则、内部 → MUST（12 格位，必载）
/// - 目标、执行 → MIXED核心（12 格位，按任务条件载入）
/// - 外在、经历 → OPTIONAL（12 格位，按需载入）
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum 加载档位 {
    MUST,
    MIXED核心,
    OPTIONAL,
}

impl 加载档位 {
    pub fn 名称(self) -> &'static str {
        match self {
            加载档位::MUST => "MUST",
            加载档位::MIXED核心 => "MIXED",
            加载档位::OPTIONAL => "OPTIONAL",
        }
    }
}

/// 会话阶段（02-概念/记忆 § 2.6.3）
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 会话阶段 {
    开始,
    任务接收,
    实施,
    验收,
    故障,
}

/// 每个总纲的加载档位（6 总纲 → 3 档）
pub fn 格位_加载档位(总纲: 总纲) -> 加载档位 {
    match 总纲 {
        总纲::规则 | 总纲::内部 => 加载档位::MUST,
        总纲::目标 | 总纲::执行 => 加载档位::MIXED核心,
        总纲::外在 | 总纲::经历 => 加载档位::OPTIONAL,
    }
}

/// 加载档位硬约束（02-概念/记忆 § 2.6.4）
/// 加载档位变更须走决策契约（不可由 LLM 在会话中自行升降）
#[allow(non_snake_case)]
pub fn 改_加载档位(
    总纲: 总纲,
    新档位: 加载档位,
    decided_by: &str,
    决策ID: &str,
) -> Result<(), 错误> {
    if decided_by.is_empty() || 决策ID.is_empty() {
        return Err(错误::缺失决策者);
    }
    println!(
        "[加载档位变更] {}: {:?} → {:?} (decided_by={}, 决策ID={})",
        总纲.名称(),
        格位_加载档位(总纲),
        新档位,
        decided_by,
        决策ID
    );
    Ok(())
}

/// 拼全息图：按会话阶段 + 当前任务返回必拼 + 选拼条目
///
/// 行数硬约束：≤ 24（MUST 12 + MIXED核心 12 = 24 恰好封顶）
pub fn 拼全息图(
    _会话阶段: 会话阶段,
    任务: Option<&str>,
    候选条目: &[记忆条目],
) -> Vec<记忆条目> {
    let mut 选中: Vec<记忆条目> = Vec::new();

    // 第 1 步：全量加载 MUST（规则 + 内部 = 12 格位）
    for g in &所有格位 {
        if 格位_加载档位(g.总纲) == 加载档位::MUST {
            选中.extend(
                候选条目
                    .iter()
                    .filter(|e| e.总纲 == g.总纲 && e.本质 == g.本质)
                    .cloned(),
            );
        }
    }

    // 第 2 步：按任务相关度追加 MIXED 核心（目标 + 执行 = 12 格位）
    if let Some(_t) = 任务 {
        for e in 候选条目 {
            if 选中.iter().any(|x| x.id == e.id) {
                continue;
            }
            let 档位 = 格位_加载档位(e.总纲);
            if 档位 == 加载档位::MIXED核心 {
                选中.push(e.clone());
            }
        }
    }

    // 硬约束：≤ 24
    assert!(选中.len() <= 24, "全息图超载：{} > 24", 选中.len());
    选中
}

