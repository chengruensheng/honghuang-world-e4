#[cfg(test)]
mod 测试 {
    use super::*;
    use renwu_zhixing_fu::{任务, 角色分类};

    fn 测试任务(描述: &str) -> 任务 {
        任务 {
            标识: "test-001".to_string(),
            分类: 角色分类::道祖级,
            描述: 描述.to_string(),
            decided_by: "界主".to_string(),
        }
    }

    #[test]
    fn 四问题枚举完整() {
        assert_eq!(追问::所有().len(), 4);
    }

    #[test]
    fn 触发率大于60() {
        // 100 个任务，100% 触发（默认追问），应 >= 60%
        let 任务列表: Vec<任务> = (0..100).map(|i| 测试任务(&format!("任务 {}", i))).collect();
        let 率 = 追问引擎::触发率统计(&任务列表);
        assert!(率 >= 0.6, "触发率 {} 应 >= 0.6", 率);
    }

    #[test]
    fn 生成追问_目标关键词映射道二() {
        let 任务 = 测试任务("这是一个目标：实现新功能");
        let 决策 = 追问引擎::新建().生成追问(&任务);
        assert_eq!(决策.问题, 追问::道二);
        assert!(决策.触发原因.contains("目标"));
    }

    #[test]
    fn 生成追问_依赖关键词映射顺因() {
        let 任务 = 测试任务("此任务的依赖：需要前置 API 完成");
        let 决策 = 追问引擎::新建().生成追问(&任务);
        assert_eq!(决策.问题, 追问::顺因);
    }

    #[test]
    fn 生成追问_边界关键词映射有度() {
        let 任务 = 测试任务("约束：不要修改数据库 schema");
        let 决策 = 追问引擎::新建().生成追问(&任务);
        assert_eq!(决策.问题, 追问::有度);
    }

    #[test]
    fn 生成追问_停止关键词映射知止() {
        let 任务 = 测试任务("完成判据：所有测试通过");
        let 决策 = 追问引擎::新建().生成追问(&任务);
        assert_eq!(决策.问题, 追问::知止);
    }

    #[test]
    fn 生成追问_无关键词默认道二() {
        let 任务 = 测试任务("随便做点东西");
        let 决策 = 追问引擎::新建().生成追问(&任务);
        assert_eq!(决策.问题, 追问::道二); // 默认最高优先级
    }

    #[test]
    fn 道祖发追问_集成测试() {
        let 任务 = 测试任务("目标：实现追问引擎");
        let 决策 = 道祖发追问(&任务);
        assert_eq!(决策.问题, 追问::道二);
    }

    // ---------- 阶段 8 Day 3-4 投票测试 ----------

    #[test]
    fn 票3枚举() {
        assert_eq!(3, [票::赞成, 票::反对, 票::弃权].len());
    }

    #[test]
    fn 投票一致率_3全赞成() {
        let 引擎 = 投票引擎::新建();
        let v = 引擎.投票(vec![票::赞成, 票::赞成, 票::赞成]);
        assert_eq!(v.一致率, 100);
        assert!(!v.升级道祖终裁);
    }

    #[test]
    fn 投票一致率_2_1升级() {
        let 引擎 = 投票引擎::新建();
        let v = 引擎.投票(vec![票::赞成, 票::赞成, 票::反对]);
        assert_eq!(v.一致率, 66);
        assert!(v.升级道祖终裁, "66% < 70% 应升级");
    }

    #[test]
    fn 投票3不一致升级() {
        let 引擎 = 投票引擎::新建();
        let v = 引擎.投票(vec![票::赞成, 票::反对, 票::弃权]);
        assert_eq!(v.一致率, 33);
        assert!(v.升级道祖终裁);
    }

    #[test]
    fn Mock3LLM_一致任务_不升级() {
        let 引擎 = 投票引擎::新建();
        let v = 引擎.投票(Mock3LLM::投票_for("目标：新增功能", "task-001"));
        assert_eq!(v.一致率, 100);
        assert!(!v.升级道祖终裁);
    }

    #[test]
    fn Mock3LLM_不一致任务_升级() {
        let 引擎 = 投票引擎::新建();
        let v = 引擎.投票(Mock3LLM::投票_不一致());
        assert!(v.升级道祖终裁);
    }
}
