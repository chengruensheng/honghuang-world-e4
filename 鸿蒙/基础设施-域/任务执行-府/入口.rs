#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 四分类齐备() {
        let 所有 = [
            角色分类::道祖级,
            角色分类::圣人级,
            角色分类::准圣级,
            角色分类::大罗金仙级,
        ];
        assert_eq!(所有.len(), 4);
    }

    #[test]
    fn 角色卡必填decided_by() {
        let 卡 = 分类_角色卡(角色分类::道祖级);
        assert!(!卡.decided_by.is_empty());
    }

    // ---------- 4 张具体角色卡 ----------

    #[test]
    fn 道祖卡内容完整() {
        let 卡 = 分类_角色卡(角色分类::道祖级);
        assert_eq!(卡.名称, "道祖卡");
        assert!(卡.权限.contains(&"化要求".to_string()));
        assert!(卡.权限.contains(&"终裁".to_string()));
        assert_eq!(卡.LLM池, "化要求专用");
        assert!(卡.工具偏好.contains(&"追问引擎".to_string()));
    }

    #[test]
    fn 圣人卡内容完整() {
        let 卡 = 分类_角色卡(角色分类::圣人级);
        assert_eq!(卡.名称, "圣人卡");
        assert!(卡.权限.contains(&"设计".to_string()));
        assert_eq!(卡.LLM池, "设计专用");
    }

    #[test]
    fn 准圣卡内容完整() {
        let 卡 = 分类_角色卡(角色分类::准圣级);
        assert_eq!(卡.名称, "准圣卡");
        assert!(卡.权限.contains(&"验收".to_string()));
        assert_eq!(卡.LLM池, "验收专用");
    }

    #[test]
    fn 大罗卡内容完整() {
        let 卡 = 分类_角色卡(角色分类::大罗金仙级);
        assert_eq!(卡.名称, "大罗卡");
        assert!(卡.权限.contains(&"实现".to_string()));
        assert_eq!(卡.LLM池, "实现专用");
    }

    // ---------- 分类机械判定 ----------

    #[test]
    fn 机械判定完整任务通过() {
        let 任务 = 任务 {
            标识: "test-001".to_string(),
            分类: 角色分类::道祖级,
            描述: "测试任务".to_string(),
            decided_by: "界主".to_string(),
        };
        assert!(分类_机械判定(&任务, 角色分类::道祖级).is_ok());
    }

    #[test]
    fn 机械判定缺标识拒绝() {
        let 任务 = 任务 {
            标识: "".to_string(),
            分类: 角色分类::道祖级,
            描述: "测试".to_string(),
            decided_by: "界主".to_string(),
        };
        assert_eq!(
            分类_机械判定(&任务, 角色分类::道祖级),
            Err(错误::任务标识为空)
        );
    }

    #[test]
    fn 机械判定缺decided_by拒绝() {
        let 任务 = 任务 {
            标识: "t-1".to_string(),
            分类: 角色分类::道祖级,
            描述: "测试".to_string(),
            decided_by: "".to_string(),
        };
        assert_eq!(
            分类_机械判定(&任务, 角色分类::道祖级),
            Err(错误::decided_by为空)
        );
    }

    #[test]
    fn 机械判定分类不匹配拒绝() {
        let 任务 = 任务 {
            标识: "t-1".to_string(),
            分类: 角色分类::道祖级, // 任务分类 = 道祖
            描述: "测试".to_string(),
            decided_by: "界主".to_string(),
        };
        // 期望 = 圣人，实际 = 道祖 → 不匹配
        assert_eq!(
            分类_机械判定(&任务, 角色分类::圣人级),
            Err(错误::分类不匹配 {
                期望: 角色分类::圣人级,
                实际: 角色分类::道祖级
            })
        );
    }

    #[test]
    fn 四分类机械判定全通过() {
        for 分类 in [
            角色分类::道祖级,
            角色分类::圣人级,
            角色分类::准圣级,
            角色分类::大罗金仙级,
        ] {
            let 任务 = 任务 {
                标识: format!("t-{:?}", 分类),
                分类,
                描述: "测试".to_string(),
                decided_by: "界主".to_string(),
            };
            assert!(分类_机械判定(&任务, 分类).is_ok(), "{:?} 应通过", 分类);
        }
    }
}
