//! 任务状态 - 道祖级调度器的任务生命周期枚举
//!
//! 决策锚：v4 阶段 18 多 agent 协同
//! 关联文档：04-设计/接口契约/任务状态.md

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 任务状态 {
    待执行,
    执行中,
    已完成,
    失败,
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 测试_状态变体数匹配() {
        // 实际只验 enum 4 变体可枚举
        let _ = [
            任务状态::待执行,
            任务状态::执行中,
            任务状态::已完成,
            任务状态::失败,
        ];
        // 用数组长度验证 4 变体（stable 兼容）
        let _所有 = [
            任务状态::待执行,
            任务状态::执行中,
            任务状态::已完成,
            任务状态::失败,
        ];
        assert_eq!(_所有.len(), 4);
    }
}
