#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 五类工具ID齐备() {
        assert_eq!(工具ID::所有().len(), 5);
    }

    #[test]
    fn 默认注册表可注册五类真实工具() {
        let mut 注册表 = 工具注册表::新建();
        注册表.注册(工具ID::探查, Box::new(读文件工具::新建()));
        注册表.注册(工具ID::编辑, Box::new(写文件工具::新建()));
        注册表.注册(工具ID::执行, Box::new(执行命令工具::新建()));
        注册表.注册(工具ID::版本, Box::new(版本差异工具::新建()));
        注册表.注册(工具ID::编排, Box::new(编排工具::新建()));
        assert_eq!(注册表.数量(), 5, "五类工具应全部注册");
    }

    #[test]
    fn manifest五工具完整() {
        let m = 工具清单::manifest();
        assert_eq!(m.工具.len(), 5);
    }
}
