// 真实 LLM 集成测试 - 用环境变量 API key 直接调用
use moxing_fu::*;

fn main() {
    println!("=== 真实云端 LLM 端到端调用 ===");
    match 环境_配置_殿::环境_模型_阁::模型_配置_园::从环境变量构造() {
        Some(池) => {
            println!("✓ 从环境变量构造 4 分类池成功");
            for 名称 in &["道祖", "圣人", "准圣", "大罗"] {
                if let Some(配置) = 池.取(名称) {
                    println!("  {} -> 模型={}, 端点={}", 名称, 配置.模型, 配置.端点);
                }
            }
            // 调用 1 次真实 LLM
            println!("\n=== 调用 道祖级 真实 LLM ===");
            let 调用器 = LLM调用器::新建(池, HTTP连接::新建());
            let 请求 = 请求::新建(
                "",
                vec![
                    消息::系统("你是道祖级助手，简短回答。"),
                    消息::用户("用一句话介绍洪荒世界。"),
                ],
            );
            match 调用器.调用("道祖", &请求) {
                Ok(响应) => {
                    println!("✓ 真实调用成功！");
                    println!("响应内容: {}", 响应.内容);
                    println!(
                        "用量: 输入={} tokens, 输出={} tokens",
                        响应.用量_输入tokens, 响应.用量_输出tokens
                    );
                }
                Err(e) => {
                    println!("✗ 调用失败: {}", e);
                }
            }
        }
        None => {
            println!("✗ 未检测到 LLM_API_KEY 环境变量");
        }
    }
}
