//! 流水线驱动 - 府
//!
//! 4 阶段状态机：道祖级 → 圣人级 → 大罗金仙级 → 准圣级 → 道祖级。
//! 不可跳层（道祖不能直接验收）+ 不可反序（大罗不能先于圣人设计）。
//! 准圣打回 → 大罗重做循环 ≤ 3 轮后自动升级道祖终裁。
//!
//! 决策锚：260826-2210 4-分类抽象 § 流水线
//! 关联文档：02-概念/流水线/02-流水线.md

/// 流水线阶段（与 4 分类一一对应）
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum 阶段 {
    道祖,
    圣人,
    大罗,
    准圣,
}

/// 阶段跳转请求
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 跳转 {
    道祖终裁,
    圣人设计,
    大罗执行,
    准圣验收,
    大罗重做, // 准圣打回 → 大罗
    准圣复验, // 大罗重做 → 准圣
}

/// 给定当前阶段与请求跳转，返回合法下一阶段或 None（拒绝）
pub fn 下一阶段(当前: 阶段, 请求: 跳转) -> Option<阶段> {
    use 阶段::*;
    match (当前, 请求) {
        (道祖, 跳转::圣人设计) => Some(圣人),
        (圣人, 跳转::大罗执行) => Some(大罗),
        (大罗, 跳转::准圣验收) => Some(准圣),
        (准圣, 跳转::道祖终裁) => Some(道祖),
        (准圣, 跳转::大罗重做) => Some(大罗),
        (大罗, 跳转::准圣复验) => Some(准圣),
        // 跳层与反序：均拒绝（None）
        _ => None,
    }
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 顺向合法() {
        assert_eq!(下一阶段(阶段::道祖, 跳转::圣人设计), Some(阶段::圣人));
        assert_eq!(下一阶段(阶段::圣人, 跳转::大罗执行), Some(阶段::大罗));
        assert_eq!(下一阶段(阶段::大罗, 跳转::准圣验收), Some(阶段::准圣));
        assert_eq!(下一阶段(阶段::准圣, 跳转::道祖终裁), Some(阶段::道祖));
    }

    #[test]
    fn 跳层拒绝() {
        // 道祖直接验收 → 拒绝（跳层）
        assert_eq!(下一阶段(阶段::道祖, 跳转::准圣验收), None);
        // 圣人直接终裁 → 拒绝
        assert_eq!(下一阶段(阶段::圣人, 跳转::道祖终裁), None);
    }

    #[test]
    fn 反序拒绝() {
        // 大罗不能先于圣人设计
        assert_eq!(下一阶段(阶段::大罗, 跳转::圣人设计), None);
    }

    #[test]
    fn 打回回路() {
        assert_eq!(下一阶段(阶段::准圣, 跳转::大罗重做), Some(阶段::大罗));
        assert_eq!(下一阶段(阶段::大罗, 跳转::准圣复验), Some(阶段::准圣));
    }
}
