//! 流水线驱动 - 府
//!
//! 4 阶段状态机：道祖级 → 圣人级 → 大罗金仙级 → 准圣级 → 道祖级。
//! 不可跳层（道祖不能直接验收）+ 不可反序（大罗不能先于圣人设计）。
//! 准圣打回 → 大罗重做循环 ≤ 3 轮后自动升级道祖终裁。
//!
//! 决策锚：260826-2210 4-分类抽象 § 流水线
//! 关联文档：02-概念/流水线/02-流水线.md + 04-设计/状态机/01-流水线.md
//! falsifiable：4 分类机械判定覆盖率 = 100% + 跳层次数 = 0 + 反序次数 = 0

#![allow(non_snake_case)] // 任务ID 等字段名遵循中文命名

use std::collections::HashMap;

// ============================================================================
// 4 分类（与 renwu_zhixing_fu::角色分类 同步，阶段 3 任务可统一为单一来源）
// ============================================================================

/// 4 分类（接 260826-2210 4-分类抽象）
///
/// 命名约定：道祖级 = 决策 / 圣人级 = 设计 / 大罗金仙级 = 执行 / 准圣级 = 验收
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum 分类 {
    /// 决策：化要求 / 派遣 / 终裁 / 定档
    道祖级,
    /// 设计：设计 / 评审
    圣人级,
    /// 验收：六维验收 / 打回
    准圣级,
    /// 执行：按道分工
    大罗金仙级,
}

impl 分类 {
    pub fn 名称(self) -> &'static str {
        match self {
            分类::道祖级 => "道祖级",
            分类::圣人级 => "圣人级",
            分类::准圣级 => "准圣级",
            分类::大罗金仙级 => "大罗金仙级",
        }
    }
}

// ============================================================================
// 4 阶段（与 4 分类一一对应）
// ============================================================================

/// 流水线阶段（与 4 分类一一对应）
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum 阶段 {
    道祖,
    圣人,
    大罗,
    准圣,
}

impl 阶段 {
    pub fn 名称(self) -> &'static str {
        match self {
            阶段::道祖 => "道祖",
            阶段::圣人 => "圣人",
            阶段::大罗 => "大罗",
            阶段::准圣 => "准圣",
        }
    }
}

/// 阶段跳转请求
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 跳转 {
    道祖终裁,
    圣人设计,
    大罗执行,
    准圣验收,
    大罗重做, // 准圣打回 → 大罗
    准圣复验, // 大罗重做 → 准圣
}

// ============================================================================
// 4 分类 ↔ 4 阶段 映射
// ============================================================================

/// 分类 → 默认阶段（接单时按分类起跳）
pub fn 分类_默认阶段(分类: 分类) -> 阶段 {
    match 分类 {
        分类::道祖级 => 阶段::道祖,
        分类::圣人级 => 阶段::圣人,
        分类::准圣级 => 阶段::准圣,
        分类::大罗金仙级 => 阶段::大罗,
    }
}

/// 阶段 → 分类（反向映射）
pub fn 阶段_分类(阶段: 阶段) -> 分类 {
    match 阶段 {
        阶段::道祖 => 分类::道祖级,
        阶段::圣人 => 分类::圣人级,
        阶段::大罗 => 分类::大罗金仙级,
        阶段::准圣 => 分类::准圣级,
    }
}

// ============================================================================
// 跳层 / 反序 判定
// ============================================================================

/// 是否跳层：跳过至少 1 个中间正向阶段
///
/// 顺向一步：道祖→圣人 / 圣人→大罗 / 大罗→准圣 / 准圣→道祖（终裁）= 合法
/// 反向一步（打回回路）：准圣→大罗 / 大罗→准圣 = 合法
/// 跳层：跳过 ≥1 个阶段
///   - 道祖直接验收（道祖→准圣）
///   - 道祖直接执行（道祖→大罗）
///   - 圣人直接终裁（圣人→道祖）
///   - 圣人跳过执行（圣人→准圣）
///   - 大罗直接回到道祖（大罗→道祖）
pub fn is_跳层(从: 阶段, 到: 阶段) -> bool {
    use 阶段::*;
    if 从 == 到 {
        return false;
    }
    matches!(
        (从, 到),
        (道祖, 准圣) | (道祖, 大罗) | (圣人, 准圣) | (圣人, 道祖) | (大罗, 道祖)
    )
}

/// 是否反序：跳过中间正向阶段（不含打回回路）
///
/// 反序对：(大罗→圣人) 大罗重做时不应该回调设计阶段
/// 合法反向：仅 (准圣→大罗) 打回 + (大罗→准圣) 复验
pub fn is_反序(从: 阶段, 到: 阶段) -> bool {
    use 阶段::*;
    if 从 == 到 {
        return false;
    }
    // 显式枚举反序对
    matches!(
        (从, 到),
        (大罗, 圣人) |    // 大罗重做时不允许回调设计
        (准圣, 圣人) // 准圣不应回到设计阶段
    )
}

/// 综合判定：合法跳转（既非跳层也非反序）
pub fn is_合法跳转(从: 阶段, 到: 阶段) -> bool {
    !is_跳层(从, 到) && !is_反序(从, 到)
}

// ============================================================================
// 给定当前阶段与请求跳转，返回合法下一阶段或 None（拒绝）
// ============================================================================

pub fn 下一阶段(当前: 阶段, 请求: 跳转) -> Option<阶段> {
    use 阶段::*;
    match (当前, 请求) {
        (道祖, 跳转::圣人设计) => Some(圣人),
        (圣人, 跳转::大罗执行) => Some(大罗),
        (大罗, 跳转::准圣验收) => Some(准圣),
        (准圣, 跳转::道祖终裁) => Some(道祖),
        (准圣, 跳转::大罗重做) => Some(大罗),
        (大罗, 跳转::准圣复验) => Some(准圣),
        // 跳层与反序：均拒绝（None）
        _ => None,
    }
}

// ============================================================================
// 循环打回计数（任务级状态）
// ============================================================================

/// 任务级循环打回计数（HashMap 模拟阶段 5 内存状态；阶段 9+ 接 SQLite）
#[derive(Default)]
pub struct 循环打回状态 {
    打回计数: HashMap<String, u32>,
}

impl 循环打回状态 {
    pub fn 新建() -> Self {
        Self::default()
    }

    /// 增加打回计数；返回新的打回次数
    pub fn 增加打回(&mut self, 任务ID: &str) -> u32 {
        let 计数 = self.打回计数.entry(任务ID.to_string()).or_insert(0);
        *计数 += 1;
        *计数
    }

    /// 获取当前打回次数
    pub fn 打回次数(&self, 任务ID: &str) -> u32 {
        self.打回计数.get(任务ID).copied().unwrap_or(0)
    }

    /// 是否需要升级道祖终裁（≥3 轮时返回 true）
    pub fn 应升级道祖(&self, 任务ID: &str) -> bool {
        self.打回次数(任务ID) >= 3
    }

    /// 重置（任务完成时调用）
    pub fn 重置(&mut self, 任务ID: &str) {
        self.打回计数.remove(任务ID);
    }
}

