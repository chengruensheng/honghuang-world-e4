#[cfg(test)]
mod 测试 {
    use super::*;

    // ---------- 4 分类 ↔ 4 阶段 映射 ----------

    #[test]
    fn 分类_阶段_一一对应() {
        for 分类 in [分类::道祖级, 分类::圣人级, 分类::准圣级, 分类::大罗金仙级]
        {
            let 阶段 = 分类_默认阶段(分类);
            assert_eq!(阶段_分类(阶段), 分类);
        }
    }

    // ---------- 跳层判定 ----------

    #[test]
    fn 跳层道祖直接验收拒绝() {
        assert!(is_跳层(阶段::道祖, 阶段::准圣));
    }

    #[test]
    fn 跳层圣人直接终裁拒绝() {
        assert!(is_跳层(阶段::圣人, 阶段::道祖));
    }

    #[test]
    fn 跳层圣人跳到执行拒绝() {
        assert!(is_跳层(阶段::圣人, 阶段::准圣));
    }

    #[test]
    fn 顺向一步不算跳层() {
        assert!(!is_跳层(阶段::道祖, 阶段::圣人));
        assert!(!is_跳层(阶段::圣人, 阶段::大罗));
        assert!(!is_跳层(阶段::大罗, 阶段::准圣));
        assert!(!is_跳层(阶段::准圣, 阶段::道祖)); // 终裁
    }

    #[test]
    fn 打回一步不算跳层() {
        assert!(!is_跳层(阶段::准圣, 阶段::大罗));
        assert!(!is_跳层(阶段::大罗, 阶段::准圣));
    }

    // ---------- 反序判定 ----------

    #[test]
    fn 反序大罗回到圣人拒绝() {
        // 注：实际业务中允许（大罗重做后可能回调设计），但在标准流水线上为反序
        // 阶段5 暂定：打回回路只允许 准圣→大罗→准圣，不允许 大罗→圣人
        assert!(is_反序(阶段::大罗, 阶段::圣人));
    }

    #[test]
    fn 顺向合法() {
        assert_eq!(下一阶段(阶段::道祖, 跳转::圣人设计), Some(阶段::圣人));
        assert_eq!(下一阶段(阶段::圣人, 跳转::大罗执行), Some(阶段::大罗));
        assert_eq!(下一阶段(阶段::大罗, 跳转::准圣验收), Some(阶段::准圣));
        assert_eq!(下一阶段(阶段::准圣, 跳转::道祖终裁), Some(阶段::道祖));
    }

    #[test]
    fn 跳层拒绝() {
        // 道祖直接验收 → 拒绝（跳层）
        assert_eq!(下一阶段(阶段::道祖, 跳转::准圣验收), None);
        // 圣人直接终裁 → 拒绝
        assert_eq!(下一阶段(阶段::圣人, 跳转::道祖终裁), None);
    }

    #[test]
    fn 反序拒绝() {
        // 大罗不能先于圣人设计
        assert_eq!(下一阶段(阶段::大罗, 跳转::圣人设计), None);
    }

    #[test]
    fn 打回回路() {
        assert_eq!(下一阶段(阶段::准圣, 跳转::大罗重做), Some(阶段::大罗));
        assert_eq!(下一阶段(阶段::大罗, 跳转::准圣复验), Some(阶段::准圣));
    }

    // ---------- 循环打回计数 ----------

    #[test]
    fn 初始打回次数为0() {
        let 状态 = 循环打回状态::新建();
        assert_eq!(状态.打回次数("task-001"), 0);
        assert!(!状态.应升级道祖("task-001"));
    }

    #[test]
    fn 打回3次升级道祖() {
        let mut 状态 = 循环打回状态::新建();
        状态.增加打回("task-001");
        状态.增加打回("task-001");
        assert_eq!(状态.打回次数("task-001"), 2);
        assert!(!状态.应升级道祖("task-001"));
        状态.增加打回("task-001");
        assert_eq!(状态.打回次数("task-001"), 3);
        assert!(状态.应升级道祖("task-001"));
    }

    #[test]
    fn 任务完成后重置打回计数() {
        let mut 状态 = 循环打回状态::新建();
        状态.增加打回("task-001");
        状态.增加打回("task-001");
        状态.重置("task-001");
        assert_eq!(状态.打回次数("task-001"), 0);
    }

    #[test]
    fn 多任务打回计数独立() {
        let mut 状态 = 循环打回状态::新建();
        状态.增加打回("task-001");
        状态.增加打回("task-001");
        状态.增加打回("task-002");
        assert_eq!(状态.打回次数("task-001"), 2);
        assert_eq!(状态.打回次数("task-002"), 1);
    }
}
