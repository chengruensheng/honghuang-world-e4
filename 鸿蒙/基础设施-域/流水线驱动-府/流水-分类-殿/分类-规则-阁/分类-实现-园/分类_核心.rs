/// 角色卡（4 分类各 1 张，承接 01-哲学/01-世界观 § 4 分类角色卡）
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct 角色卡 {
    pub 分类: 分类,
    pub 职责: &'static str,
    pub llm_池_最小: u8,
    pub llm_池_最大: u8,
    pub 工具偏好: 工具偏好,
    pub 写权限: 写权限,
    pub decided_by: &'static str,
    pub 可证伪: &'static str,
    pub 文案: &'static str,
}

/// 路径前缀校验（验证分离：LLM 不直改文档）
///
/// 可写代码的实现者级也只允许写代码根（鸿蒙/证道/道韵/道果树），
/// 传承殿（文档/决策）永不直写；只读分类一律拒绝。
pub fn 路径可写(分类: 分类, 路径: &str) -> bool {
    if 分类.写权限() == 写权限::只读 {
        return false;
    }
    // 传承殿（文档/决策）永不直写（验证分离）
    if 路径.contains("/传承殿/") || 路径.contains("\\传承殿\\") {
        return false;
    }
    // 代码根按目录边界精确匹配，避免工作区名「洪荒 - 世界」的「世界」误判
    ["鸿蒙", "证道", "道韵", "道果树"]
        .iter()
        .any(|根| 路径.contains(&format!("/{}/", 根)) || 路径.contains(&format!("\\{}\\", 根)))
}

#[cfg(test)]
mod 测试 {
    use super::*;

    #[test]
    fn 分类写权限_仅大罗可写代码() {
        assert_eq!(分类::道祖级.写权限(), 写权限::只读);
        assert_eq!(分类::圣人级.写权限(), 写权限::只读);
        assert_eq!(分类::准圣级.写权限(), 写权限::只读);
        assert_eq!(分类::大罗金仙级.写权限(), 写权限::可写代码);
    }

    #[test]
    fn 写权限_两态名称与互异() {
        assert_eq!(写权限::只读.名称(), "只读");
        assert_eq!(写权限::可写代码.名称(), "可写代码");
        assert_ne!(写权限::只读, 写权限::可写代码);
    }

    #[test]
    fn 分类工具偏好_与写权限同构() {
        assert_eq!(分类::道祖级.工具偏好(), 工具偏好::读检索);
        assert_eq!(分类::圣人级.工具偏好(), 工具偏好::读检索);
        // 准圣级工具偏好=审计（F→E 协议 E盘侧挂接点：可调外部审计命令做确定性验收）
        assert_eq!(分类::准圣级.工具偏好(), 工具偏好::审计);
        assert_eq!(分类::大罗金仙级.工具偏好(), 工具偏好::写编辑执行);
    }

    #[test]
    fn 工具偏好_三态名称与互异() {
        assert_eq!(工具偏好::读检索.名称(), "读检索");
        assert_eq!(工具偏好::审计.名称(), "读检索+审计命令");
        assert_eq!(工具偏好::写编辑执行.名称(), "写编辑执行");
        assert_ne!(工具偏好::读检索, 工具偏好::写编辑执行);
        assert_ne!(工具偏好::审计, 工具偏好::写编辑执行);
        assert_ne!(工具偏好::审计, 工具偏好::读检索);
    }

    #[test]
    fn 路径可写_只读分类拒绝_大罗限代码根_文档永不直写() {
        // 只读分类一律拒绝
        assert!(!路径可写(分类::道祖级, "E:/洪荒 - 世界/鸿蒙/代码.rs"));
        assert!(!路径可写(分类::圣人级, "E:/洪荒 - 世界/证道/代码.rs"));
        assert!(!路径可写(分类::准圣级, "E:/洪荒 - 世界/道果树/代码.rs"));
        // 大罗可写代码根
        assert!(路径可写(
            分类::大罗金仙级,
            "E:/洪荒 - 世界/鸿蒙/代码.rs"
        ));
        assert!(路径可写(
            分类::大罗金仙级,
            "E:/洪荒 - 世界/道韵/代码.rs"
        ));
        // 传承殿文档永不直写（验证分离）
        assert!(!路径可写(
            分类::大罗金仙级,
            "E:/洪荒 - 世界/传承殿/03-决策/已定/文档.md"
        ));
        // 非代码根也不可写（Cargo.toml 在项目根，不含任何代码根词）
        assert!(!路径可写(分类::大罗金仙级, "E:/洪荒 - 世界/Cargo.toml"));
    }

    #[test]
    fn 角色卡_四分类_职责池权限可证伪对号() {
        let 道祖 = 分类::道祖级.角色卡();
        assert_eq!(道祖.职责, "化要求 / 派遣 / 终裁 / 定档");
        assert_eq!((道祖.llm_池_最小, 道祖.llm_池_最大), (2, 3));
        assert_eq!(道祖.写权限, 写权限::只读);
        assert!(道祖.可证伪.contains("通过"), "道祖可证伪含通过/打回");

        let 圣人 = 分类::圣人级.角色卡();
        assert_eq!(圣人.职责, "设计 / 评审");
        assert_eq!(圣人.llm_池_最小, 3);
        assert!(圣人.可证伪.contains("decided_by"), "圣人可证伪含决策锚");

        let 准圣 = 分类::准圣级.角色卡();
        assert!(准圣.职责.contains("验收"));
        assert!(准圣.可证伪.contains("逐项"), "准圣可证伪含逐项产出");

        let 大罗 = 分类::大罗金仙级.角色卡();
        assert_eq!(大罗.llm_池_最小, 1);
        assert_eq!(大罗.写权限, 写权限::可写代码);
        assert!(大罗.可证伪.contains("复现"), "大罗可证伪含可复现");
    }

    #[test]
    fn 角色卡_四分类互异() {
        let 道祖 = 分类::道祖级.角色卡();
        let 圣人 = 分类::圣人级.角色卡();
        let 准圣 = 分类::准圣级.角色卡();
        let 大罗 = 分类::大罗金仙级.角色卡();
        assert_ne!(道祖, 圣人);
        assert_ne!(圣人, 准圣);
        assert_ne!(准圣, 大罗);
        assert_ne!(道祖, 大罗);
    }
}
