/// 流水线阶段（与 4 分类一一对应）
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum 阶段 {
    道祖,
    圣人,
    大罗,
    准圣,
}

impl 阶段 {
    pub fn 名称(self) -> &'static str {
        match self {
            阶段::道祖 => "道祖",
            阶段::圣人 => "圣人",
            阶段::大罗 => "大罗",
            阶段::准圣 => "准圣",
        }
    }
}

/// 阶段跳转请求
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum 跳转 {
    道祖终裁,
    圣人设计,
    大罗执行,
    准圣验收,
    大罗重做, // 准圣打回 → 大罗
    准圣复验, // 大罗重做 → 准圣
}
