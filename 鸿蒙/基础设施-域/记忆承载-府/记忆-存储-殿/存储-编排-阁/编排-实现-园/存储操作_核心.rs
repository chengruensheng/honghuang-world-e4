    #[test]
    fn 全36格位全写入后检索命中() {
        let mut s = 内存存储::新建();
        let mut 写入数 = 0;
        for g in &所有格位 {
            let 内容 = match g.总纲 {
                总纲::内部 => format!("我是角色身份 {}", g.本质.名称()),
                总纲::外在 => format!("结构依赖目录 {}", g.本质.名称()),
                总纲::规则 => format!("必须禁止门禁 {}", g.本质.名称()),
                总纲::执行 => format!("命令构建技术栈 {}", g.本质.名称()),
                总纲::目标 => format!("目标未来阶段 {}", g.本质.名称()),
                总纲::经历 => format!("已发生历史教训 {}", g.本质.名称()),
            };
            match s.写入校验(
                g.总纲,
                g.本质,
                阶段::提案,
                档位::经档,
                来源::人类,
                内容,
                "摘要",
                "界主",
                "法",
            ) {
                Ok(_) => 写入数 += 1,
                Err(e) => panic!("写入失败 {:?}：{:?}", g, e),
            }
        }
        assert_eq!(写入数, 36);
        assert_eq!(s.查_全部().len(), 36);
        for g in &所有格位 {
            let 命中 = s.按格位(g.总纲, g.本质);
            assert_eq!(命中.len(), 1, "{:?} 应命中 1 条", g);
        }
    }
