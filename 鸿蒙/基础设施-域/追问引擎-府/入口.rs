/// 道祖入口：发追问 + 收追问答案
pub fn 道祖发追问(任务: &任务) -> 追问决策 {
    // 1. 任务分类机械判定（防缺字段）
    分类_机械判定(任务, 角色分类::道祖级).expect("道祖级判定通过");
    // 2. 触发追问
    let 引擎 = 追问引擎::新建();
    引擎.生成追问(任务)
}

