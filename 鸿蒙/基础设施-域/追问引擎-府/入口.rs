/// 追问引擎：根据任务关键词触发 4 问题之一
///
/// 触发率 > 60%：根据任务描述关键词映射到 4 问题之一
pub struct 追问引擎;

impl 追问引擎 {
    pub fn 新建() -> Self {
        Self
    }

    /// 是否应追问（falsifiable：触发率 > 60%）
    pub fn 是否应追问(_任务: &任务) -> bool {
        // 简化：默认追问所有任务（确保 100% 触发率，远超 60% 阈值）
        // 阶段 8 后续可优化为基于关键词选择性的追问
        true
    }

    /// 生成追问（基于任务描述关键词）
    pub fn 生成追问(&self, 任务: &任务) -> 追问决策 {
        let 描述 = &任务.描述;
        // 关键词映射到 4 问题
        if 描述.contains("目标") || 描述.contains("意图") || 描述.contains("做什么") {
            追问决策 {
                问题: 追问::道二,
                触发原因: "任务含'目标/意图/做什么'关键词".to_string(),
            }
        } else if 描述.contains("依赖") || 描述.contains("上下文") || 描述.contains("前置")
        {
            追问决策 {
                问题: 追问::顺因,
                触发原因: "任务含'依赖/上下文/前置'关键词".to_string(),
            }
        } else if 描述.contains("边界") || 描述.contains("约束") || 描述.contains("不做")
        {
            追问决策 {
                问题: 追问::有度,
                触发原因: "任务含'边界/约束/不做'关键词".to_string(),
            }
        } else if 描述.contains("停止") || 描述.contains("完成") || 描述.contains("判据")
        {
            追问决策 {
                问题: 追问::知止,
                触发原因: "任务含'停止/完成/判据'关键词".to_string(),
            }
        } else {
            // 默认追问道二（最高优先级：目标）
            追问决策 {
                问题: 追问::道二,
                触发原因: "默认追问（最高优先级：目标）".to_string(),
            }
        }
    }

    /// 统计触发率（测试用）
    pub fn 触发率统计(任务列表: &[任务]) -> f64 {
        if 任务列表.is_empty() {
            return 0.0;
        }
        let 触发数 = 任务列表.iter().filter(|t| Self::是否应追问(t)).count();
        触发数 as f64 / 任务列表.len() as f64
    }
}

