/// 4 问题（道二 / 顺因 / 有度 / 知止）—— 02-概念/追问/05-追问.md
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum 追问 {
    /// 道二：目标是什么？确认意图
    道二,
    /// 顺因：依赖什么？上下文关系
    顺因,
    /// 有度：边界/约束是什么？
    有度,
    /// 知止：何时停止？终止条件
    知止,
}

impl 追问 {
    pub fn 名称(self) -> &'static str {
        match self {
            追问::道二 => "道二",
            追问::顺因 => "顺因",
            追问::有度 => "有度",
            追问::知止 => "知止",
        }
    }
    pub fn 问题(self) -> &'static str {
        match self {
            追问::道二 => "目标是什么？请用一句话描述。",
            追问::顺因 => "依赖什么？前置/上下游是什么？",
            追问::有度 => "边界/约束是什么？什么不做？",
            追问::知止 => "何时停止？完成判据是什么？",
        }
    }
    pub fn 所有() -> [追问; 4] {
        [追问::道二, 追问::顺因, 追问::有度, 追问::知止]
    }
}

/// 追问决策
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct 追问决策 {
    pub 问题: 追问,
    pub 触发原因: String,
}

// ============================================================================
// 追问引擎
