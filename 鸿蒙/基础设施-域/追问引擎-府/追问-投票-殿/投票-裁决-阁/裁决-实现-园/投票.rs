// ============================================================================

/// 票（赞成/反对/弃权）
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum 票 {
    赞成,
    反对,
    弃权,
}

impl 票 {
    pub fn 名称(self) -> &'static str {
        match self {
            票::赞成 => "赞成",
            票::反对 => "反对",
            票::弃权 => "弃权",
        }
    }
}

/// 投票结果
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct 投票 {
    pub 票列表: Vec<票>,
    pub 一致率: u32,
    pub 最终决策: 票,
    pub 升级道祖终裁: bool,
}

impl 投票 {
    pub fn 最终决策名称(&self) -> &'static str {
        if self.升级道祖终裁 {
            "升级道祖终裁（未一致）"
        } else {
            self.最终决策.名称()
        }
    }
}

// ============================================================================
// 投票引擎
// ============================================================================

/// 投票引擎：3 mock LLM 独立判断 + 一致率 > 阈值
pub struct 投票引擎 {
    pub 阈值: u32, // 默认 70
}

impl 投票引擎 {
    pub fn 新建() -> Self {
        Self { 阈值: 70 }
    }

    pub fn 投票(&self, 票列表: Vec<票>) -> 投票 {
        assert_eq!(票列表.len(), 3, "投票必须 3 票");
        let 赞成 = 票列表.iter().filter(|t| **t == 票::赞成).count() as u32;
        let 反对 = 票列表.iter().filter(|t| **t == 票::反对).count() as u32;
        let 弃权数 = 票列表.iter().filter(|t| **t == 票::弃权).count() as u32;
        let 总 = 3u32;
        let (主流派, 主流数) = if 赞成 >= 反对 {
            (票::赞成, 赞成)
        } else {
            (票::反对, 反对)
        };
        let 一致率 = (主流数 * 100) / 总;
        let 升级道祖终裁 = 一致率 < self.阈值;
        投票 {
            票列表,
            一致率,
            最终决策: if 弃权数 == 3 {
                票::弃权
            } else {
                主流派
            },
            升级道祖终裁,
        }
    }
}

/// 3 mock LLM 投票生成（简化：所有任务一致赞成/手动可触发不一致）
pub struct Mock3LLM;
impl Mock3LLM {
    pub fn 投票_for(_任务描述: &str, _任务ID: &str) -> Vec<票> {
        vec![票::赞成, 票::赞成, 票::赞成]
    }
    pub fn 投票_不一致() -> Vec<票> {
        vec![票::赞成, 票::反对, 票::弃权]
    }
}
